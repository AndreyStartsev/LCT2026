"""Цитата доказательства записи по одному значению — со своей страницы (Р-159).

  python tests/test_evidence_quotes_159.py

У записей с одним значением стадии (`reconcile`) на все страницы доказательства ставилась одна цитата —
цитата самой плотной страницы. Если то же значение названо и на других страницах, у них цитата бывала
чужой: у PZ-009 Новослободской в РД на КЖ1.1.1 и КЖ1.1.2 (стр. 3) стояло «3. За относительную отметку
±0.000 … 159.95. 4. Все конструкции соприка…» из КЖ1.1.8, а на этих листах за пунктом идёт другой
(«4. Фундамент жилого до…») или сам пункт под другим номером («5. За относительную отметку…»).
Тексты ниже — сокращённые фрагменты этих страниц. У записей по элементам то же исправлял Р-158.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pipeline import matrix_rules as mr  # noqa: E402

PZ = ". За относительную отметку 0,000 принята абсолютная отметка 159,95 м., что соответствует отметке чистого пола"
KZH_118 = ". 3. За относительную отметку ±0.000 принята отметка чистого пола первого этажа, соответствующая " \
          "абсолютной отметке 159.95. 4. Все конструкции соприка"
KZH_111 = ". 3. За относительную отметку ±0.000 принята отметка чистого пола первого этажа, соответствующая " \
          "абсолютной отметке 159.95. 4. Фундамент жилого до"
KZH_112 = ". 5. За относительную отметку ±0.000 принята отметка чистого пола первого этажа, соответствующая " \
          "абсолютной отметке 159.95. 6. Все конструкции соп"
PZ009 = {"labels": [r"[±+]?0[.,]000[^;]{0,110}?абсолютн\w* отметк\w*"], "rule": "first", "kind": "elevation",
         "compare": {"type": "any_change"}, "implemented": True, "scope": "building"}


def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def cand(fid, page, value, snippet, document="КЖ.pdf", **extra):
    return {"value": value, "raw": f"{value:g}", "columns": [f"{value:g}"], "label": "отметка", "snippet": snippet,
            "file_id": fid, "page": page, "document": document, **extra}


def quotes_of(finding, stage):
    return [(e["file_id"], e["pdf_page_number"], e["quote"]) for e in finding["evidence"] if e["stage"] == stage]


def test_own_pages():
    """Одно значение на трёх листах: у каждого листа — его фрагмент, у самого плотного — цитата стороны."""
    print("\n1. Одно значение на разных страницах (PZ-009 Новослободской, РД)")
    cands = [cand("F0139", 4, 159.95, KZH_118, "КЖ1.1.8_Изм.1.pdf"), cand("F0140", 3, 159.95, KZH_111, "КЖ1.1.1.pdf"),
             cand("F0141", 3, 159.95, KZH_112, "КЖ1.1.2.pdf")]
    side = mr.reconcile(cands, {("F0139", 4): 2})
    ok = check("значение 159,95; цитата стороны — самой плотной страницы", side["value"] == 159.95
               and side["snippet"] == KZH_118, side["snippet"])
    ok &= check("у каждой страницы своя цитата",
                side["quotes"] == {("F0139", 4): KZH_118, ("F0140", 3): KZH_111, ("F0141", 3): KZH_112},
                str(side["quotes"]))
    ok &= check("страницы те же", side["pages"] == [("F0139", 4), ("F0140", 3), ("F0141", 3)], str(side["pages"]))
    return ok


def test_quote_choice():
    """На странице несколько кандидатов: значение выбранное, затем цитата стороны, затем порядок текста."""
    print("\n2. Какой кандидат страницы даёт цитату")
    cands = [cand("A", 1, 5, "таблица показателей: этажность 5"),
             # на второй странице первым по тексту идёт другое значение, затем два упоминания выбранного;
             # второе — та же фраза, что у стороны
             cand("B", 2, 7, "этажность секции 2 — 7"),
             cand("B", 2, 5, "в тексте записки: 5 этажей"),
             cand("B", 2, 5, "таблица показателей: этажность 5"),
             # на третьей — два упоминания, фразы стороны нет
             cand("C", 3, 5, "первое упоминание: 5 этажей"),
             cand("C", 3, 5, "второе упоминание: 5 этажей")]
    side = mr.reconcile(cands, {("A", 1): 6})
    ok = check("значение — 5, цитата стороны — таблицы", side["value"] == 5
               and side["snippet"] == "таблица показателей: этажность 5", side["snippet"])
    ok &= check("фраза стороны есть и на странице — у страницы она же",
                side["quotes"][("B", 2)] == "таблица показателей: этажность 5", side["quotes"][("B", 2)])
    ok &= check("фразы стороны на странице нет — первый по тексту кандидат с выбранным значением",
                side["quotes"][("C", 3)] == "первое упоминание: 5 этажей", side["quotes"][("C", 3)])
    ok &= check("кандидат другого значения цитату не даёт", "этажность секции 2 — 7" not in side["quotes"].values())
    return ok


def test_first_page():
    """Первая по порядку страница — не самая плотная: и у неё цитата своя, а не цитата стороны."""
    print("\n3. Первая страница доказательства — не самая плотная (PZ-009 Алтуфьевского, ПД)")
    # страницы доказательства идут по файлу и номеру, а цитата стороны — с самой плотной страницы: первой
    # шла стр. 6 СПОЗУ, а цитата стороны была со стр. 12, и на стр. 6 и в томе АР стояла фраза стр. 12
    cands = [cand("L0008", 6, 164.18, "За отметку 0,000 условно принята отметка чистого пола 1-го этажа, что "
                                      "соответствует абсолютной отметке 164,18.", "СПОЗУ (Изм.1).pdf"),
             cand("L0008", 12, 164.18, "За относительную отметку 0,000 (уровень чистого пола 1-го этажа) принята "
                                       "абсолютная отметка 164,18.", "СПОЗУ (Изм.1).pdf"),
             cand("L0010", 8, 164.18, "За условную проектную отметку 0,000 здания принята отметка чистого пола первого "
                                      "этажа, что соответствует абсолютной отметке 164,18.", "АР Изм. 1.pdf")]
    side = mr.reconcile(cands, {("L0008", 12): 4})
    ok = check("цитата стороны — со стр. 12, первая страница — стр. 6",
               side["snippet"].startswith("За относительную") and side["pages"][0] == ("L0008", 6), str(side["pages"]))
    ok &= check("у стр. 6 — её фраза, а не фраза стр. 12", side["quotes"][("L0008", 6)].startswith("За отметку 0,000 условно"),
                side["quotes"][("L0008", 6)])
    ok &= check("у тома АР — его фраза", side["quotes"][("L0010", 8)].startswith("За условную проектную"),
                side["quotes"][("L0010", 8)])
    ok &= check("у стр. 12 — цитата стороны", side["quotes"][("L0008", 12)] == side["snippet"])
    return ok


def test_findings():
    """Основной цикл находок: ПД, РД и ИД — у каждой страницы своя цитата; метка и значения прежние."""
    print("\n4. Запись PZ-009 целиком (основной цикл находок)")
    found = {"PZ-009": {
        "PD": [cand("F0101", 13, 159.95, PZ, "НВС-ПЗ.pdf")],
        "RD": [cand("F0139", 4, 159.95, KZH_118, "КЖ1.1.8_Изм.1.pdf"),
               cand("F0140", 3, 159.95, KZH_111, "КЖ1.1.1.pdf"),
               cand("F0141", 3, 159.95, KZH_112, "КЖ1.1.2.pdf")],
        "ID": [cand("I1", 2, 159.95, "исполнительная схема: отм. 0,000 = 159,95", "ИС-1.pdf"),
               cand("I2", 5, 159.95, "акт: отметка 0,000 соответствует 159,95", "АОСР-2.pdf")]}}
    density = {("F0139", 4): 2, ("I1", 2): 1}
    rules = {"parameters": {"PZ-009": PZ009}, "classes": {}, "location_defaults": {}}
    got, _ = mr.build_findings("OBJ-X", rules, collected=(found, density, 6))
    f = got[0]
    ok = check("нарушения нет, значения стадий те же", f["violation_label"] == "NO_VIOLATION"
               and f["pd_value"] == f["rd_value"] == f["id_value"], f"{f['violation_label']} {f['rd_value']}")
    ok &= check("РД: у КЖ1.1.1 и КЖ1.1.2 — свои пункты",
                quotes_of(f, "RD") == [("F0139", 4, KZH_118), ("F0140", 3, KZH_111), ("F0141", 3, KZH_112)],
                str(quotes_of(f, "RD")))
    ok &= check("ИД: у акта — фраза акта, а не исполнительной схемы",
                quotes_of(f, "ID") == [("I1", 2, "исполнительная схема: отм. 0,000 = 159,95"),
                                       ("I2", 5, "акт: отметка 0,000 соответствует 159,95")], str(quotes_of(f, "ID")))
    ok &= check("ПД: одна страница, цитата прежняя", quotes_of(f, "PD") == [("F0101", 13, PZ)])
    ok &= check("в пояснении записи цитат по страницам нет",
                "quotes" not in (f["extraction"].get("rd") or {}) and "quotes" not in (f["extraction"].get("id") or {}))
    return ok


def test_presence_and_plain():
    """Наличие систем — сводка названий на всех страницах, как прежде; сторона без цитат страниц — одна цитата."""
    print("\n5. Наличие систем и сторона без цитат страниц")
    cands = [cand("P", 3, 1.0, "водоотводные лотки вдоль проезда", columns=["лотки"]),
             cand("P", 8, 1.0, "пристенный дренаж по периметру", columns=["дренаж"])]
    side = mr.union_presence(mr.reconcile(cands, {}), cands)
    ok = check("цитата — сводка названий, цитат страниц у стороны нет",
               side["snippet"] == "названы: дренаж, лотки" and "quotes" not in side, side["snippet"])
    evidence = []
    mr.id_evidence({"value": 4, "raw": "4", "pages": [("I", 5), ("I", 6)], "snippet": "4 этажа"}, evidence)
    ok &= check("сторона без цитат страниц — одна цитата на все страницы",
                [e["quote"] for e in evidence] == ["4 этажа", "4 этажа"], str(evidence))
    return ok


