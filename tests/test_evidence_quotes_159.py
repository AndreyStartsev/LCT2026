    print("Цитата доказательства записи по одному значению — со своей страницы (Р-159)")
    results = [test_own_pages(), test_quote_choice(), test_first_page(), test_findings(), test_presence_and_plain()]
    print("\nИТОГ: " + ("все проверки пройдены" if all(results) else "есть сбои"))
