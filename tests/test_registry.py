def test_nfd():
    ok = True
    # macOS отдаёт имена в NFD: «й» и «ё» приходят буквой и отдельным знаком
    for path, expected in (
            ("Пример нарушений на чертежах/Рабочая и исполнительная документация/"
             "Исполнительный чертеж. План 1 этажа..pdf", "RD_ID_MIXED"),
            ("Пример нарушений на чертежах/ПД/2 Схема планировочной организации ЗУ/"
             "АНО1503211-П-ПЗУ.pdf", "PD"),
            ("Исполнительная съёмка/Съёмка фундаментной плиты.pdf", "ID"),
            ("Реестр исполнительной документации от 22.07.2026.docx", "ID"),
            ("Первый этап/23.009-Р-1-КЖ0.1.pdf", "RD")):
        nfd = unicodedata.normalize("NFD", path)
        got = guess_stage(nfd)
        ok &= check(f"NFD: {os.path.basename(path)}", nfd != path and got == expected,
                    "" if got == expected else f"{got} вместо {expected}")
    # В словах стадий нет «й» и «ё», поэтому сейчас ответ от NFD не зависит. Но без
    # приведения к NFC слово распадается на части, и первое же такое слово стадии
    # перестало бы находиться.
    words = registry._words(unicodedata.normalize("NFD", "Первый этап, съёмка"))
    ok &= check("слово с «й» и «ё» в NFD доходит до сравнения целым",
                words == ["первый", "этап", "съёмка"], str(words))
    # а в названиях разделов «й» есть: «пожарной безопасности»
    path = ("Пример нарушений на чертежах/ПД/9 Мероприятия по обеспечению пожарной безопасности/"
            "V2_01-09-00-01-14_Том 9.1.pdf.pdf")
    got = guess_section(unicodedata.normalize("NFD", path))
    ok &= check("NFD: раздел «пожарной безопасности»", got == "PB", "" if got == "PB" else f"{got} вместо PB")
    return ok


def test_manifest():
    # Официальные файлы берут стадию из реестра организатора, а не из пути. Но пути
    # у них настоящие и стадия проставлена организатором: это проверка на всём
    # корпусе, а не на примерах. Поиск подстрокой совпадал у 364 файлов из 416.
    with open(MANIFEST, encoding="utf-8") as f:
        rows = [json.loads(l) for l in f if l.strip()]
    wrong = [(r["file_id"], r["stage"], guess_stage(r["relative_path"])) for r in rows
             if guess_stage(r["relative_path"]) != r["stage"]]
    return check(f"стадия по пути совпала со стадией организатора: {len(rows) - len(wrong)} из {len(rows)}",
                 not wrong, str(wrong[:5]) if wrong else "")


