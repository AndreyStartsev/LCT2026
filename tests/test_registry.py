# конструкций. Остальные расхождения — тома, которым организатор поставил OTHER.
ORGANIZER_SECTION_ERRORS = {"F0209": "KR", "F0210": "KR"}


def test_section_manifest():
    with open(MANIFEST, encoding="utf-8") as f:
        rows = [json.loads(l) for l in f if l.strip()]
    got = {r["file_id"]: guess_section(r["relative_path"]) for r in rows}
    same = sum(got[r["file_id"]] == r["section"] for r in rows)
    # Раздел OTHER у организатора стоит и у томов ИОС Новослободской и Речникова,
    # и у «МОПБ»: там наш раздел конкретнее. Спорить с конкретным разделом организатора
    # можно только в проверенных случаях. Поиск подстрокой совпадал у 104 файлов из 416.
    contradicts = {r["file_id"]: got[r["file_id"]] for r in rows
                   if r["section"] != "OTHER" and got[r["file_id"]] != r["section"]}
    ok = check(f"раздел по пути совпал с разделом организатора: {same} из {len(rows)}", same >= 390)
    ok &= check("с конкретным разделом организатора расходятся только проверенные файлы",
                contradicts == ORGANIZER_SECTION_ERRORS, str(contradicts))
    return ok


def make_tree(root, files):
    for rel, content in files.items():
        path = os.path.join(root, *rel.split("/"))
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(content)


def fake_walk(reverse):
    """os.walk с заданным порядком каталогов, как у разных файловых систем.

    Как и настоящий os.walk сверху вниз, уважает изменение списка каталогов на месте.
    """
    def walk(top):
        names = sorted(os.listdir(top), reverse=reverse)
        dirnames = [n for n in names if os.path.isdir(os.path.join(top, n))]
        filenames = [n for n in names if not os.path.isdir(os.path.join(top, n))]
        yield top, dirnames, filenames
        for d in dirnames:
            yield from walk(os.path.join(top, d))
    return walk


def ids(rows):
    return {r["relative_path"]: r["file_id"] for r in rows}


def test_local_ids():
    ok = True
    files = {"Проектная документация/АР.xml": "ар", "Рабочая документация/КЖ.xml": "кж",
             "Исполнительная документация/Акт.xml": "акт"}
    with tempfile.TemporaryDirectory() as tmp:
        make_tree(tmp, files)
        registry.OBJECTS["TEST-OBJ"] = {"name": "тест", "root": tmp}
        try:
            real_walk, real_relpath, real_sep = registry.os.walk, registry.os.path.relpath, registry.os.sep
            try:
                registry.os.walk = fake_walk(reverse=False)
                first = registry.build("TEST-OBJ")
                registry.os.walk = fake_walk(reverse=True)
                second = registry.build("TEST-OBJ")
            finally:
                registry.os.walk = real_walk
            ok &= check("номера не зависят от порядка, в котором файловая система отдаёт каталоги",
                        ids(first) == ids(second), f"{ids(first)} против {ids(second)}")

            # Windows: системный разделитель — обратная косая черта
            try:
                registry.os.path.relpath = lambda p, r: real_relpath(p, r).replace("/", "\\")
                registry.os.sep = "\\"
                windows = registry.build("TEST-OBJ")
            finally:
                registry.os.path.relpath, registry.os.sep = real_relpath, real_sep
            ok &= check("пути записаны через «/» и на Windows",
                        all("\\" not in r["relative_path"] for r in windows),
                        str([r["relative_path"] for r in windows]))

            # прежний реестр раздал номера в другом порядке, как это было в Windows
            swapped = {"L0001": "L0003", "L0002": "L0001", "L0003": "L0002"}
            previous = [dict(r, file_id=swapped[r["file_id"]]) for r in first]
            again = registry.build("TEST-OBJ", previous=previous)
            ok &= check("номера из прежнего реестра сохраняются по содержимому файла",
                        ids(again) == ids(previous), f"{ids(again)}")

            make_tree(tmp, {"Рабочая документация/ВК.xml": "вк"})
            grown = registry.build("TEST-OBJ", previous=previous)
            new = ids(grown)["Рабочая документация/ВК.xml"]
            ok &= check("новый файл получает номер после наибольшего занятого", new == "L0004", new)
            ok &= check("номера прежних файлов при этом не сдвигаются",
                        all(ids(grown)[k] == v for k, v in ids(previous).items()))
        finally:
            registry.OBJECTS.pop("TEST-OBJ", None)
    return ok


