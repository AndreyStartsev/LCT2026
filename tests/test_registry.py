def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def stage_is(name, path, expected):
    got = guess_stage(path)
    return check(name, got == expected, "" if got == expected else f"{got} вместо {expected}")


def section_is(name, path, expected):
    got = guess_section(path)
    return check(name, got == expected, "" if got == expected else f"{got} вместо {expected}")


def section_hint_is(name, path, expected_hint):
    """Раздел не определён, но догадка записана: «ИОС5.N» без подсказки подраздела (#41)."""
    got, hint = section_with_hint(path)
    ok = got == "OTHER" and hint == expected_hint
    return check(name, ok, "" if ok else f"{got} и догадка {hint} вместо OTHER и {expected_hint}")


