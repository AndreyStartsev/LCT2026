"""Протоколы испытаний бетона как источник значения исполнительной документации. Задача #62.

  python tests/test_test_protocols.py

Первая часть — строки протоколов лаборатории «Паскаль» с Октябрьской, как их отдало
распознавание: конструкция и отметка в строке, класс без слова «бетон», «В. 25.» с точками.
Вторая — строки вне корпуса: другая лаборатория, другой порядок колонок, класс перед
конструкцией, строка без отметки, два класса в строке, не протокол вовсе. Парсер обязан
либо ответить верно, либо промолчать и назвать причину.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pipeline import elements, matrix_rules, test_protocols as tp  # noqa: E402
from pipeline.elements import ABOVEGROUND, UNDERGROUND  # noqa: E402

UNDER_V = "Вертикальные конструкции подземной части"
ABOVE_V = "Вертикальные конструкции надземной части"


def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def got(flat):
    found, skipped = tp.protocol_classes(flat)
    return {(f["location"], f["value"]) for f in found}, [why for why, _ in skipped]


FOOTER = " Исполнитель: Специалист по оформлению протоколов испытаний Хрусталева М.Н. Страница 2 из 2 Протокол № 1908-26"


def test_corpus_rows():
    print("\n1. Строки протоколов «Паскаль» (Октябрьская, распознанный текст)")
    ok = True
    # L0052 стр. 2: лестница с диапазоном отметок, класс «В. 25.» с точками, доли прочности нет
    page = ("Секция 1 с отм. +1.620 до | a |7| 15.06.2026 | 23.06.2026 |отм. +4.820 Лестница в/о Д 0,59 29,9 |'4.0 | 65 | ДА 23,9 В. 25. | 12-3 Мосбетон lies "
            "Секция 2 на отм. -5.850 $ 15.06.2026 | 23.06.2026 | фундаментная плита в/о Г- 0,59 32:7. 119 ДА | 26,1 B30 | 87% ee . : < \"Мосбетон\"" + FOOTER)
    found, skipped = got(page)
    ok &= check("лестница B25 и фундаментная плита B30 из двух строк", found == {("Лестницы", 25.0), ("Фундаментная плита", 30.0)}, str(found))
    ok &= check("страница опознана как протокол", tp.is_protocol_page(page))
    # L0052 стр. 1: заголовок строки перед датами, «В.К.» после класса, доля 80 %
    page = ("Протокол испытаний № 1908-26 от 24.06 Определение фактического класса бетона по прочности монолитных конструкций "
            "Уравнение стандартной градуировочной зависимости R=0,016*V-27,3 (для B7,5-B35) R=0,02*V-37,6 (для B35-B60) "
            "Завод-изготовитель бетонной смеси согласно заявки: ООО \"ТД \"Мосбетон\" B30 испытаний МПа m3 Результаты испытаний: "
            "Секция 1 на отм. +9.650 3410 000 \"ТД 15.06.2026 | 23.06.2026 0,59 29,9 4,6 | 6,5 23,9 B 30 80% ан В.К. в/о АЛ2 3560 23 | \"Мосбетон\" Страница 1 из2")
    found, skipped = tp.protocol_classes(page)
    ok &= check("«В.К.» на отм. +9.650 — вертикальные конструкции надземной части B30, доля 80 %",
                [(f["location"], f["value"], f.get("share")) for f in found] == [(ABOVE_V, 30.0, 80)], str(found))
    ok &= check("классы из шапки («для B7,5-B35», «Мосбетон B30») не взяты", len(found) == 1 and not skipped, str(skipped))
    # L0051 стр. 2: «BK.» латиницей, конструкция второй строки не распозналась
    page = ("екция 2 на отм. -5.250/- о 900: ТД 11.06.2026 | 23.06.2026 2.950 BK. plo A-T'/1-5 12 3780 0,59 33,5 4,4 | 6,5 | ДА 26,8 В 30 89% \"Мосбетон\" "
            "аркинг на отм. -5.25 3670 о 000 \"ТД 2| 14.06.2026 | 23.06.2026 а 3720 0,59 33,1 2,3 | 6,5 | ДА 26,5 B30 | 88% \"Мосбетон\"" + FOOTER)
    found, skipped = got(page)
    ok &= check("«BK.» латиницей на отм. -5.250 — подземная часть B30; строка без конструкции пропущена с причиной",
                found == {(UNDER_V, 30.0)} and skipped == ["конструкция в строке не прочитана"], str((found, skipped)))
    # L0054 стр. 2: плита перекрытия на отм. -0.200 — знак решает
    page = ("Секция | на отм. -0.200 3650 21.05.2026|23.06.2026 плита перекрытия в/о А-| 33 ak 35,3 2,3 32:7 B 30 109% B/8-14 3660" + FOOTER)
    found, skipped = got(page)
    ok &= check("плита перекрытия на отм. -0.200 — подземной части, 109 % прочности", found == {("Плиты перекрытия подземной части", 30.0)}, str(found))
    # L0056 стр. 2: слой сканера без колонок «прочность / класс / %»
    page = ("екция 2 на отм. \xad5.75 я 3800 \xad 34.1 1 20.06.2026 | 03.07.2026 В. К. в/о Ж\xadИ/1\xad2 13 3740 0,59 33 3853 1,9 | 6.5 | ДА 2 3720 32.8 "
            "екция 2 на отм. \xad5.25 2 | 20.06.2026 | 03.07.2026 В К в/о И/? 13 3700 0,59 325 32,7 2.3 | 6.5 | ДА 3750 333 Исполнитель: Страница 2 из 2 Протокол №2098\xad26")
    found, skipped = got(page)
    ok &= check("слой без колонки класса: две строки пропущены как «класс не прочитан», значений нет",
                found == set() and skipped == ["класс в строке не прочитан"] * 2, str((found, skipped)))
    return ok


def test_outside_rows():
    print("\n2. Строки вне корпуса")
    ok = True
    head = "ПРОТОКОЛ ИСПЫТАНИЙ № 17/25 определение прочности бетона монолитных конструкций ультразвуковым методом. "
    # другая лаборатория: класс до конструкции, отметка в конце строки, доля прочности с пробелом
    page = head + ("№ п/п | Дата бетонирования | Дата испытания | Проектный класс | Средняя прочность, МПа | Доля, % | Конструкция "
                   "1 | 03.04.2025 | 01.05.2025 | В25 | 33,4 | 104 % | стены подвала в осях 1-5 на отм. -3.300")
    found, skipped = got(page)
    ok &= check("класс перед конструкцией, доля с пробелом, «в осях» вместо «в/о» — стены подвала B25",
                found == {(UNDER_V, 25.0)} and not skipped, str((found, skipped)))
    # два класса в строке: по проекту и фактический
    page = head + "1 | 03.04.2025 | 01.05.2025 | колонны на отм. +3.300 в осях А-Б/1 | по проекту B30 | 27,4 | 91 % | фактический B25"
    found, skipped = got(page)
    ok &= check("два разных класса в строке — значения нет, причина названа",
                found == set() and skipped == ["в строке два разных класса — по проекту и фактический не различить"], str((found, skipped)))
    # стена без отметки: часть здания не определить
    page = head + "1 | 03.04.2025 | 01.05.2025 | стены в осях 1-5 | 33,4 | B25 | 104 %"
    found, skipped = got(page)
    ok &= check("стена без отметки — значения нет: часть здания не названа",
                found == set() and skipped == ["часть здания не названа: отметки в строке нет"], str((found, skipped)))
    # ростверк без отметки — зона ему не нужна
    page = head + "1 | 03.04.2025 | 01.05.2025 | ростверк Рм-1 в осях 3-4 | 31,0 | B25 | 97 %"
    found, skipped = got(page)
    ok &= check("ростверк без отметки берётся: часть здания ему не нужна", found == {("Ростверки", 25.0)}, str((found, skipped)))
    # класс без прочности рядом: обозначение системы вентиляции в той же строке
    page = head + "1 | 03.04.2025 | 01.05.2025 | плита перекрытия на отм. +6.600 у венткамеры В1 и В2 | 33,4 | 104 %"
    found, skipped = got(page)
    ok &= check("«В1», «В2» без прочности рядом — не класс, строка «класс не прочитан»",
                found == set() and skipped == ["класс в строке не прочитан"], str((found, skipped)))
    # ошибка распознавания в числе класса: «В З0» с буквой З
    page = head + "1 | 03.04.2025 | 01.05.2025 | фундаментная плита в осях 1-9 на отм. -6.900 | 35,2 | В З0 | 117 %"
    found, skipped = got(page)
    ok &= check("«В З0» с буквой вместо цифры — класс не определён", found == set() and skipped == ["класс в строке не прочитан"], str((found, skipped)))
    # бетонная подготовка в протоколе — не несущая конструкция
    page = head + "1 | 03.04.2025 | 01.05.2025 | бетонная подготовка под плиту на отм. -7.100 | 11,2 | B7,5 | 149 %"
    found, skipped = got(page)
    ok &= check("подготовка B7,5 — не элемент Матрицы", found == set(), str((found, skipped)))
    # не протокол: документ о качестве смеси с процентами рядом с классом
    page = "Документ о качестве бетонной смеси заданного качества партии № 40390 БСТ В30 П4 F150 W6, доля песка 42 %, фундаментная плита"
    found, skipped = got(page)
    ok &= check("документ о качестве — не протокол: построчный разбор молчит", found == set() and not skipped and not tp.is_protocol_page(page))
    # заключение протокола другой лаборатории: класс назван словами, а не колонкой
    page = ("ПРОТОКОЛ ИСПЫТАНИЙ № ЗАТ-1 от 16.10.2024 5. Место проведения испытаний: Вертикальные конструкции "
            "Парапет в/о 2/16-2/23 на отм. +49,150/+49,750 6. Наименование материала: Бетон B30 по ГОСТ 26633-2015 "
            "13. Заключение: По результатам проведенных испытаний в возрасте 7 суток установлено, что фактический "
            "класс бетона находится в диапазоне Вф=21,9-22, что соответствует 73-73% от проектного класса бетона "
            "по прочности на сжатие B30. 17% Выполнил: Инженер-лаборант")
    found, skipped = tp.protocol_classes(page)
    ok &= check("форма «СтройЭксперта»: парапет отнесён к вертикальным конструкциям надземной части B30, доля 73 %, 7 суток, Вф=21,9-22",
                [(f["location"], f["value"], f.get("share"), f.get("age_days"), f.get("vf")) for f in found]
                == [(ABOVE_V, 30.0, 73, 7, "21,9-22")] and not skipped, str((found, skipped)))
    # диапазон отметок через ноль: часть здания не определить
    page = head + "1 | 03.04.2025 | 01.05.2025 | стены лестничной клетки с отм. -3.300 до отм. +3.300 в осях А/1 | 33,4 | B25 | 104 %"
    found, skipped = got(page)
    ok &= check("диапазон через ноль — часть здания не названа", found == set() and skipped == ["часть здания не названа: отметки в строке нет"], str((found, skipped)))
    return ok


def test_zone_and_rules():
    print("\n3. Знак отметки в общем разборе и путь через правила")
    ok = True
    ok &= check("«на отм. +6,290» — надземная часть", elements.zone_of("Стены на отм. +6,290") == ABOVEGROUND)
    ok &= check("«с отм. +9,880 до +23,240» — надземная часть", elements.zone_of("тип. эт с отм. +9,880 до +23,240") == ABOVEGROUND)
    ok &= check("«на отм. -5.250» — подземная часть", elements.zone_of("Паркинг на отм. -5.250") == UNDERGROUND)
    got_ = {(c["location"], c["value"]) for c in elements.concrete_classes("Стены на отм. +6,290 ГОСТ 26633-2015 Бетон В30 42 м3")}
    ok &= check("класс стен на отм. +6,290 идёт только в надземную часть", got_ == {(ABOVE_V, 30.0)}, str(got_))
    rule = {"kind": "element_class"}
    page = ("Секция 2 на отм. -5.850 $ 15.06.2026 | 23.06.2026 | фундаментная плита в/о Г- 0,59 32:7. 119 ДА | 26,1 B30 | 87% \"Мосбетон\"" + FOOTER)
    cands = matrix_rules.extract(rule, page, doc={"stage": "ID", "relative_path": "ИД/Протокол 1908-26.pdf"})
    ok &= check("правило на странице ИД берёт строку протокола: локация, CLAUSE, источник PROTOCOL",
                [(c["location"], c["raw"], c["binding"], c.get("source")) for c in cands] == [("Фундаментная плита", "B30", "CLAUSE", "PROTOCOL")], str(cands))
    cands = matrix_rules.extract(rule, page, doc={"stage": "RD", "relative_path": "РД/КЖ.pdf"})
    ok &= check("та же страница в рабочей стадии — не протокол: класса без слова «бетон» нет", cands == [], str(cands))
    built = matrix_rules.reconcile_set(rule, [dict(c, stage="ID", file_id="L1", page=2, document="Протокол 1908-26.pdf") for c in cands or
                                              matrix_rules.extract(rule, page, doc={"stage": "ID", "relative_path": "x.pdf"})], by_registry=True)
    ok &= check("сторона ИД помнит число строк протокола", built and built.get("protocol_rows") == 1 and built["raw"] == "B30", str(built))
    ok &= check("пояснение находки называет источник", matrix_rules.protocol_note(built) == "значение исполнительной стадии — из протоколов испытаний бетона (1 строка)",
                str(matrix_rules.protocol_note(built)))
    return ok


def main():
    ok = True
    for fn in (test_corpus_rows, test_outside_rows, test_zone_and_rules):
        ok &= fn()
    print("\nИТОГ:", "все проверки пройдены" if ok else "ЕСТЬ СБОИ")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
