def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def test_repair():
    """Испорченный блок читается, целый текст не меняется."""
    ok = True
    fixed, n = encoding.repair(BROKEN)
    ok &= check("«Äîêóìåíò çàðåãèñòðèðîâàí» → «Документ зарегистрирован»",
                "Документ зарегистрирован" in fixed, fixed[:60])
    ok &= check("починенных слов посчитано", n >= 2, str(n))
    ok &= check("дата и номер целы", "12.05.2021" in fixed and "16-13-2395/21" in fixed, fixed)
    same, n_good = encoding.repair(GOOD)
    ok &= check("правильная кириллица не тронута", same == GOOD and n_good == 0, same)
    return ok


def test_mixed():
    """Слово за словом: в перемешанной строке починены только испорченные слова."""
    ok = True
    fixed, n = encoding.repair(MIXED)
    ok &= check("«äî» → «до», «âûøå» → «выше»", "до" in fixed.split() and "выше" in fixed.split(), fixed)
    ok &= check("целое слово «волновой» уцелело", "волновой" in fixed, fixed)
    ok &= check("числа уцелели", "600 600" in fixed, fixed)
    ok &= check("починено не больше, чем испорчено", 0 < n <= 4, str(n))
    return ok


def test_threshold():
    """Одно слово похоже на кириллицу случайно: порог не даёт чинить латиницу.

    В корпусе латиницей набраны марки и обозначения («Àl», «Ìax»), и одиночное
    преобразование там даёт слово-мусор. Починка требует, чтобы в тексте нашлось
    не меньше двух слов, которые после преобразования стали кириллицей.
    """
    ok = True
    one = "Òèï"                     # одно слово: ниже порога
    fixed, n = encoding.repair(one)
    ok &= check("одно слово не чинится", fixed == one and n == 0, fixed)
    two, n2 = encoding.repair("Òèï êðîâëè")
    ok &= check("два слова чинятся", "Тип кровли" in two and n2 == 2, two)
    ok &= check("латиница не признаётся испорченной",
                encoding.repair("Concrete class B25 GOST")[1] == 0)
    return ok


def test_looks_broken():
    """Признак «страница в неверной кодировке» отделяет её от обычной."""
    ok = True
    ok &= check("испорченная страница распознана", encoding.looks_broken(BROKEN))
    ok &= check("обычная страница не помечена", not encoding.looks_broken(GOOD))
    return ok


def test_single_letters():
    """Р-140: предлоги, союзы и буквы у чисел чинятся там, где кодировка уже доказана словами."""
    ok = True
    fixed, n = encoding.repair(SLABS)
    ok &= check("общие указания КЖ4.1 читаются целиком", fixed == SLABS_FIXED, fixed)
    ok &= check("«Â25W4F75» → «В25W4F75», «Â35» → «В35»", "класса В25W4F75" in fixed and "прочности В35" in fixed)
    ok &= check("«ñ отм.» → «с отм.», «4-го è выше» → «4-го и выше»",
                "перекрытия с отм.+10,400" in fixed and "4-го и выше" in fixed)
    ok &= check("одиночные буквы посчитаны в починенных словах", n > len(encoding.SUSPECT_RE.findall(SLABS)), str(n))
    spec = encoding.repair(SPEC)[0]
    ok &= check("«Áåòîí Â25» → «Бетон В25», «ì³» → «м³»", "Бетон В25 F75 W4" in spec and "7,91 м³" in spec, spec)
    legend = encoding.repair(LEGEND)[0]
    ok &= check("условные обозначения: буквы отдельными строками",
                legend.startswith("В\nВ\nдо 600\n600 и выше\nС\nС\nД\nД\nК\nК\nк.ТВ\n1к.ДС\nк.МПС")
                and "\nх\nх\nБ.Д.\n" in legend, legend)
    return ok


def test_single_letters_safe():
    """Одна буква сама по себе ничего не доказывает: латиница, знаки и шум остаются как были."""
    ok = True
    fixed = encoding.repair(DIAMETER)[0]
    ok &= check("знак диаметра цел, «À500Ñ» → «А500С», «200õ200» → «200х200»",
                fixed == "47х200=9400\nОсновное верхнее/нижнее армирование\nØ10 А500С, ячейка 200х200мм", fixed)
    mixed = encoding.repair(TIMES + "\n" + STAMP)[0]
    ok &= check("на испорченной странице «100×100×55» не тронуто, «Ïîäï. è äàòà» → «Подп. и дата»",
                TIMES in mixed and "Подп. и дата" in mixed, mixed)
    for name, text in (("португальский", PORTUGUESE), ("французский", FRENCH)):
        ok &= check(f"{name} текст не тронут: «é» и «à» здесь слова", encoding.repair(text)[0] == text)
    glued = "informações, instruções, soluções, condições, opções: é importante"
    ok &= check("серии внутри латинских слов кодировку не доказывают", not encoding.letters_allowed(glued))
    ok &= check("целые испорченные слова доказывают", encoding.letters_allowed(STAMP))
    ok &= check("слой сканера с мусором не тронут", encoding.repair(NOISE)[0] == NOISE)
    ok &= check("отдельное слово «ё» не чинится: это кусок скобки формульного шрифта",
                "\n¸\n" in encoding.repair(STAMP + "\n¸\n¨\n")[0])
    return ok


def test_concrete_class():
    """«Â» вплотную перед классом бетона чинится и без счёта слов; прочие «Â» — только со счётом."""
    ok = True
    # строка собрана руками: в корпусе «Â25» стоит только на страницах, где испорчены и слова
    ok &= check("«Бетон Â25» → «Бетон В25»", encoding.repair("Бетон Â25 F75 W4")[0] == "Бетон В25 F75 W4")
    ok &= check("«Â7,5» и «Â22.5W6» — классы", encoding.repair("Â7,5 и Â22.5W6")[0] == "В7,5 и В22.5W6")
    for text in ("Â 25", "Â\xa025", "Â350", "Â1.520", "ÂÂ25"):
        ok &= check(f"«{text!r}» без счёта слов не чинится", encoding.repair(text)[0] == text)
    ok &= check("класс бетона признаётся испорченным текстом", encoding.looks_broken("Бетон Â25"))
    return ok


def test_words_follow_page():
    """Слова страницы по одному чинятся теми же решениями, что и её текст (`repair_words`)."""
    ok = True
    for name, text in (("общие указания", SLABS), ("спецификация", SPEC), ("шум", NOISE),
                       ("два слова", "Òèï êðîâëè ñ"), ("класс бетона", "Бетон Â25 F75")):
        words = text.split()
        got = " ".join(encoding.repair_words(words, text))
        ok &= check(f"{name}: слова совпали с текстом страницы", got == " ".join(encoding.repair(text)[0].split()), got)
    return ok


