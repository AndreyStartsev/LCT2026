"""Проверка разбора экспликаций: форма номера помещения выводится из столбца. Задача #41.

  python tests/test_rooms.py

В корпусе номера помещений — две-три цифры («012», «140»), и разбор был написан под них.
У другого застройщика нумерация другая: «1.01» поэтажная, «2.3.1» с секцией, «А101»
с литерой корпуса, «1.1-4» с номером блока, просто «7» и «1001». Здесь собраны такие
экспликации из слов с координатами — так же, как их отдаёт чтение страницы.

Отдельно проверяется, что нумерация строк таблицы («№ п/п» в балансе площадей)
помещениями не становится и что неразобранные строки попадают в счёт.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pipeline import rooms  # noqa: E402

TEXT = "Экспликация помещений Наименование Площадь, м2"
# столбец номеров стоит слева от шапки «Наименование» не дальше 0,09 доли листа
NUM_X, NAME_X, AREA_X = 0.13, 0.20, 0.36


def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def word(t, x, y, w=0.08):
    return {"t": t, "bbox": [x, y, x + w, y + 0.01]}


def explication(rows, number_header=("Номер", "поме", "щения"), x0=None):
    """Слова экспликации: шапка и строки «номер — наименование — площадь».

    x0 сдвигает всю таблицу вправо: так на листе получаются две таблицы бок о бок.
    """
    num_x = NUM_X if x0 is None else x0
    name_x = num_x + (NAME_X - NUM_X)
    area_x = num_x + (AREA_X - NUM_X)
    words = [word(t, num_x + i * 0.02, 0.10, 0.015) for i, t in enumerate(number_header)]
    words += [word("Наименование", name_x, 0.10), word("Площадь", area_x, 0.10)]
    for i, (num, name, area) in enumerate(rows):
        y = 0.16 + i * 0.03
        words.append(word(num, num_x, y, 0.04))
        words += [word(part, name_x + j * 0.05, y) for j, part in enumerate(name.split())]
        words.append(word(area, area_x, y))
    return words


def numbers(rows, header=("Номер", "поме", "щения")):
    got, _ = rooms.parse_page_full(explication(rows, header), TEXT)
    return [r["number"] for r in got]


def test_corpus_format():
    ok = True
    got = numbers([("012", "Венткамера", "99.7"), ("013", "Коридор", "12.5"), ("014", "Тамбур", "6.0")])
    ok &= check("привычные номера корпуса разбираются как раньше", got == ["012", "013", "014"], str(got))
    got, stats = rooms.parse_page_full(explication([("012", "Венткамера", "99.7")]), "просто текст страницы")
    ok &= check("страница без признаков экспликации не разбирается", got == [] and stats["rows"] == 0)
    return ok


def test_foreign_formats():
    ok = True
    cases = [
        ("поэтажная нумерация «1.01»", [("1.01", "Прихожая", "8.2"), ("1.02", "Кухня", "14.5"),
                                        ("1.03", "Санузел", "4.1")], ["1.01", "1.02", "1.03"]),
        ("секция и этаж «2.3.1»", [("2.3.1", "Холл", "18.0"), ("2.3.2", "Коридор", "22.4"),
                                   ("2.3.3", "Кладовая", "5.6")], ["2.3.1", "2.3.2", "2.3.3"]),
        ("литера корпуса «А101»", [("А101", "Вестибюль", "40.2"), ("А102", "Гардероб", "25.0"),
                                   ("А103", "Охрана", "9.8")], ["А101", "А102", "А103"]),
        ("номер блока «1.1-4»", [("1.1-4", "Офис", "33.0"), ("1.1-5", "Переговорная", "17.2"),
                                 ("1.1-6", "Серверная", "11.4")], ["1.1-4", "1.1-5", "1.1-6"]),
        ("однозначные номера «7»", [("7", "Спальня", "16.0"), ("8", "Гостиная", "24.3"),
                                    ("9", "Кухня", "12.1")], ["7", "8", "9"]),
        ("четырёхзначные номера «1001»", [("1001", "Палата", "18.5"), ("1002", "Ординаторская", "21.0"),
                                          ("1003", "Процедурная", "15.7")], ["1001", "1002", "1003"]),
    ]
    for name, rows, expected in cases:
        got = numbers(rows)
        ok &= check(name, got == expected, "" if got == expected else str(got))
    return ok


def test_not_rooms():
    ok = True
    # баланс площадей: в столбце нумерация строк, подпись «№ п/п», помещений здесь нет
    got = numbers([("1", "Площадь участка", "1401.0"), ("2", "Площадь застройки", "767.0"),
                   ("3", "Площадь озеленения", "153.9")], header=("№", "п/п"))
    ok &= check("нумерация строк под подписью «№ п/п» помещениями не становится", got == [], str(got))
    # спецификация: «80-6.3» — диаметр и давление, столбец не назван номерами помещений
    got = numbers([("80-6.3", "Задвижка стальная", "12.0"), ("80-50", "Задвижка чугунная", "8.0"),
                   ("40-1.0", "Кран шаровой", "3.0")], header=("Поз.", "обозн"))
    ok &= check("столбец без подписи «номер помещения» чужие формы не учит", got == [], str(got))
    # одиночная чужая форма не принимается: повтор отличает нумерацию от случайности
    got = numbers([("001", "Тепловой пункт", "35.0"), ("002", "Коридор", "12.0"),
                   ("003", "Тамбур", "6.0"), ("0011", "Лестница", "26.5")])
    ok &= check("одиночная чужая форма в столбце номером не становится",
                got == ["001", "002", "003"], str(got))
    # а повторяющаяся — становится: у Тюменской-5 экспликация продолжается 0010, 0011, 0012
    got = numbers([("009", "Тепловой пункт", "35.0"), ("0010", "Коридор", "12.0"),
                   ("0011", "Лестница", "26.5"), ("0012", "Венткамера", "82.4")])
    ok &= check("повторяющаяся чужая форма принимается",
                got == ["009", "0010", "0011", "0012"], str(got))
    return ok


def test_row_without_area():
    """Строка без площади — тоже помещение: «147 Лаборантская» (#15)."""
    ok = True
    rows = [("1.01", "Прихожая", "8.2"), ("1.02", "Кухня", "14.5"), ("1.03", "Санузел", "4.1")]
    words = explication(rows)
    y = 0.16 + len(rows) * 0.03
    words += [word("1.04", NUM_X, y, 0.04), word("Балкон", NAME_X, y)]
    got, stats = rooms.parse_page_full(words, TEXT)
    ok &= check("строка без площади стала записью",
                [r["number"] for r in got] == ["1.01", "1.02", "1.03", "1.04"], str([r["number"] for r in got]))
    ok &= check("площадь у неё пустая", got[-1]["area_m2"] is None and got[-1]["name"] == "Балкон")
    ok &= check("неразобранных строк нет", stats["rows"] == 4 and stats["unparsed"] == 0, str(stats))
    ok &= check("формы номеров названы", stats["shapes"] == ["9.99"], str(stats["shapes"]))
    # строка без номера записью не становится и попадает в счёт только если номер есть
    words += [word("Продолжение", NAME_X, y + 0.03)]
    got, stats = rooms.parse_page_full(words, TEXT)
    ok &= check("строка без номера записью не становится", len(got) == 4 and stats["rows"] == 4, str(stats))
    return ok


def test_neighbour_table():
    """Слова соседней таблицы не затекают в наименование (#15)."""
    ok = True
    left = explication([("101", "Тамбур", "8.6"), ("102", "Вестибюль со стойкой", "134.0"),
                        ("103", "Санузел для посетителей", "5.0")])
    right = explication([("163", "Процедурный", "12.0"), ("164", "Кабинет врача", "18.0"),
                         ("165", "Туалет медблока", "4.2")], x0=0.55)
    got, _ = rooms.parse_page_full(left + right, TEXT)
    by = {r["number"]: r["name"] for r in got}
    ok &= check("разобраны обе таблицы", sorted(by) == ["101", "102", "103", "163", "164", "165"], str(sorted(by)))
    ok &= check("наименование своё, без слов соседней таблицы",
                by.get("102") == "Вестибюль со стойкой" and by.get("164") == "Кабинет врача", str(by))
    return ok


def test_title():
    """Столбец подписан одним словом «Номер», над таблицей — «Экспликация помещений» (#100)."""
    ok = True
    rows = [("135", "Гардероб персонала", "8,8"), ("145", "Помещение с холодильным оборудованием", "13,7")]
    words = explication(rows, ("Номер",))
    got, _ = rooms.parse_page_full(words, TEXT)
    ok &= check("без заголовка строки разобраны, но помещениями не помечены",
                [r["number"] for r in got] == ["135", "145"] and not any(r["labeled"] for r in got))
    titled = words + [word("Экспликация", NUM_X + 0.03, 0.08, 0.06), word("помещений", NUM_X + 0.10, 0.08, 0.06)]
    got, _ = rooms.parse_page_full(titled, TEXT)
    ok &= check("заголовок «Экспликация помещений» над шапкой — помечены", all(r["labeled"] for r in got), str(got))
    far = words + [word("Экспликация", NUM_X + 0.03, 0.02, 0.06), word("помещений", NUM_X + 0.10, 0.02, 0.06)]
    got, _ = rooms.parse_page_full(far, TEXT)
    ok &= check("заголовок далеко над таблицей — не её", not any(r["labeled"] for r in got))
    garbled = explication(rows, ("Ноиер",)) + [word("Экспликация", NUM_X + 0.03, 0.08, 0.06),
                                                word("помещений", NUM_X + 0.10, 0.08, 0.06)]
    got, _ = rooms.parse_page_full(garbled, TEXT)
    ok &= check("шапка столбца не читается — по одному заголовку не помечаем", not any(r["labeled"] for r in got))
    return ok


def revit(x0, y0, title, rows):
    """Спецификация помещений Revit: заголовок, шапка «Номер | Имя | Площадь», площадь с «м²» (#114).

    Подпись «Имя» стоит по центру столбца, наименования начинаются левее неё.
    """
    words = [word(w, x0 + i * 0.03, y0 - 0.012, 0.025) for i, w in enumerate(title.split())]
    words += [word("Номер", x0, y0, 0.01), word("Имя", x0 + 0.037, y0, 0.006), word("Площадь", x0 + 0.072, y0, 0.013)]
    for i, (num, name, area) in enumerate(rows):
        y = y0 + 0.012 * (i + 1)
        words.append(word(num, x0 + 0.004, y, 0.002))
        words += [word(part, x0 + 0.016 + j * 0.012, y, 0.01) for j, part in enumerate(name.split())]
        words += [word(area, x0 + 0.065, y, 0.006), word("м²", x0 + 0.075, y, 0.003)]
    return words


FLOOR_1 = [("1", "Зона мойки", "165.05"), ("2", "Зона выдачи", "69.10"), ("3", "Сан.узел МГН", "5.35"),
           ("4", "Сан.узел", "4.33"), ("23", "Помещение", "19.41"),
           ("А", "Лестничная клетка", "24.51"), ("Б", "Лестничный марш", "24.05")]


def test_revit():
    """Спецификации этажей Revit столбиком на одном листе, под ними чертёж (#114)."""
    ok = True
    words = revit(0.80, 0.125, "Спецификация помещений 1-го этажа", FLOOR_1)
    # обломок подписи у начала наименования — буква, но не в столбце номеров: номером не становится
    words.append(word("М", 0.814, 0.125 + 0.012 * 8, 0.002))
    # чертёж под таблицей: подписи фрагмента и метка помещения в полосе столбца номеров
    words += [word("1", 0.831, 0.546, 0.002), word(":", 0.834, 0.546, 0.002), word("50", 0.837, 0.546, 0.004),
              word("Зона", 0.84, 0.50, 0.01), word("12.40", 0.86, 0.50, 0.006)]
    words += revit(0.86, 0.62, "Спецификация помещений антресольного этажа",
                   [("1", "Тех.помещение", "11.33"), ("2", "Тех.помещение", "7.75")])
    text = "Спецификация помещений 1-го этажа Номер Имя Площадь"
    got, stats = rooms.parse_page_full(words, text)
    floor = [r for r in got if r["table"] == "Спецификация помещений 1-го этажа"]
    ok &= check("лестничные клетки с литерой «А», «Б» — помещения этажа, обломок «М» — нет",
                [r["number"] for r in floor][-2:] == ["А", "Б"] and "М" not in [r["number"] for r in got],
                str([r["number"] for r in floor]))
    ok &= check("строки этажа: номер, полное наименование, площадь",
                [(r["number"], r["name"], r["area_m2"]) for r in floor]
                == [(n, name, float(a)) for n, name, a in FLOOR_1], str([(r["number"], r["name"], r["area_m2"]) for r in floor]))
    ok &= check("однозначные номера под заголовком «Спецификация помещений» — помещения", all(r["labeled"] for r in floor))
    upper = [r for r in got if (r["table"] or "").startswith("Спецификация помещений антресольного")]
    ok &= check("таблица под таблицей — своя, номера «1» и «2» не съедены повтором",
                [(r["number"], r["name"]) for r in upper] == [("1", "Тех.помещение"), ("2", "Тех.помещение")], str(upper))
    ok &= check("подписи чертежа под таблицей в строки не попали", stats["rows"] == 9 and stats["unparsed"] == 0 and len(got) == 9, str(stats))
    alone = [word("Имя", 0.30, 0.30, 0.006), word("файла", 0.31, 0.30, 0.01), word("1", 0.29, 0.32, 0.002),
             word("Отчёт", 0.30, 0.32, 0.01), word("12.40", 0.33, 0.32, 0.006)]
    got, _ = rooms.parse_page_full(alone, text)
    ok &= check("«Имя» без «Номер» и «Площадь» в шапке — не экспликация", got == [], str(got))
    return ok


def test_tall_header():
    """Шапка в две строки: разрыв до первой строки таблицы её не обрывает (#114)."""
    rows = [("101", "Тамбур", "8.6"), ("102", "Вестибюль", "134.0"), ("103", "Санузел", "5.0"), ("104", "Кладовая", "3.1")]
    words = explication(rows)
    for w in words:
        if w["bbox"][1] > 0.12:
            w["bbox"][1] += 0.06
            w["bbox"][3] += 0.06
    got, _ = rooms.parse_page_full(words, TEXT)
    return check("строки после высокой шапки разобраны", [r["number"] for r in got] == ["101", "102", "103", "104"],
                 str([r["number"] for r in got]))


def main():
    ok = True
    for title, fn in (("Нумерация корпуса", test_corpus_format),
                      ("Нумерация вне корпуса", test_foreign_formats),
                      ("Не помещения", test_not_rooms),
                      ("Строка без площади", test_row_without_area),
                      ("Соседняя таблица", test_neighbour_table),
                      ("Заголовок экспликации", test_title),
                      ("Спецификация помещений Revit", test_revit),
                      ("Высокая шапка", test_tall_header)):
        print(f"\n{title}")
        ok &= fn()
    print("\nИТОГ:", "все проверки пройдены" if ok else "ЕСТЬ СБОИ")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
