"""Повысительные насосные установки: разбор и сравнение по правилу специалиста. IOS2-073, #135.

  python tests/test_pumps.py

Фрагменты — с настоящих страниц корпуса: Речников (ИОС2.1-кор3 и ВК1), Полярная 16, Тюменская-5.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pipeline import pumps  # noqa: E402


def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


# Речников, ИОС2.1-кор3, ПЗ лист 16 (F0277 стр. 21)
PD_RECH = ("Для повышения давления в системах холодного и горячего водоснабжения на минус 1 этаже предусмотрена "
           "насосная установка Wilo COR-4 MVL 1206/SKw-LC- EB-R (3 раб., 1 рез.) Q=8,569 л/с, Н=54,20 м, N=4,0 кВт")
# Речников, ВК1 изм. 1, лист 2 (F0416 стр. 5): повысительная установка, затем станция пожаротушения
RD_RECH = ("В системе хозяйственно-питьевого водоснабжения запроектирована повысительная насосная установка "
           "COR-4 MVL 1206/SKw-LC-EB-R ф. Wilo с частотным регулированием, количество насосов: 3 рабочих, 1 резервный "
           "(Q = 33,3 м3/ч; Н = 63,1 м, N = 4 кВт (1 насос), U = 3x380 B. 10 На сети хозяйственно-питьевого "
           "водопровода … 2 Для обеспечения потребного напора для нужд внутреннего пожаротушения предусмотрена "
           "установка CO 2 BL 65/190-18.5/2/SK-FFS-J4-2V35-X8-R-CS-П-М405 ф. Wilo с 1 рабочим и 1 резервным насосами "
           "(Q = 33.3 м3/ч; Н = 63.1 м , N = 4 кВт (1 насос), U = 3x380 B и жокей-насосом.")
# Полярная 16: в ПД зона не названа, в РД названа
PD_POL = ("Для повышения давления в сети ХВС предусмотрена автоматическая насосная установка с частотным "
          "регулированием (2-рабочих, 1 резервный). Марка насосной установки Aikon PBS 3 CDM10-5 FCC. "
          "Рабочая точка: Q=15.98 м3/час Н= 44,36м")
RD_POL = ("1) Установка повышения давления ХВС зоны 1 в комплекте с 3 насосами (2-раб., 1- рез.), шкафом управления, "
          "Q=15,98 м3/час Н=44,36 м, N=2х2,2 кВт Aikon PBS 3 CDM10-5 FCC;")
# Тюменская-5, спринклерная установка: не хоз-питьевая
TYUM = ("1 Спецификация Насосная установка для пожарной системы (спринклеры) - Объект: «Школа на 600 мест по адресу: "
        "г. Москва, ул. Тюменская». Заданные параметры: Q = 59,4 м3/ч н = 17,7 м Насосная установка: ВНУпж 2 IR "
        "65-125B 5,5кВт + 1хMK 32-4 0,75кВт РР/К 100мм Рабочие параметры: для основных насосов: Q = 59,4 м3/ч, Н = 18,3 м")


def keyed(cands):
    out = {}
    for c in cands:
        out.setdefault(c["key"], set()).add((c["model"], c["flow"], c["head"], c["point"]))
    return out


def main():
    ok = True
    pd = pumps.installations(PD_RECH)
    ok &= check("л/с приведены к м³/ч, модель и расчётная точка",
                [(c["model"], c["flow"], c["head"], c["point"]) for c in pd] == [("COR-4 MVL 1206", 30.85, 54.2, "calc")],
                str(pd))
    rd = pumps.installations(RD_RECH)
    ok &= check("«Q = 33,3 м3/ч; Н = 63,1 м» разобрано, станция пожаротушения — нет",
                [(c["flow"], c["head"]) for c in rd] == [(33.3, 63.1)], str([(c["flow"], c["head"]) for c in rd]))
    lower, higher = pumps.compare(keyed(pd), keyed(rd))
    ok &= check("Речников: РД выше ПД на 8 % и 16 % — не нарушение и не завышение больше 20 %",
                not lower and not higher, str((lower, higher)))
    ok &= check("спринклерная установка Тюменской-5 не повысительная", not pumps.installations(TYUM))
    pp, rp = pumps.installations(PD_POL), pumps.installations(RD_POL)
    ok &= check("рабочая точка распознана", pp and pp[0]["point"] == "working", str(pp))
    pumps.adopt_zones(pp, rp)
    ok &= check("зона проекта взята из рабочей стадии по модели", pp[0]["key"] == "Повысительная установка, зона 1",
                pp[0]["key"])
    ok &= check("Полярная 16: одинаковые установки — расхождений нет", pumps.compare(keyed(pp), keyed(rp)) == ([], []))
    low = {"Повысительная установка": {("COR-4 MVL 1206", 30.0, 50.0, "calc")}}
    got = pumps.compare({"Повысительная установка": {("COR-4 MVL 1206", 33.3, 63.1, "working")}}, low)
    ok &= check("занижение расхода и напора — нарушение", got[0] and "расход ниже" in got[0][0][3]
                and "напор ниже" in got[0][0][3], str(got))
    high = {"Повысительная установка": {("COR-4 MVL 1206", 45.0, 63.1, "calc")}}
    got = pumps.compare({"Повысительная установка": {("COR-4 MVL 1206", 33.3, 63.1, "working")}}, high)
    ok &= check("завышение больше 20 % — не нарушение, но названо", not got[0] and got[1] and "расход +35%" in got[1][0][3],
                str(got))
    two = {"Повысительная установка": {("A", 10.0, 50.0, "calc"), ("B", 20.0, 60.0, "calc")}}
    one = {"Повысительная установка": {("C", 5.0, 40.0, "calc")}}
    ok &= check("несколько установок без общей модели — пары не угадываются", pumps.compare(two, one) == ([], []))
    print("\nИТОГ:", "все проверки пройдены" if ok else "ЕСТЬ СБОИ")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
