def side(values, binding="CLAUSE", kind="element_thickness"):
    rule = {"kind": kind}
    return {"value": sorted(values), "raw": matrix_rules._set_raw(rule, sorted(values)), "binding": binding}


def test_decisions():
    ok = True
    thick = {"kind": "element_thickness", "compare": {"type": "min_decrease", "result": "DIMENSION_REDUCED"}}
    cls = {"kind": "element_class", "compare": {"type": "min_decrease", "result": "CLASS_DOWNGRADE"}}

    def label(rule, pd, rd):
        got = matrix_rules.decide_set(rule, pd, rd)
        return got[0], got[1]

    # TRAIN-0015: толщина увеличилась — не нарушение
    ok &= check("1000/1200 → 1200/1500: разница без уменьшения, как в эталоне",
                label(thick, side([1000, 1200]), side([1200, 1500])) == ("NO_VIOLATION", "NON_TRIGGERING_DIFFERENCE_NO_DECREASE"))
    ok &= check("совпавшие наборы — равенство",
                label(cls, side([40], kind="element_class"), side([40], kind="element_class")) == ("NO_VIOLATION", "EQUAL_PD_RD"))
    ok &= check("класс в указаниях РД ниже — нарушение",
                label(cls, side([35], kind="element_class"), side([30], kind="element_class")) == ("VIOLATION_PRESENT", "CLASS_DOWNGRADE"))
    ok &= check("понижение только из таблицы листа — сравнение невозможно, а не нарушение",
                label(cls, side([35], kind="element_class"), side([30], "PAGE", "element_class"))[0] == "COMPARISON_IMPOSSIBLE")
    # Речников: ПД 600 и 900 мм, в РД корпуса есть участки t=800
    ok &= check("новое значение меньше проектного наибольшего — сравнение невозможно",
                label(thick, side([600, 900]), side([600, 800, 900, 1000]))[0] == "COMPARISON_IMPOSSIBLE")
    # Стадии называют конструкции по-разному: у свайного фундамента проект пишет «ростверк»,
    # а рабочая документация — «фундаментная плита». Сравнивать нечего, и запись должна
    # сказать, чего именно ждать инспектору (#52).
    named = {"PD": {"Ростверки", "Лестницы"}, "RD": {"Фундаментная плита", "Плиты перекрытия подземной части"}}
    got = matrix_rules.decide_set(cls, side([30], kind="element_class"), None, named)
    ok &= check("значения нет в рабочей стадии, но там названы другие элементы — сказано какие",
                got[0] == "COMPARISON_IMPOSSIBLE" and "Фундаментная плита" in got[2] and "Плиты перекрытия" in got[2],
                got[2])
    got = matrix_rules.decide_set(cls, side([30], kind="element_class"), None, {"PD": {"Ростверки"}, "RD": set()})
    ok &= check("в рабочей стадии класс не назван ни для одного элемента — сказано и это",
                "ни для одного элемента" in got[2], got[2])
    # Фундамент здания на сваях проект описывает ростверком, рабочая документация — плитой.
    # Система их не отождествляет, но говорит инспектору, куда смотреть (#52).
    got = matrix_rules.decide_set(cls, side([30], kind="element_class"), None, named, "Ростверки")
    ok &= check("родственное название названо подсказкой",
                "та же конструкция под другим названием: Фундаментная плита" in got[2], got[2])
    ok &= check("подсказка не выдаётся за отождествление", "система их не отождествляет" in got[2])
    got = matrix_rules.decide_set(cls, side([30], kind="element_class"), None, named, "Лестницы")
    ok &= check("у элемента без родни подсказки нет", "та же конструкция" not in got[2], got[2])
    ok &= check("значение только в одной стадии — сравнение невозможно",
                label(thick, None, side([600]))[0] == "COMPARISON_IMPOSSIBLE")
    # Специалист (#136): «если явно не указана граница плиты перекрытия — то не нарушение»
    listed = dict(side([200, 250, 350]), enumerated=[200, 250, 350])
    got = matrix_rules.decide_set(thick, side([250]), listed)
    ok &= check("250 → перечень 350, 250, 200 без границ плит — не нарушение",
                got[:2] == ("NO_VIOLATION", "NON_TRIGGERING_DIFFERENCE_NO_DECREASE") and "без границ плит" in got[2], got[2])
    got = matrix_rules.decide_set(thick, side([250]), dict(side([180, 200]), enumerated=[180, 200]))
    ok &= check("проектной толщины в перечне нет — сравнение невозможно, а не нарушение", got[0] == "COMPARISON_IMPOSSIBLE", got[2])
    got = matrix_rules.decide_set(thick, side([250]), dict(side([200, 250]), enumerated=[250]))
    ok &= check("меньшая толщина названа отдельно, не перечнем — нарушение", got[0] == "VIOLATION_PRESENT", got[2])
    # Речников: плита на −2,100 толщиной 200 мм в РД названа явно, а в ПД — только «t=200» на листе КР2-кор3
    pd_sheet = dict(side([250]), every=[200, 250])
    got = matrix_rules.decide_set(thick, pd_sheet, side([200, 250, 350]), None, "Плиты перекрытия подземной части")
    ok &= check("та же толщина есть в ПД на листе чертежа — не нарушение",
                got[0] == "NO_VIOLATION" and "в проекте такая толщина тоже есть" in got[2], got[2])
    got = matrix_rules.decide_set(cls, dict(side([50], kind="element_class"), every=[25, 50]),
                                  side([25], kind="element_class"), None, "Плиты перекрытия надземной части")
    ok &= check("класс бетона плиты: значение с листа проекта понижение не снимает", got[0] == "VIOLATION_PRESENT", got[2])
    got = matrix_rules.decide_set(thick, pd_sheet, side([200]), None, "Фундаментная плита")
    ok &= check("у фундаментной плиты лист чертежа проекта понижение не снимает", got[0] == "VIOLATION_PRESENT", got[2])
    # Полярная 16: распределительный ростверк — отдельный элемент, класс в ПД не назван (#136)
    ok &= check("распределительный ростверк — свой элемент, плитный — «Ростверки»",
                [m[2] for m in elements.element_mentions("Распределительный ростверк В20; плитный ростверк В35")]
                == ["Распределительный ростверк", "Ростверки"])
    got = matrix_rules.decide_set(cls, None, side([20], kind="element_class"),
                                  {"PD": {"Ростверки"}, "RD": {"Ростверки", "Распределительный ростверк"}},
                                  "Распределительный ростверк")
    ok &= check("класс распределительного ростверка в ПД не назван — сравнение невозможно с подсказкой",
                got[0] == "COMPARISON_IMPOSSIBLE" and "Ростверки" in got[2] and "та же конструкция" in got[2], got[2])
    return ok


def test_side_view():
    ok = True
    # У значения, взятого без выбора колонки, ключа `column_choice` нет (#41), а выгрузка
    # находки запрашивала его по жёсткому списку: прогон правил по Тюменской-5 падал
    # с KeyError прямо на сборке находок по элементам.
    keys = ("value", "raw", "support", "alternatives", "columns", "column_choice", "binding")
    partial = {"value": [600], "raw": "600", "support": 1, "alternatives": [], "columns": None, "binding": None}
    view = matrix_rules._side_view(partial, keys, [])
    ok &= check("сторона без column_choice выгружается и не роняет прогон",
                view.get("value") == [600] and "column_choice" not in view, str(sorted(view)))
    view = matrix_rules._side_view(dict(partial, column_choice="проект"), keys, [])
    ok &= check("имеющийся column_choice остаётся в выгрузке",
                view.get("column_choice") == "проект", str(view.get("column_choice")))
    view = matrix_rules._side_view(partial, keys, [{"document": "том 1"}])
    ok &= check("прежние редакции добавляются рядом",
                view.get("revisions") == [{"document": "том 1"}], str(view.get("revisions")))
    return ok


