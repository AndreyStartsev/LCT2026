def test_definition_dash():
    """Тире определения предложение не кончает (Р-149).

    «Наружные стены - железобетонные … В25W4F75»: дефис с пробелами `_BOUNDARY` считал маркером пункта
    перечня, и за ним элемента нет. Класс стен уходил через `_ahead` к элементу следующего предложения:
    B25 стен 4-го и выше этажей — в плиты перекрытия надземной части, B35 внутренних стен подвала — в стены
    из фразы про утеплитель, а у наружных стен класса не было вовсе. Пункт перечня начинается после «:», «;»
    или точки, и там границу ставит пробел за знаком. Дефис без знака перед ним кончает пункт, если текст
    до дефиса не открывается элементом или сам несёт класс.
    """
    ok = True

    def classes(text):
        return [(c["location"], c["value"], c["binding"]) for c in elements.concrete_classes(text)]

    # стр. 28: элемент в окне NEAR, мешала только граница
    head, value = KR1_WALLS_UNDER.find("Наружные стены"), KR1_WALLS_UNDER.find("В35")
    ok &= check("класс наружных стен в окне NEAR", value - KR1_WALLS_UNDER.find("стены", head) <= elements.NEAR)
    ok &= check("«Наружные стены - железобетонные …» — дефис предложение не кончает",
                elements._sentence_start(KR1_WALLS_UNDER, value) == head,
                str(elements._sentence_start(KR1_WALLS_UNDER, value)))
    # Часть здания предложение не называет, и на странице элементов с частью здания несколько: сказанное обо всех
    # стенах идёт в обе части (`location_names`). `bind` — без листа, как на странице; в отрывке часть здания
    # назвала бы одна фраза про утеплитель. Раньше наружные стены класса не получали, а внутренние брали
    # «Наружные стены подземной части» следующего предложения (PAGE)
    for name in ("Наружные стены -", "Внутренние стены"):
        got = elements.bind(KR1_WALLS_UNDER, KR1_WALLS_UNDER.find("В35", KR1_WALLS_UNDER.find(name)))
        ok &= check(f"стр. 28, «{name}…»: B35 — по своему предложению",
                    got is not None and got[:2] == ([UNDER_V, ABOVE_V], "CLAUSE"), str(got and got[:2]))

    # стр. 29: у внутренних стен класс ещё и дальше NEAR — берёт `_sentence_head`
    inner = KR1_WALLS_ABOVE.find("Внутренние стены (в том числе лестнично-лифтовых узлов) 4-го")
    value = KR1_WALLS_ABOVE.find("В25", inner)
    ok &= check("класс внутренних стен 4-го и выше этажей дальше NEAR",
                value - KR1_WALLS_ABOVE.find("стены", inner) > elements.NEAR,
                f"{value - KR1_WALLS_ABOVE.find('стены', inner)} знаков")
    got = classes(KR1_WALLS_ABOVE)
    ok &= check("стр. 29: B35 и B25 стен — вертикальные конструкции надземной части, B25 не уходит в плиты",
                got == [(ABOVE_V, 35, "CLAUSE"), (ABOVE_V, 25, "CLAUSE"), (ABOVE_V, 25, "CLAUSE"),
                        (ABOVE_S, 35, "CLAUSE")], str(got))

    got = classes(ALTUF_KR)
    ok &= check("Алтуфьевское: «Ростверки - монолитные … В25», «Лестничные марши - сборные … В30»",
                got == [("Ростверки", 25, "CLAUSE"), ("Лестницы", 30, "CLAUSE")], str(got))

    # пункты перечня — границы, как раньше
    value = RECH_STAIRS.find("В30")
    ok &= check("«…лестниц: - бетон класса В30 …; - арматура» — пункт начинается за двоеточием",
                elements._sentence_start(RECH_STAIRS, value) == RECH_STAIRS.find("- бетон"),
                str(elements._sentence_start(RECH_STAIRS, value)))
    got = classes(RECH_STAIRS)
    ok &= check("класс пункта — лестницам из заголовка перечня, как раньше", got == [("Лестницы", 30, "CLAUSE")],
                str(got))
    item = RECH_COLUMNS.find("- бетона")
    ok &= check("«- бетона класса B35 - марка F150»: пункт не открывается элементом — дефис кончает его",
                not elements._definition_dash(RECH_COLUMNS, item, _dash_before(RECH_COLUMNS, "марка F150")))
    ok &= check("«…лестницы … марки В25 W6 F150 - в подземной части»: текст до дефиса несёт класс — не подлежащее",
                not elements._definition_dash(SOSH_STAIRS, SOSH_STAIRS.find("Монолитные"),
                                              _dash_before(SOSH_STAIRS, "в подземной")))
    # в подлежащем два элемента: к которому из них класс, правило не решает — значения нет, как раньше
    got = classes(KZH41_TWO)
    ok &= check("«Плиты перекрытия …, наружные стены … - … В25» — два элемента, не берётся", not got, str(got))
    return ok


