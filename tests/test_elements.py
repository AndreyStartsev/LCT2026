def test_retaining_walls():
    """Подпорная стена участка и её части — не стены здания (Р-146).

    Раздел ПД школы Полярная 25 о подпорной стене называет её в заголовке и первых предложениях, а класс
    бетона ставит частям: «Выравнивающая стенка – … В30», «Парапетная стенка – … В30». `_NOT_STRUCTURAL`
    смотрит на 90 знаков назад в предложении значения, и стенки уходили в стены здания обеих частей.
    """
    ok = True
    got = bindings(RETAINING_47)
    ok &= check("раздел «6.2.12. Подпорные стены» (стр. 47): стенки, сваи и пояс — не элементы здания",
                not got, str(got))
    got = bindings(RETAINING_14)
    ok &= check("таблица изменений (стр. 14): подпорная стена названа за четыре предложения до стенки",
                not got, str(got))
    # « - » — граница предложения, и «Основной материал подпорной стены - тяжёлый бетон класса В25» оставался
    # без подпорной стены: класс уходил ростверку ограждения запасной привязкой «лист»
    got = bindings(RETAINING_24)
    ok &= check("исходный ПД (L3177, стр. 24): сваи и тело подпорной стены — не ростверк ограждения",
                not got, str(got))
    got = bindings(POS_FENCE + " " + POS_WORKS)
    ok &= check("ПОС (L3158, стр. 32): «заполнение скважин бетоном марки B25» подпорной стены — не ростверк",
                not got, str(got))
    # ПД ДОО Полярная 25, КР изм.1 (DOO25-000842), стр. 8: пункт «1.» под заголовком о подпорной стене — её данные
    doo = "1.8 Конструктивные решения подпорной стены 1. Материал железобетон- ных конструкций ПС, В25 F200 W8."
    ok &= check("пункт «1.» под заголовком о подпорной стене продолжает раздел",
                elements.retaining_passage(doo, doo.index("В25")))

    # парапеты здания: подпорной стены перед ними нет, значения остаются как были
    got = [(c["location"], c["value"], c["binding"]) for c in elements.concrete_classes(KR1_SLABS + " " + KR1_PARAPETS)
           if "Парапеты выполнены" in c["snippet"]]
    ok &= check("парапеты здания (Полярная 16, КР1, стр. 30) остаются", len(got) == 2, str(got))
    # здание после подпорной стены: заголовок следующего раздела (стр. 37 того же тома), другой элемент или часть
    # здания при стене кончают текст о подпорной стене
    got = pairs(RETAINING_48_END + " 6.2.2. Стены здания - внутренние. " + OKT_WALLS)
    ok &= check("заголовок нового раздела после подпорной стены — стены здания, обе части",
                got == {(UNDER_V, 30), (ABOVE_V, 30)}, str(got))
    got = pairs(RETAINING_48_END + " " + OKT_PYLONS + " " + OKT_WALLS)
    ok &= check("пилоны и колонны после подпорной стены — дальше текст о здании",
                got == {(UNDER_V, 30), (ABOVE_V, 30)}, str(got))
    # Октябрьская L0009 стр. 3
    got = pairs(RETAINING_48_END + " Стены на отм. +6,290 ГОСТ 26633-2015 Бетон В30 42 м3")
    ok &= check("стены с отметкой после подпорной стены — стены здания", got == {(ABOVE_V, 30)}, str(got))
    # граница правила: стена сразу за текстом о подпорной стене, без заголовка и без другого элемента, — её часть
    got = pairs(RETAINING_48_END + " " + OKT_WALLS)
    ok &= check("стены сразу за подпорной стеной, без заголовка, считаются её частью", not got, str(got))
    return ok


