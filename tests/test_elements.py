def limit_at(text, raw):
    return elements.class_limit(text, text.index(raw))


def test_class_limits():
    """Предел класса в задании на проектирование и технических условиях — не класс конструкции (Р-147).

    «Выше чем В30 допускается только при обосновании» ограничивает класс, а не называет его. Разбор таблицы
    брал элемент из следующего предложения, и у стен подземной части Полярной 16 появлялось B30 — в ПД
    и в шести томах РД, куда приложено задание.
    """
    ok = True
    # Полярная 16, ПД ЗнП (POL16-000021), стр. 13. Тот же текст — в РД: АТМ (POL16-000157/158, стр. 92),
    # ТМ (POL16-000267/268, стр. 197), ЭОМ.ИТП (POL16-000286/287, стр. 65)
    text = ("Класс бетона определить расчетом. Применение бетона классом по прочности выше чем В30 допускается "
            "только при обосновании по предварительному согласованию с Застройщиком. Предусмотреть устройство "
            "гидроизоляции наружных стен подземной части здания. Независимо от гидрогеологических условий "
            "предусмотреть гидроизоляцию рабочих швов бетонирования в виде гидрошпонок или набухающих шнуров")
    ok &= check("«классом по прочности выше чем В30 допускается только…» — предел", limit_at(text, "В30"))
    got = pairs(text)
    ok &= check("задание на проектирование: стены из следующего предложения не получают B30", not got, str(got))
    # Полярная 16, ПД КР1 (POL16-000045), стр. 28: класс стен подвала берётся тем же ходом через следующее
    # предложение, но это не предел — он остаётся
    got = bindings("Внутренние стены (в том числе лестнично-лифтовых узлов) - железобетонные толщиной 200 мм из "
                   "монолитного бетона класса В35W6F150. Армирование стен принято отдельными стержнями из арматуры "
                   "класса А500С и А240. Наружные стены подземной части на глубину промерзания (не менее 1800мм от "
                   "планировочной отметки земли) утепляются плитами из экструзионного пенополистирола толщиной 100 мм "
                   "по ГОСТ 32310-2012.")
    ok &= check("КР1: B35 стен подвала остаётся, «не менее 1800мм» — не про класс", got == {(UNDER_V, 35, "PAGE")},
                str(got))
    # Октябрьская, ПЗ (L0028), стр. 37, распознанный скан: задание на проектирование в составе записки
    text = ("Материалы несущих конструкций для зданий до 75 м. В перекрытиях и покрытиях принять класс бетона no "
            "прочности не менее B30. Вертикальные конструкции подземной части и первого этажа — B30, при "
            "соответствующем обосновании - B35/B40. Для вертикальных конструкций со 2-20 этажа и выше применить "
            "бетон класса B30, либо B35 по согласованию с Заказчиком.")
    got = pairs(text[:text.index("Вертикальные")])
    ok &= check("задание в ПЗ: «принять класс бетона no прочности не менее B30» — не класс плит", not got, str(got))
    ok &= check("«со 2-20 этажа и выше применить бетон класса B30» — «выше» про этажи, не предел",
                not limit_at(text, "B30, либо"))
    # Полярная 16, ПД ПЗ (POL16-000034), стр. 130, распознанный скан технических условий ПАО МГТС
    got = pairs("Использовать смотровые устройства кабельной канализации связи (ККС, колодцы), а также плиты "
                "перекрытия и разгрузочные плиты дая смотровых устройств, из бетона класса не менее В25 "
                "(327 xre/ см?), Е2 200 (200 циклов замораживания и оттаивания)")
    ok &= check("технические условия: «из бетона класса не менее В25» — предел", not got, str(got))
    # ДОО, ПД (DOO25-000852), стр. 68, распознанный скан: «(не менее)» после марок — не предел класса
    text = ("Несущие конструкции надземной части корпуса — монолитные железобетонные: стены и простенки толщиной "
            "200, 240, 300, 390 мм из бетона класса: B40, марок W8, F150 (не менее) — в уровне первого этажа; "
            "B40, марки F75 (не менее) — в уровне со второго по семнадцатый этаж; B35, марки F75 (не менее) — "
            "в уровне с восемнадцатого по тридцать третий этаж;")
    ok &= check("«B40, марок W8, F150 (не менее)», «B35, марки F75 (не менее)» — не пределы",
                not limit_at(text, "B40, марок") and not limit_at(text, "B40, марки") and not limit_at(text, "B35"))
    got = pairs(text)
    ok &= check("класс стен B40 остаётся значением", 40 in {v for _, v in got}, str(got))
    # Тюменская-5, ПД том 4.1.1 (F0158), стр. 18 и Новослободская, ПД КР1 (F0105), стр. 14: «ниже» и «более»
    # не при классе
    text = ("Материал горизонтальных и вертикальных железобетонных конструкций ниже отм. ±0,000 запроектирован из "
            "бетона B30W10F300 и В30W8F200 по ГОСТ 26633-91*.")
    ok &= check("«конструкций ниже отм. ±0,000 … из бетона B30» — не предел", not limit_at(text, "B30"))
    text = "величиной более 100 мм – зачеканен бетоном класса В25."
    ok &= check("«величиной более 100 мм – зачеканен бетоном класса В25» — не предел", not limit_at(text, "В25"))
    return ok


def test_zones():
    ok = True
    ok &= check("этажи с минус третьего — подземная часть", elements.zone_of("стены -3 по +1") == UNDERGROUND)
    ok &= check("этажи до кровли — надземная часть", elements.zone_of("стены +17 до +кровля") == ABOVEGROUND)
    ok &= check("«-1 этажа» — подземная часть", elements.zone_of("Вертикальные конструкции -1 этажа") == UNDERGROUND)
    ok &= check("«с 2 по 12 этаж» — надземная часть", elements.zone_of("Плиты перекрытия с 2 по 12 этаж") == ABOVEGROUND)
    # Полярная 16, КР1 ПД (POL16-000045), стр. 31 и 32: диапазон этажей через дефис. «24» после дефиса
    # отбрасывалось как номер со знаком минус, часть здания не находилась, и класс наружных стен уходил
    # в обе части: в подземной выходило B25/B35, хотя стены подвала — B35 (стр. 28) (Р-144)
    ok &= check("«2-24 этажей» — надземная часть",
                elements.zone_of("Наружные стены 2-24 этажей: Тип 1 • внутренний слой") == ABOVEGROUND)
    ok &= check("«3–17 этажи» через короткое тире — надземная часть",
                elements.zone_of("Вертикальные конструкции 3–17 этажи") == ABOVEGROUND)
    ok &= check("«2 - 4 этажей» с пробелами — надземная, а не подземная по «- 4 этажей»",
                elements.zone_of("стены 2 - 4 этажей") == ABOVEGROUND)
    ok &= check("диапазон с минуса «-2-1 этажей» надземным не становится",
                elements.zone_of("Вертикальные конструкции -2-1 этажей") != ABOVEGROUND)
    ok &= check("«-2го до кровли» — по-прежнему вся высота", elements.zone_of("Плита перекрытия -2го до кровли") == elements.MIXED)
    got = pairs("Наружные стены 2-24 этажей: Тип 1 • внутренний слой – железобетонная стена толщиной 200 мм из "
                "монолитного бетона класса В35W4F75 армированная отдельными стержнями вязаной арматуры класса А500С и А240;")
    ok &= check("наружные стены 2-24 этажей: B35 только в надземной части", got == {(ABOVE_V, 35)}, str(got))
    got = pairs("Наружные стены 2-24 этажей в зоне лоджий: Тип 1 • внутренний слой – железобетонная стена толщиной "
                "200мм из монолитного бетона класса В25W4F75 армированная отдельными стержнями вязаной арматуры класса "
                "А500С и А240;")
    ok &= check("то же в зоне лоджий: B25 только в надземной части", got == {(ABOVE_V, 25)}, str(got))
    got = pairs("Наружная стена 1 этажа: • внутренний слой – железобетонная стена толщиной 200 мм из монолитного "
                "бетона класса В35W4F75 армированная отдельными стержнями вязаной арматуры класса А500С и А240;")
    ok &= check("наружная стена 1 этажа — как и было, надземная часть", got == {(ABOVE_V, 35)}, str(got))
    # Полярная 16, РД КЖ5.2 изм.3 (POL16-000102), стр. 3 — ведомость материалов по этажам
    got = pairs("Стены 10-22 этаж ГОСТ 26633-2015 Бетон В25 F75 W4 86,87 м³")
    ok &= check("строка ведомости «Стены 10-22 этаж» — надземная часть", got == {(ABOVE_V, 25)}, str(got))
    # Октябрьская, ПЗ (L0027), стр. 37: часть здания бралась из заголовка предыдущего предложения
    got = pairs("Вертикальные конструкции подземной части и первого этажа — B30, при соответствующем обосновании - "
                "B35/B40. Для вертикальных конструкций со 2-20 этажа и выше применить бетон класса B30, либо B35 по "
                "согласованию с Заказчиком.")
    ok &= check("«со 2-20 этажа и выше» — надземная часть, а не подземная из предыдущего предложения",
                got == {(ABOVE_V, 30), (ABOVE_V, 35)}, str(got))
    # Речников, РД К2-КЖ4.2 (F0400), стр. 3: толщина плит с диапазоном этажей — проза с уровнем, привязка крепкая
    got = [(values, zone, form) for values, _s, zone, form in elements.slab_thickness(
        "6. В данный комплект включены чертежи плит перекрытия 2-12 этажей, в виде монолитных железобетонной плит "
        "толщиной 200 мм. и контурной балки")]
    ok &= check("толщина плит 2-12 этажей — надземная часть", got == [([200], ABOVEGROUND, "prose")], str(got))
    # Октябрьская L0009 стр. 3 и протоколы испытаний (#62): знак отметки решает часть здания.
