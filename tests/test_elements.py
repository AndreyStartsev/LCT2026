def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def pairs(text, path=""):
    return {(c["location"], c["value"]) for c in elements.concrete_classes(text, path)}


def bindings(text, path=""):
    return {(c["location"], c["value"], c["binding"]) for c in elements.concrete_classes(text, path)}


