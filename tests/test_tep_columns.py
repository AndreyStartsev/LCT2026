def test_foreign_headers():
    """Шапки вне корпуса: значение проекта 3694,60, норма 2500,00 (#41).

    Проверяется, что выбор не зависит от того, слева норма или справа, и что незнакомая
    шапка не выдаёт себя за распознанную: способ выбора виден в column_choice.
    """
    ok = True
    cases = [
        ("«По проекту | Нормативное», правило last",
         "Наименование По проекту Нормативное Площадь озеленения 3694,60 2500,00", "last", 3694.6, "header"),
        ("«Нормативное | По проекту», правило first",
         "Наименование Нормативное По проекту Площадь озеленения 2500,00 3694,60", "first", 3694.6, "header"),
        ("«Требуется | Принято», правило first",
         "Наименование Требуется Принято Площадь озеленения 2500,00 3694,60", "first", 3694.6, "header"),
        ("«По расчёту | Принято», правило last",
         "Наименование По расчёту Принято Площадь озеленения 2500,00 3694,60", "last", 3694.6, "header"),
        ("«По нормам | Принято», правило first",
         "Наименование По нормам Принято Площадь озеленения 2500,00 3694,60", "first", 3694.6, "header"),
        ("незнакомая шапка «Вариант 1 | Вариант 2» решается правилом и говорит об этом",
         "Наименование Вариант 1 Вариант 2 Площадь озеленения 3987,30 3694,60", "last", 3694.6, "rule"),
        ("незнакомая шапка «I этап | II этап» — то же",
         "Наименование I этап II этап Площадь озеленения 1500,00 2194,60", "last", 2194.6, "rule"),
        ("одна колонка выбора не требует",
         "Наименование Показатель Площадь озеленения 3694,60", "last", 3694.6, "single"),
    ]
    for name, text, rule, value, choice in cases:
        got = found(text, [r"площадь озеленения"], rule)
        good = got and got["value"] == value and got["column_choice"] == choice
        ok &= check(name, good, "" if good else f'{got and got["value"]} способом {got and got["column_choice"]}')
    return ok


