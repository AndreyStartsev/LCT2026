def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def by_rule(code, text):
    """Первое вхождение показателя по правилу из конфигурации."""
    rule = RULES[code]
    got = tep.find_values(text, rule["labels"], rule.get("exclude", []), rule.get("rule", "first"),
                          rule.get("exclude_unless_header", []))
    return got[0] if got else None


def found(text, labels, rule="first"):
    got = tep.find_values(text, labels, (), rule)
    return got[0] if got else None


def row_start(text, label):
    flat = tep.flatten(text)
    return flat, flat.lower().index(label.lower())


def test_share():
    ok = True
    got = by_rule("PZ-001", ALTUF_PZU)
    ok &= check("до реконструкции | после | %: доля называет колонку проекта",
                got["value"] == 2909.5 and got["columns"] == [2362.5, 2909.5, 31.0],
                f"{got['value']} из {got['columns']}; правило «первая» брало 2362,5 — площадь до реконструкции")
    ok &= check("значение — выбранная колонка, а не вся строка", got["raw"] == "2909,5",
                f"raw {got['raw']!r}; раньше в находку уходило «2362,5 2909,5 31 м²»")
    got = by_rule("PZ-001", ALTUF_SPOZU)
    ok &= check("то же в томе другого проектировщика, дробная часть через точку",
                got["value"] == 3009.4 and got["raw"] == "3009.4", f"{got['value']} из {got['columns']}")
    no_header = ALTUF_PZU[ALTUF_PZU.index("площадь участка"):]
    ok &= check("доля решает и без шапки",
                by_rule("PZ-001", no_header)["value"] == 2909.5
                and tep.header_roles(*row_start(no_header, "площадь застройки")) == (None, False))
