"""Шифр с листа, выправленный по шифру комплекта из реестра. Задача #52.

  python tests/test_code_registry.py

Распознавание портит шифр одинаково на всех листах комплекта, и голосование по ряду
листов такую ошибку не ловит. Шифр комплекта известен из имени файла — это независимый
источник, которым прочтение выправляется. Опасность ровно одна: подменить прочтение
шифром соседнего комплекта, ведь комплекты одного объекта отличаются на один-два знака.
Поэтому здесь проверяется не только то, что правится, но и то, что остаётся как есть.

Примеры написаны по виду ошибок, которые даёт распознавание надписей корпуса;
конкретные шифры выдуманы, чтобы проверка не опиралась на отдельный объект.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from pipeline import code_registry as cr, sheet_sequence  # noqa: E402


def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def fixed(read, registry):
    return cr.align(read, registry)[0]


def test_fixes():
    ok = True
    # Ноль в шрифте надписи принят за букву «О» — так читается весь комплект разом
    ok &= check("ноль, прочитанный как буква, выправлен",
                fixed("НВС-2025/03-КЖО2.1", "НВС-2025-03-КЖ02.1") == "НВС-2025/03-КЖ02.1",
                fixed("НВС-2025/03-КЖО2.1", "НВС-2025-03-КЖ02.1"))
    # Цифра сливается с рамкой и теряется: на одном объекте так испорчены 35 листов из 43
    ok &= check("потерянный знак возвращён по реестру",
                fixed("НВС-2025/03-КЖ.1", "НВС-2025-03-КЖ1.1") == "НВС-2025/03-КЖ1.1",
                fixed("НВС-2025/03-КЖ.1", "НВС-2025-03-КЖ1.1"))
    ok &= check("разделители прочтения сохраняются: на листе косая черта, в имени файла дефис",
                "/" in fixed("НВС-2025/03-КЖО2.1", "НВС-2025-03-КЖ02.1"))
    ok &= check("хвост листа, которого нет в имени файла, остаётся",
                fixed("НВС-2025/03-КЖО2.1.И", "НВС-2025-03-КЖ02.1") == "НВС-2025/03-КЖ02.1.И")
    ok &= check("совпавшее прочтение не трогается",
                cr.align("НВС-2025/03-КР1", "НВС-2025/03-КР1") == ("НВС-2025/03-КР1", []))
    return ok


def test_keeps_hands_off():
    ok = True
    # Соседние комплекты объекта отличаются на один знак: подменить их друг другом нельзя
    ok &= check("другой подраздел того же тома не подменяется",
                fixed("АНО/150321/1-П-ИОС5.1", "АНО/150321/1-П-ИОС5.2") == "АНО/150321/1-П-ИОС5.1")
    ok &= check("другой номер комплекта не подменяется",
                fixed("НВС-2025/03-КР1", "НВС-2025/03-КР2") == "НВС-2025/03-КР1")
    ok &= check("прочтение, потерявшее целые куски, не достраивается",
                fixed("НВС-ИОС.8", "НВС-2025/03-ИОС5.8.ПЗ") == "НВС-ИОС.8")
    ok &= check("больше двух исправлений — это другой шифр (выдуманный случай)",
                fixed("АБВ-11-ГД5.1", "ГДЕ-77-КЖ5.1") == "АБВ-11-ГД5.1")
    ok &= check("пустые значения не ломают разбор",
                cr.align("", "НВС-2025/03-КР1") == ("", []) and cr.align("НВС-2025/03-КР1", None)[0] == "НВС-2025/03-КР1")
    ok &= check("латиница вместо кириллицы — один знак для распознавания",
                cr.confusable("O", "О") and cr.confusable("н", "H") and not cr.confusable("к", "р"))
    return ok


def test_in_linkage():
    """Выправление в связке листов: шифр слоя не трогается, из распознавания — правится."""
    rows = [
        {"file_id": "F1", "pdf_page_number": 1, "document_sheet_number": 1, "sheet_source": "TEXT_LAYER",
         "document_code": "НВС-2025/03-КР1.ПЗ", "code_source": "TEXT_LAYER"},
        {"file_id": "F1", "pdf_page_number": 2, "document_sheet_number": 2, "sheet_source": "OCR_CORNER",
         "document_code": "НВС-2025/О3-КР1", "code_source": "OCR_CORNER"},
    ]
    stats = sheet_sequence.check(rows, {"F1": "НВС-2025/03-КР1"})
    ok = check("шифр из текстового слоя не тронут", rows[0]["document_code"] == "НВС-2025/03-КР1.ПЗ",
               rows[0]["document_code"])
    ok &= check("шифр из распознавания выправлен по реестру", rows[1]["document_code"] == "НВС-2025/03-КР1",
                rows[1]["document_code"])
    ok &= check("прочитанное сохранено рядом", rows[1].get("document_code_read") == "НВС-2025/О3-КР1")
    ok &= check("исправление названо в строке", rows[1].get("code_fixed_by_registry") == [["О3", "03"]],
                str(rows[1].get("code_fixed_by_registry")))
    ok &= check("счётчик исходов посчитал выправление", stats["CODE_FIXED_BY_REGISTRY"] == 1)
    rows2 = [{"file_id": "F2", "pdf_page_number": 1, "document_sheet_number": 1, "sheet_source": "OCR_CORNER",
              "document_code": "НВС-2025/03-КР2", "code_source": "OCR_CORNER"}]
    sheet_sequence.check(rows2, {"F2": "НВС-2025/03-КР1"})
    ok &= check("шифр соседнего комплекта не подменяется и в связке",
                rows2[0]["document_code"] == "НВС-2025/03-КР2")
    return ok


def main():
    ok = True
    for title, fn in (("Что правится", test_fixes), ("Что остаётся как есть", test_keeps_hands_off),
                      ("В связке листов", test_in_linkage)):
        print(f"\n{title}")
        ok &= fn()
    print("\nИТОГ:", "все проверки пройдены" if ok else "ЕСТЬ СБОИ")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
