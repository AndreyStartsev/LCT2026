def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def got(text, doc=None):
    return {(c["location"], c["raw"], c["value"], c["binding"])
            for c in steel.grades(text, doc, elements.clause_bounds)}


def test_element():
    """Марка достаётся тому элементу, о котором сказана.

    Так выглядела ошибка экспериментального профиля: одно значение на страницу, и
    наименьшей маркой абзаца всегда оказывалась сталь закладных пластин.
    """
    ok = True
    rows = got(PD_PIT)
    ok &= check("проект: распорки — Ст2сп", ("Распорки котлована", "Ст2сп", 225, "CLAUSE") in rows, str(rows))
    ok &= check("проект: пояс — С245 (латинская C в обозначении)",
                ("Обвязочный пояс", "С245", 245, "CLAUSE") in rows)
    rows = got(RD_PIT)
    ok &= check("рабочая: трубы спецификации — распорки Ст20",
                ("Распорки котлована", "Ст20", 245, "CLAUSE") in rows, str(rows))
    ok &= check("рабочая: двутавр спецификации — обвязочный пояс С245",
                ("Обвязочный пояс", "С245", 245, "CLAUSE") in rows)
    ok &= check("«пояса ферм» — ферма, а не обвязочный пояс котлована",
                got(TRUSS) == {("Стальные фермы", "С345", 345, "CLAUSE")}, str(got(TRUSS)))
