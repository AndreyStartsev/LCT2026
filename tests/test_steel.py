def side(values, binding="CLAUSE"):
    return {"value": sorted(values), "raw": "/".join(g for _v, g in sorted(values)), "binding": binding}


def test_decision():
    """Решение по элементу: понижение прочности — нарушение, замена без понижения — кандидат."""
    rule = {"kind": "element_steel_grade", "scope": "element",
            "compare": {"type": "min_decrease", "result": "CLASS_DOWNGRADE"}}
    named = {"PD": {"Металлические колонны"}, "RD": {"Металлические колонны"}, "ID": set()}
    high, low = side([(345, "С345")]), side([(245, "С245")])
    label, result, detail = matrix_rules.decide_set(rule, high, low, named, "Металлические колонны")
    ok = check("С345 → С245 — понижение марки", (label, result) == ("VIOLATION_PRESENT", "CLASS_DOWNGRADE"), detail)
    # ANN-C-0001: Ст2сп → Ст20 поднимает предел текучести с 225 до 245 МПа
    pd, rd = side([(225, "Ст2сп")]), side([(245, "Ст20")])
    label, result, detail = matrix_rules.decide_set(rule, pd, rd, named, "Распорки котлована")
    ok &= check("Ст2сп → Ст20 — не нарушение", label == "NO_VIOLATION", detail)
    ok &= check("но и не молчание: замена марки названа", result == steel.SUBSTITUTION, result)
    ok &= check("в пояснении обе марки и оба предела", "225 → 245" in detail and "Ст2сп → Ст20" in detail, detail)
    same = side([(245, "С245"), (245, "Ст20")])
    label, result, detail = matrix_rules.decide_set(rule, same, same, named, "Распорки котлована")
    ok &= check("тот же набор марок — расхождения нет", (label, result) == ("NO_VIOLATION", "EQUAL_PD_RD"), detail)
    label, _result, detail = matrix_rules.decide_set(rule, high, side([(245, "С245")], "PAGE"),
                                                    named, "Металлические колонны")
    ok &= check("понижение только по таблице листа — не вердикт", label == "COMPARISON_IMPOSSIBLE", detail)
    return ok


