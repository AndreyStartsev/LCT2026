def test_profile_decision():
    """Решение по профилю: наибольший профиль стадии, лишний профиль из ПОС не мешает."""
    pages = [({"file_id": "F0105", "stage": "PD", "relative_path": "Стадия П/КР1.pdf"}, 14, PD_BELT),
             ({"file_id": "F0112", "stage": "PD", "relative_path": "Стадия П/ПОС.pdf"}, 26, PD_POS),
             ({"file_id": "F0145", "stage": "RD", "relative_path": PIT_DOC["relative_path"]}, 4, RD_BELT)]
    got = steel.profile_findings("OBJ-X", pages)
    ok = check("одна запись по обвязочному поясу",
               len(got) == 1 and got[0]["locations"] == ["Обвязочный пояс"], str(got)[:160])
    f = got[0] if got else {}
    ok &= check("понижение профиля — гипотеза, а не вердикт",
                f.get("violation_label") == "VIOLATION_PRESENT" and f.get("finding_status") == "SUSPICION"
                and f.get("needs_expert") and f.get("comparison_result") == "DIMENSION_REDUCED")
    ok &= check("сравнивается наибольший профиль: 50Б2 из тома ПОС не делает вид, что профиль вырос",
                f.get("pd_value") == "70Б2/70Б3" and f.get("rd_value") == "60Б1/55Б1"
                or f.get("pd_value") == "70Б2/70Б3" and f.get("rd_value") == "60Б1",
                f'ПД {f.get("pd_value")} → РД {f.get("rd_value")}')
    ok &= check("в записи и обе стадии, и весь набор профилей",
                "50Б2" in (f.get("extraction") or {}).get("detail", "")
                and {e["stage"] for e in f.get("evidence") or []} == {"PD", "RD"},
                (f.get("extraction") or {}).get("detail", "")[:140])
    same = [(p[0], p[1], p[2]) for p in pages if p[0]["file_id"] != "F0145"]
    same.append(({"file_id": "F0145", "stage": "RD", "relative_path": PIT_DOC["relative_path"]}, 4,
                 "Обвязочный пояс состоит из трех двутавров 70Б3."))
    got = steel.profile_findings("OBJ-X", same)
    ok &= check("профиль не понижен — запись «расхождения нет»",
                len(got) == 1 and got[0]["violation_label"] == "NO_VIOLATION"
                and got[0]["finding_status"] == "NEGATIVE_VERIFIED", str(got)[:140])
    one_stage = [p for p in pages if p[0]["stage"] == "PD"]
    ok &= check("одна стадия молчит — сравнивать нечего", steel.profile_findings("OBJ-X", one_stage) == [])
    return ok


