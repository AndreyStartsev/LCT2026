def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def got(text, doc=None):
    return {(c["location"], c["raw"], c["value"], c["binding"])
            for c in steel.grades(text, doc, elements.clause_bounds)}


def test_element():
    """Марка достаётся тому элементу, о котором сказана.

    Так выглядела ошибка экспериментального профиля: одно значение на страницу, и
    наименьшей маркой абзаца всегда оказывалась сталь закладных пластин.
    """
    ok = True
    rows = got(PD_PIT)
    ok &= check("проект: распорки — Ст2сп", ("Распорки котлована", "Ст2сп", 225, "CLAUSE") in rows, str(rows))
    ok &= check("проект: пояс — С245 (латинская C в обозначении)",
                ("Обвязочный пояс", "С245", 245, "CLAUSE") in rows)
    rows = got(RD_PIT)
    ok &= check("рабочая: трубы спецификации — распорки Ст20",
                ("Распорки котлована", "Ст20", 245, "CLAUSE") in rows, str(rows))
    ok &= check("рабочая: двутавр спецификации — обвязочный пояс С245",
                ("Обвязочный пояс", "С245", 245, "CLAUSE") in rows)
    ok &= check("«пояса ферм» — ферма, а не обвязочный пояс котлована",
                got(TRUSS) == {("Стальные фермы", "С345", 345, "CLAUSE")}, str(got(TRUSS)))
    ok &= check("вид проката в предложении сильнее элемента из соседнего: марка труб не уходит "
                "закладным", got(RD_SVG, SVG_DOC) == {("Распорки котлована", "Ст20", 245, "CLAUSE")},
                str(got(RD_SVG, SVG_DOC)))
    return ok


def test_no_false_alarms():
    """Что маркой стали не считается."""
    ok = True
    ok &= check("«не ниже С235» — требование, а не решение", got(REQUIREMENT) == set(), str(got(REQUIREMENT)))
    ok &= check("«Ст25-1», «Ст20-1» на плане — подписи стен", got(WALL_MARKS) == set(), str(got(WALL_MARKS)))
    ok &= check("марка листовой стали своей записи не даёт: закладные не несущие",
                got("сталь листовая по ГОСТ 19903-2015 из стали С235 по ГОСТ 27772-88*") == set())
    ok &= check("марка без элемента отброшена",
                got("Материал стальных элементов - сталь С 245 по ГОСТ 27772-2015.") == set())
    ok &= check("«ст. 20» с точкой — не марка",
                got("см. ст. 20 настоящего договора, сталь поставляется партиями") == set())
    return ok


def side(values, binding="CLAUSE"):
    return {"value": sorted(values), "raw": "/".join(g for _v, g in sorted(values)), "binding": binding}


def test_decision():
    """Решение по элементу: понижение прочности — нарушение, замена без понижения — кандидат."""
    rule = {"kind": "element_steel_grade", "scope": "element",
            "compare": {"type": "min_decrease", "result": "CLASS_DOWNGRADE"}}
    named = {"PD": {"Металлические колонны"}, "RD": {"Металлические колонны"}, "ID": set()}
    high, low = side([(345, "С345")]), side([(245, "С245")])
    label, result, detail = matrix_rules.decide_set(rule, high, low, named, "Металлические колонны")
    ok = check("С345 → С245 — понижение марки", (label, result) == ("VIOLATION_PRESENT", "CLASS_DOWNGRADE"), detail)
    # ANN-C-0001: Ст2сп → Ст20 поднимает предел текучести с 225 до 245 МПа
    pd, rd = side([(225, "Ст2сп")]), side([(245, "Ст20")])
    label, result, detail = matrix_rules.decide_set(rule, pd, rd, named, "Распорки котлована")
    ok &= check("Ст2сп → Ст20 — не нарушение", label == "NO_VIOLATION", detail)
    ok &= check("но и не молчание: замена марки названа", result == steel.SUBSTITUTION, result)
    ok &= check("в пояснении обе марки и оба предела", "225 → 245" in detail and "Ст2сп → Ст20" in detail, detail)
    same = side([(245, "С245"), (245, "Ст20")])
    label, result, detail = matrix_rules.decide_set(rule, same, same, named, "Распорки котлована")
    ok &= check("тот же набор марок — расхождения нет", (label, result) == ("NO_VIOLATION", "EQUAL_PD_RD"), detail)
    label, _result, detail = matrix_rules.decide_set(rule, high, side([(245, "С245")], "PAGE"),
                                                    named, "Металлические колонны")
    ok &= check("понижение только по таблице листа — не вердикт", label == "COMPARISON_IMPOSSIBLE", detail)
    return ok


