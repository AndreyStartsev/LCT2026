def test_tsv():
    ok = True
    head = "level\tpage_num\tblock_num\tpar_num\tline_num\tword_num\tleft\ttop\twidth\theight\tconf\ttext"
    lines = [head,
             "5\t1\t1\t1\t1\t1\t10\t10\t50\t20\t90.1\t\"АРКТОС”",
             "5\t1\t1\t1\t1\t2\t70\t10\t40\t20\t91.0\t-//-",
             "5\t1\t2\t1\t1\t1\t2555\t663\t81\t33\t90.5\tJlucm",
             "5\t1\t3\t1\t1\t1\t2577\t749\t40\t39\t96.9\t12"]
    got = [t for t, *_ in ocr.tsv_words("\n".join(lines))]
    ok &= check("кавычка в начале слова не глотает остальной вывод",
                got == ["\"АРКТОС”", "-//-", "Jlucm", "12"], str(got))
    return ok


def test_vote():
    ok = True
    ok &= check("оба языка согласны — сильное прочтение", ocr.vote(["4", "4"]) == (4, True))
    ok &= check("ответил один язык — слабое прочтение", ocr.vote(["4", ""]) == (4, False))
    ok &= check("ответы расходятся — отказ", ocr.vote(["57", "7"]) == (None, False))
    ok &= check("пустая графа — отказ", ocr.vote(["", ""]) == (None, False))
    ok &= check("ноль — не номер листа", ocr.vote(["0", "0"]) == (None, False))
    return ok


