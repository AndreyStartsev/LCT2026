def test_corner():
    ok = True
    # F0204 стр. 19, форма 2а: «Лист» шапки таблицы изменений ниже графы номера листа
    words = [mm("flucm", 12.8, 16.6, 86.4), mm("5", 13.5, 9.0, 75.6),
             mm("Лист", 165.6, 7.8), mm("|Кол.уч.", 175.4, 7.4), mm("Формат", 51.8, 1.9)]
    got, _ = ocr.read(words)
    ok &= check("форма 2а: номер под самой правой подписью «Лист»",
                got["document_sheet_number"] == 5, str(got["document_sheet_number"]))

    # F0201 стр. 16, форма 3: ниже значений «ООО «ТСП»», прочитанное как «000»
    words = [mm("Cmagua", 47.5, 32.5), mm("Jlucm", 32.7, 32.5), mm("Листов", 12.0, 32.5),
             mm("РД", 47.5, 25.0), mm("3", 32.5, 25.0), mm("000", 30.0, 12.0),
             mm("АНО/150321/1-РД-ОВ1", 110.0, 50.0)]
    got, _ = ocr.read(words)
    ok &= check("форма 3: лист, стадия и шифр", (got["document_sheet_number"],
                got["stage_from_titleblock"], got["document_code"]) == (3, "RD", "АНО/150321/1-РД-ОВ1"),
                str(got))

    # F0203 стр. 9, лист 3917×2863: подписи прочитаны как «Пуст», «Пустов», «Стадбуя»
    words = [mm("Стадбуя", 47.8, 37.0, 45.2), mm("Пуст", 32.7, 37.0, 78.8),
             mm("Пустов", 15.3, 37.0, 52.4), mm("Р", 47.1, 29.9), mm("3", 32.2, 29.9),
             mm("7", 15.9, 30.1), mm("flucm", 165.2, 42.0)]
    got, _ = ocr.read(words)
    ok &= check("подписи с «П» вместо «Л» и «у» вместо «и»",
                (got["document_sheet_number"], got["sheets_total"]) == (3, 7), str(got))

    words = [mm("flucm", 165.2, 42.0), mm("3", 160.0, 35.0)]
    got, _ = ocr.read(words)
    ok &= check("«Лист» дальше 120 мм — шапка таблицы изменений, не графа листа",
                got["document_sheet_number"] is None and got["has_titleblock"], str(got))

    got, _ = ocr.read([mm("KR22-031295/1", 60.0, 20.0)])
    ok &= check("без подписей шифр не берётся", got["document_code"] is None
                and not got["has_titleblock"], "паспорта оборудования давали 418 ложных шифров")

    # Новослободская F0134 стр. 14: лист 6.1 вставлен между шестым и седьмым
