def row(page, sheet=None, code=None, source="OCR_CORNER", code_source=None, fid="F1", **extra):
    return {"file_id": fid, "pdf_page_number": page, "document_sheet_number": sheet,
            "document_code": code, "sheet_source": source if sheet is not None else None,
            "code_source": code_source or (source if code else None), **extra}


def test_sequence():
    ok = True
    rows = [row(10, 1), row(11, 2), row(12, 9), row(13, 4), row(14, 5)]
    stats = sheet_sequence.check(rows)
    r12 = rows[2]
    ok &= check("номер против соседей с обеих сторон снимается",
                r12["sheet_rejected"] == {"sheet": 9, "source": "OCR_CORNER"}, str(r12))
    ok &= check("на его место встаёт номер по ряду", r12["document_sheet_number"] == 3
                and r12["sheet_source"] == "SEQUENCE", str(r12))
    ok &= check("соседи подтверждены", stats["CONFIRMED"] == 4, str(dict(stats)))

    rows = [row(20, 5), row(21, sheet_candidate=6), row(30, sheet_candidate=7)]
    sheet_sequence.check(rows)
    ok &= check("слабое прочтение с подтверждением соседа принимается",
                rows[1]["document_sheet_number"] == 6 and rows[1]["sheet_source"] == "OCR_CELL_WEAK")
    ok &= check("слабое прочтение без соседа отбрасывается", rows[2]["document_sheet_number"] is None)

    good, bad = "АНО/150321/1-П-ИОС5.5.5", "АНО/150371/1-П-ИОСЪ.5.5"
    rows = [row(1, 1, good, source="TEXT_LAYER", fid="F0"), row(2, 2, good, source="TEXT_LAYER", fid="F0"),
            row(40, 1, good), row(41, 2, bad), row(42, 3, bad), row(43, 4)]
    sheet_sequence.check(rows)
    ok &= check("шифр из слоя побеждает систематическую ошибку распознавания",
                [r["document_code"] for r in rows[2:]] == [good] * 4,
                str([r["document_code"] for r in rows[2:]]))
    ok &= check("прочитанный шифр сохраняется", rows[3].get("document_code_read") == bad)

    rows = [row(1, 1, "АНО/150321/1-П-ИОС5.7.3.1ПЗ", source="TEXT_LAYER"),
            row(2, 2, "АНО/150321/1-П-ИОС5.7.3.1"), row(3, 3, "АНО/150321/1-П-ИОС5.7.3.1")]
    rows[1]["code_source"] = rows[2]["code_source"] = "TEXT_LAYER"
    sheet_sequence.check(rows)
    ok &= check("шифр из текстового слоя не заменяется",
                rows[0]["document_code"] == "АНО/150321/1-П-ИОС5.7.3.1ПЗ")

    rows = [row(50, 1, "Х-ОВ1"), row(51, 2, "Х-ОВ1"), row(52), row(53, 4, "Y-ВК-ZZZZ"), row(54, 5, "Y-ВК-ZZZZ")]
    sheet_sequence.check(rows)
    ok &= check("пропуск между разными шифрами не заполняется", rows[2]["document_sheet_number"] is None)
    rows = [row(50, 1, "Х-ОВ1"), row(51, 2, "Х-ОВ1"), row(52), row(53, 4, "Х-ОВ1"), row(54, 5, "Х-ОВ1")]
    sheet_sequence.check(rows)
    ok &= check("пропуск внутри ряда заполняется", rows[2]["document_sheet_number"] == 3)
    return ok


