def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def w(t, x0, y0, x1, y1):
    """Слово текстового слоя, координаты в долях страницы."""
    return {"t": t, "bbox": [x0, y0, x1, y1]}


def mm(t, dx, dy, conf=90.0):
    """Слово распознанного угла, миллиметры от правого нижнего угла."""
    return {"t": t, "dx": dx, "dy": dy, "conf": conf}


