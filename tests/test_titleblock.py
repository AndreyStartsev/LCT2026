def test_document_code():
    ok = True
    # Ведущие группы шифра не теряются
    w_gp = [w("01-07/23-14-РД-ГП", 0.70, 0.90, 0.90, 0.93)]
    got = titleblock.document_code(w_gp)
    ok &= check("полный шифр генплана: префикс 01- не теряется", got == "01-07/23-14-РД-ГП", str(got))

    # Тире с пробелами внутри шифра
    w_nvs = [w("НВС-2025/03", 0.60, 0.92, 0.75, 0.95), w("–", 0.76, 0.92, 0.78, 0.95),
             w("СГ", 0.79, 0.92, 0.83, 0.95)]
    got = titleblock.document_code(w_nvs)
    ok &= check("тире с пробелами: марка СГ не теряется", got == "НВС-2025/03-СГ", str(got))

    # Подраздел через пробел
    w_ios = [w("НВС-2025/03-ИОС", 0.57, 0.95, 0.71, 0.97), w("2.1-", 0.715, 0.95, 0.74, 0.97),
             w("ПЗ", 0.75, 0.95, 0.77, 0.97)]
    got = titleblock.document_code(w_ios)
    ok &= check("подраздел через пробел: 2.1-ПЗ не теряется", got == "НВС-2025/03-ИОС 2.1-ПЗ", str(got))

    # Запятая в этапах/корпусах
    w_nsl = [w("НСЛ-17-02/2026-1,2-КЖ1.1.4", 0.60, 0.90, 0.85, 0.93)]
    got = titleblock.document_code(w_nsl)
    ok &= check("запятая в этапах: КЖ1.1.4 не теряется", got == "НСЛ-17-02/2026-1,2-КЖ1.1.4", str(got))

    # Отсечение экспертиз
    w_exp = [w("РФ-77-4-59-3-19-2022-1660", 0.70, 0.90, 0.95, 0.93)]
    got = titleblock.document_code(w_exp)
    ok &= check("номер заключения экспертизы отсекается", got is None, str(got))

    # Отсечение сертификатов
    w_cert = [w("RU.MCC.243.450.38885", 0.70, 0.90, 0.95, 0.93)]
    got = titleblock.document_code(w_cert)
    ok &= check("номер сертификата соответствия отсекается", got is None, str(got))

    # Отсечение поставщиков
    w_supp = [w("KR22-031295/1", 0.70, 0.90, 0.95, 0.93)]
    got = titleblock.document_code(w_supp)
    ok &= check("номер документа поставщика отсекается", got is None, str(got))

    # Отсечение адреса
    w_addr = [w("ВН.ТЕР.Г", 0.70, 0.90, 0.85, 0.93)]
    got = titleblock.document_code(w_addr)
    ok &= check("фрагмент адреса ВН.ТЕР.Г отсекается", got is None, str(got))

    # Колонтитул не берется
    w_header = [w("01-07/23-14-РД-ГП", 0.50, 0.05, 0.80, 0.08)]
    got = titleblock.document_code(w_header)
    ok &= check("верхний колонтитул игнорируется: поиск только в штампе", got is None, str(got))

    # Номер листа не приклеивается к шифру через пробел
    w_sheet_near = [w("АНО/150321/1-П-ПЗ1.2-СТ", 0.70, 0.95, 0.85, 0.96),
                    w("10", 0.95, 0.95, 0.96, 0.96)]
    got = titleblock.document_code(w_sheet_near)
    ok &= check("номер листа рядом не приклеивается к шифру", got == "АНО/150321/1-П-ПЗ1.2-СТ", str(got))

    # Перечни ГОСТов через запятую не превращаются в шифр
    got = titleblock.document_code([], text="21.1101-2013,ГОСТ 21.406-88,ГОСТ 21.210-2014")
    ok &= check("перечень ГОСТов через запятую отсекается", got is None, str(got))

    # Перечни СП через запятую не превращаются в шифр
    got = titleblock.document_code([], text="70.13330.2012,СП 45.1")
    ok &= check("перечень СП через запятую отсекается", got is None, str(got))
    return ok


