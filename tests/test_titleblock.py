def test_foreign_codes():
    """Шифры и служебные номера вне корпуса: отбор по контексту, а не по началу (#41)."""
    ok = True
    # шифры чужого проектировщика: раньше их убирал чёрный список начал «ДС-», «МС-», «УД-»
    for code in ("ДС-12/2024-АР", "МС-2023-01-КЖ", "УД-118/22-ЭОМ", "ВХ-2024-05-ОВ1",
                 "ДКН-16-2024-ПЗУ"):
        got = titleblock.document_code([w(code, 0.70, 0.90, 0.90, 0.93)])
        ok &= check(f"шифр «{code}» остаётся", got == code, str(got))

    # те же начала в служебных номерах: решает то, что стоит перед номером
    cases = [
        ("исх. № МС-2023-01-КЖ", "исходящее письмо"),
        ("Договор № ДС-12/2024-АР", "номер договора"),
        ("в заключении экспертизы № ДКН-16-62-157/23", "номер заключения экспертизы"),
        ("по 2.1 технических условий МПТЦ-КТУ-100127", "номер технических условий"),
        ("Поставщик: KR22-0042-ND", "номер поставщика"),
    ]
    for text, name in cases:
        got = titleblock.document_code([w(part, 0.60 + 0.03 * i, 0.90, 0.63 + 0.03 * i, 0.93)
                                        for i, part in enumerate(text.split())])
        ok &= check(f"{name} шифром не становится", got is None, str(got))

    # строчный хвост марки
    got = titleblock.document_code([w("23.009-Р-1-КЖ2.1и", 0.70, 0.90, 0.90, 0.93)])
    ok &= check("строчная буква после цифры остаётся в шифре", got == "23.009-Р-1-КЖ2.1и", str(got))
    got = titleblock.document_code([w("АНО/150321/1-П-ИОС5.5.5.", 0.60, 0.90, 0.80, 0.93),
                                    w("2.", 0.81, 0.90, 0.83, 0.93),
                                    w("Объектовая", 0.84, 0.90, 0.92, 0.93)])
    # Прежде кандидат дотягивался до «2.О» — первой буквы следующего предложения. Строчная
    # буква сразу за кандидатом («Объектовая») теперь обрывает его, и остаётся сам шифр.
    ok &= check("шифр не перебирается в соседнее предложение",
                got == "АНО/150321/1-П-ИОС5.5.5", str(got))

    # Новослободская F0121 стр. 22: разделитель базового обозначения — точка
    got = titleblock.document_code([w("2451.П.ДР.ГИ.ТЧ", 0.70, 0.90, 0.90, 0.93)])
    ok &= check("шифр на точках остаётся: два блока из одних букв", got == "2451.П.ДР.ГИ.ТЧ", str(got))

    # Речников F0252 стр. 19: у марки изделия блок из одних букв один
    got = titleblock.document_code([w("БР100.20.8", 0.70, 0.90, 0.90, 0.93)])
    ok &= check("марка изделия на точках шифром не становится", got is None, str(got))

    # Новослободская F0103 стр. 10: в надписи после шифра точка, следом слово «Лист»
    got = titleblock.document_code([w("НВС-2025/03-АТЗ.ПЗ.", 0.60, 0.95, 0.75, 0.96),
                                    w("Лист", 0.92, 0.93, 0.94, 0.94), w("5", 0.93, 0.95, 0.94, 0.96)])
    ok &= check("слово за точкой не приклеивается к шифру", got == "НВС-2025/03-АТЗ.ПЗ",
                f"{got}; прежде НВС-2025/03-АТЗ.ПЗ.Л")

    # Новослободская F0129 стр. 30: адрес в надписи кончается на «…стр.1.», следом шифр
    got = titleblock.document_code([w("стр.1.", 0.60, 0.95, 0.64, 0.96),
                                    w("24-392-П-ИОС5.2", 0.66, 0.95, 0.80, 0.96)])
    ok &= check("конец адреса не приклеивается к шифру слева", got == "24-392-П-ИОС5.2",
                f"{got}; прежде 1.24-392-П-ИОС5.2")
    return ok


