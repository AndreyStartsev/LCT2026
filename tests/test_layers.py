def test_roof_record():
    """Кровля с добавленным слоем — «нарушения нет» у своих типов (R4-Q-AR-044, точки SPEC-0009, SPEC-0010)."""
    from pipeline import matrix_rules as mr

    def stack(*kinds):
        return [{"kind": k, "mm": None, "text": k} for k in kinds]

    def cand(stage, key, got):
        return {"file_id": f"{stage}1", "page": 1, "document": f"{stage.lower()}-АР.pdf", "stage": stage, "key": key,
                "value": layers.show(got), "raw": layers.show(got), "layers": got, "form": "list", "snippet": key}

    pd = stack("waterproofing", "primer", "screed", "slope", "insulation", "vapor", "base")
    rd = stack("waterproofing", "primer", "screed", "slope", "separation", "insulation", "vapor", "base")
    rule = {"kind": "layer_stack", "profile": "roof", "compare": {"type": "keyed", "result": "CONFIGURATION_MISMATCH"}}
    catalog = {"AR-044": {"parameter_name": "Послойный состав пирога кровли", "criticality": "Существенное"}}
    f = mr.keyed_findings("OBJ", "AR-044", rule, {"PD": [cand("PD", "II", pd), cand("PD", "III", pd)],
                                                  "RD": [cand("RD", "II", rd), cand("RD", "III", rd)]}, catalog)[0]
    ok = check("добавлен слой — «нарушения нет», разница без нарушения",
               f["violation_label"] == "NO_VIOLATION" and f["comparison_result"] == "NON_TRIGGERING_DIFFERENCE_NO_DECREASE",
               f["extraction"]["detail"])
    ok &= check("запись стоит у своих типов, а не у здания", f["locations"] == ["тип II", "тип III"], str(f["locations"]))
    ok &= check("в пояснении — какие слои добавлены", "тип II: разделительный слой" in f["extraction"]["detail"])
    gone = stack("waterproofing", "primer", "screed", "slope", "vapor", "base")
    f = mr.keyed_findings("OBJ", "AR-044", rule, {"PD": [cand("PD", "II", pd)], "RD": [cand("RD", "II", gone)]}, catalog)[0]
    ok &= check("исключённый слой — нарушение", f["violation_label"] == "VIOLATION_PRESENT"
                and "исключён слой: утеплитель" in f["extraction"]["detail"], f["extraction"]["detail"])
    return ok


