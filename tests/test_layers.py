def test_roof():
    lst = layers.roof(PD_ROOF)
    ok = check("список записки: тип II", [s["key"] for s in lst if s["form"] == "list"] == ["II"])
    shown = layers.show(lst[0]["layers"])
    ok &= check("«плитка 60 мм/ стяжка 30 мм» — два слоя", shown.startswith("плитка 60 мм; стяжка 30 мм"), shown)
    ok &= check("пояснение «(поднять … утеплителя - 200мм)» — не слой утеплителя",
                "утеплитель" not in shown, shown)
    pd, rd = layers.roof(PD_CALLOUT), layers.roof(RD_CALLOUT)
    ok &= check("выноски обеих стадий разобраны", len(pd) == 1 and len(rd) == 1, f"{len(pd)} / {len(rd)}")
    pairs = layers.pair(pd, rd, "roof")
    ok &= check("выноска РД без номера типа связана по сходству набора", pairs and "сходству" in pairs[0][3])
    d = layers.differences(pairs[0][1]["layers"], pairs[0][2]["layers"], thickness=False, ignore={"base"})
    ok &= check("добавлен разделительный слой — изменение состава", d == ["добавлен слой: разделительный слой"], str(d))
    d = layers.differences(pairs[0][1]["layers"], pairs[0][2]["layers"], thickness=False, ignore={"base"}, added=False)
    more = layers.added_layers(pairs[0][1]["layers"], pairs[0][2]["layers"], ignore={"base"})
    ok &= check("у кровли добавленный слой — признак, а не нарушение (R4-Q-AR-044)",
                d == [] and more == ["разделительный слой"], f"{d} / {more}")
    cut = [l for l in rd[0]["layers"] if l["kind"] not in ("vapor", "base")]
    ok &= check("выноска оборвалась до плиты — «исключён слой» не утверждается",
                layers.differences(pd[0]["layers"], cut, thickness=False, complete=False, ignore={"base"})
                == ["добавлен слой: разделительный слой"])
    return ok


