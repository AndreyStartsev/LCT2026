def test_pavement():
    pd, rd = layers.pavement(PD_PAVEMENT), layers.pavement(RD_PAVEMENT)
    by = {s["key"]: s for s in pd}
    ok = check("типы ПД разобраны", sorted(by) == ["2", "4", "6"], str(sorted(by)))
    ok &= check("слои ТИП 2 с толщинами в мм, грунтовые воды — не слой",
                layers.show(by["2"]["layers"]) == "асфальтобетон 50 мм; асфальтобетон 90 мм; щебень 200 мм; "
                                                   "геотекстиль; песок 450 мм; геотекстиль", layers.show(by["2"]["layers"]))
    ok &= check("бетон бортового камня в состав площадки не входит",
                "бетон основания" not in layers.show(by["4"]["layers"]), layers.show(by["4"]["layers"]))
    pairs = {k: (p, r, how) for k, p, r, how in layers.pair(pd, rd, "pavement")}
    ok &= check("ТИП 2.1 РД связан с ТИП 2 ПД по назначению",
                pairs["2.1"][0]["key"] == "2" and "назначению" in pairs["2.1"][2], pairs["2.1"][2])
    d = layers.differences(pairs["2.1"][0]["layers"], pairs["2.1"][1]["layers"])
    ok &= check("асфальт заменён плиткой по бетону, песок тоньше — нарушение",
                "исключён слой: асфальтобетон" in d and "добавлен слой: плитка" in d
                and "песок: толщина 450 → 400 мм" in d, str(d))
    ok &= check("тот же ТИП 2 — без изменений", layers.differences(pairs["2"][0]["layers"], pairs["2"][1]["layers"]) == [])
    ok &= check("цветник 200 → 400 мм — толщина больше, не нарушение",
                layers.differences(pairs["6"][0]["layers"], pairs["6"][1]["layers"]) == [])
