def test_presence_decision():
    """Решение по наличию: исключение решения целиком против разницы в словах (#84)."""
    ok = True
    rule = {"compare": {"type": "presence", "result_ok": "DRAINAGE_NOT_EXCLUDED"}}
    def side(names):
        return {"value": float(len(names)), "raw": "PRESENT", "columns": names}
    label, result, _ = decide(rule, side(["лотки", "дренаж"]), side(["лотки"]))
    ok &= check("пропажа одного слова из двух нарушением не считается",
                label == "NO_VIOLATION" and result == "DRAINAGE_NOT_EXCLUDED", f"{label} {result}")
    label, result, detail = decide(rule, side(["лотки", "дренаж"]), side([]))
    ok &= check("исключение решения целиком — нарушение",
                label == "VIOLATION_PRESENT" and result == "MISSING_DESIGN_ELEMENT", f"{label} {result}")
    label, _, _ = decide(rule, side(["дренаж"]), side(["лотки"]))
    ok &= check("разные слова об одном решении — не нарушение", label == "NO_VIOLATION")
    return ok


def test_height_decision():
    """Решение по ограждению: занижение высоты и замена типа (#84)."""
    ok = True
    rule = {"compare": {"type": "decrease_or_text_change"}}
    def side(height, row):
        return {"value": height, "raw": f"h={height} м", "columns": [row]}
    same_pd = side(2.0, "11 Ограждение территории, секция забора 2, h=2,0м 174.45")
    same_rd = side(2.0, "21 Ограждение территории, секция забора 2, h=2,0м 174.45")
    label, result, _ = decide(rule, same_pd, same_rd)
    ok &= check("номер позиции у стадий разный, а строка одна — не нарушение",
                label == "NO_VIOLATION" and result == "EQUAL_PD_RD", f"{label} {result}")
    label, result, _ = decide(rule, same_pd, side(1.5, "21 Ограждение территории, секция забора 2, h=1,5м 174.45"))
    ok &= check("занижение высоты — нарушение",
                label == "VIOLATION_PRESENT" and result == "DIMENSION_REDUCED", f"{label} {result}")
    label, result, _ = decide(rule, same_pd, side(2.0, "21 Ограждение территории, сетка рабица, h=2,0м 174.45"))
    ok &= check("замена типа при той же высоте — нарушение",
                label == "VIOLATION_PRESENT" and result == "VALUE_MISMATCH", f"{label} {result}")
    return ok


