def test_decisions():
    ok = True
    num = lambda v, raw: {"value": v, "raw": raw}
    rule = lambda t, thr=None: {"compare": {"type": t, **({"threshold": thr} if thr else {})}}
    ok &= check("уменьшение озеленения — нарушение",
                decide(rule("decrease"), num(3694.6, "3694,60"), num(3663.1, "3663,10"))[0]
                == "VIOLATION_PRESENT")
    ok &= check("увеличение при правиле «уменьшение» — не нарушение",
                decide(rule("decrease"), num(16, "16"), num(27, "27"))[0] == "NO_VIOLATION")
    label, result, _ = decide(rule("any_change"), num(159.95, "159,95"), num(159.95, "159.95"))
    ok &= check("159,95 и 159.95 равны после приведения точности",
                label == "NO_VIOLATION" and result == "EQUAL_AFTER_DECIMAL_NORMALIZATION",
                f"{label} {result}")
    ok &= check("появление покрытия с нуля — нарушение при пороге 5%",
                decide(rule("relative", 0.05), num(0.0, "0"), num(129.0, "129,0"))[0]
                == "VIOLATION_PRESENT")
    ok &= check("значение только в одной стадии — сравнение невозможно",
                decide(rule("decrease"), num(10, "10"), None)[0] == "COMPARISON_IMPOSSIBLE")
    order = ["С0", "С1", "С2", "С3"]
    ok &= check("понижение класса пожарной опасности — нарушение",
                decide({"compare": {"type": "class_downgrade"}}, {"value": "С0", "raw": "С0"},
                       {"value": "С1", "raw": "С1"}, order)[0] == "VIOLATION_PRESENT")
    return ok


