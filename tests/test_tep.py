# Ярлык рулонного материала в ИД кровли ДОО на Полярной 25 (DOO25-000769, стр. 31)
PACKAGE = ("ТУ 5774-005-96067115-2012 Количество мест 400 Дата изготовления __ 24.07.2023г. "
           "Масса нетто 18 519,70кг.")


def test_foreign_context():
    ok = True
    rules = load_rules(QUEUES[1])
    P, classes = rules["parameters"], rules["classes"]
    got = lambda code, text, stage: [c["raw"] for c in extract(P[code], text, classes.get(P[code].get("class")),
                                                               {"stage": stage})]
    ok &= check("нагрузка из условий подключения в рабочей стадии — не нагрузка объекта",
                got("PZ-017", TU_HEAT, "RD") == [], str(got("PZ-017", TU_HEAT, "RD")))
    ok &= check("в проектной стадии условия подключения — источник, который называет каталог",
                got("PZ-017", TU_HEAT, "PD") == ["24,376"], str(got("PZ-017", TU_HEAT, "PD")))
    ok &= check("категория надёжности из договора присоединения в рабочей стадии — не категория по схеме ВРУ",
                got("PZ-015", TU_POWER, "RD") == [] and got("PZ-015", TU_POWER, "RD_ID_MIXED") == [])
    ok &= check("та же категория в проектной стадии остаётся", got("PZ-015", TU_POWER, "PD") == ["III"])
    ok &= check("категория в общих данных рабочей стадии остаётся",
                got("PZ-015", "Категория надежности электроснабжения – II. Система заземления TN-C-S", "RD") == ["II"])
    ok &= check("«Количество мест» на ярлыке упаковки — не вместимость", got("PZ-013", PACKAGE, "ID") == [])
    ok &= check("вместимость в ТЭП остаётся",
                got("PZ-013", "Количество мест 600 Количество классов 24 Общая площадь", "PD") == ["600"])
    # приложение ПЗ Октябрьской (стр. 351): сертификат на подстанцию, у здания I степень
    cert = ("кВ типа (2)БКТП» Серийный выпуск. ОКПД2 27.11.4 Предел огнестойкости по ГОСТ 30247.1-94 соответствует "
            "показателю RE 90. Степень огнестойкости - II. Приложение на бланке № 01184.")
    ok &= check("степень огнестойкости из сертификата на изделие — не степень здания", got("PZ-022", cert, "PD") == [],
                str(got("PZ-022", cert, "PD")))
    listed = ("Степень огнестойкости: - поземная автостоянка – I (первая); - Жилые секции (Корпуса 1 и 2) высотой "
              "более 50 м (не более 75 м) – I (первая); Класс конструктивной пожарной опасности - С0.")
    ok &= check("степень огнестойкости частей здания перечнем читается", got("PZ-022", listed, "PD") == ["I"],
                str(got("PZ-022", listed, "PD")))
    ok &= check("степень сразу за подписью — как прежде",
                got("PZ-022", "Степень огнестойкости – II. Класс конструктивной пожарной опасности – С0.", "PD") == ["II"])
    return ok


