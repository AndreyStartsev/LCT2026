from pipeline import demolition, lighting, matrix_rules, metering, protocol  # noqa: E402


def check(name, condition, detail=""):
    mark = "ок  " if condition else "СБОЙ"
    print(f"  [{mark}] {name}" + (f"   {detail}" if detail else ""))
    return bool(condition)


def kinds(text):
    return [k for k, _ in demolition.statements(text)]


def test_demolition():
    ok = True
    ok &= check("«подлежащие сносу, на объекте отсутствуют» — сноса нет (ПЗУ Тюменской-5)",
                kinds("Инженерные коммуникации, подлежащие выносу в границах участка, отсутствуют. Сооружения и "
                      "строения, подлежащие сносу, на объекте отсутствуют.") == ["NOT_APPLICABLE"])
    got = kinds("В настоящее время на участке строительства расположены объекты капитального строительства, "
                "которые подлежат сносу (разрабатывается отдельным проектом).")
    ok &= check("«подлежат сносу (разрабатывается отдельным проектом)» — отдельный проект (Речников)",
                "SEPARATE_PROJECT" in got, str(got))
    ok &= check("«Снос и демонтаж будет производится в рамках отдельного проекта»",
                kinds("которые подлежат сносу. Снос и демонтаж будет производится в рамках отдельного проекта.")
                .count("SEPARATE_PROJECT") == 1)
    ok &= check("«Здания и сооружения … подлежат демонтажу в соответствии с разделом ПОД» — снос есть",
                kinds("Здания и сооружения, расположенные на участке, подлежат демонтажу в соответствии с разделом "
                      "«Проект организации работ по сносу или демонтажу объектов капитального строительства».")
                == ["APPLICABLE"])
    ok &= check("«сносимых зданий» в ПОС — снос есть", kinds("конструкций сносимых зданий по завершению работ") == ["APPLICABLE"])
    for text in ("с) Сведения о предполагаемых затратах, связанных со сносом зданий и сооружений, переселением людей",
                 "Федеральный закон от 30 декабря 2009 г. № 384-ФЗ «Технический регламент о безопасности зданий и сооружений»",
                 "Часть 4. Мероприятия по обращению с отходами строительства и сноса",
                 "МДС 12-46.2008 «Методические рекомендации по разработке и оформлению проекта организации работ по сносу (демонтажу)»"):
        ok &= check(f"шаблон не ответ: «{text[:60]}…»", kinds(text) == [], str(kinds(text)))
    got = demolition.decide([("APPLICABLE", "F1", 2, "сносимых зданий"), ("NOT_APPLICABLE", "F2", 3, "отсутствуют"),
                             ("SEPARATE_PROJECT", "F3", 4, "отдельным проектом")])
    ok &= check("отдельный проект сильнее «снос есть», «снос есть» сильнее «сноса нет»",
                got["status"] == "SEPARATE_PROJECT" and got["evidence"][0]["file_id"] == "F3", str(got))
    ok &= check("ничего не сказано — неизвестно", demolition.decide([])["status"] == "UNKNOWN")
    ok &= check("«приступать после выноса коммуникаций из пятна застройки по отдельному проекту» — сети выносятся "
                "до работ (R4-Q-POD-092)",
                bool(demolition.NETWORKS_SEPARATE.search(
                    "2. К работам приступать после выноса коммуникаций из пятна застройки по отдельному проекту, "
                    "получившему положительное заключение")))
    ok &= check("вынос одной сети отдельным проектом — не вынос всех сетей",
                not demolition.NETWORKS_SEPARATE.search("вынос сети выполняется АО \"Мосводоканал\" отдельным проектом"))
    ok &= check("том «7. ТР снос …» и шифр «-П-ПОД1» по имени файла",
                bool(demolition.FILE_NAME.search("7. ТР снос Алтуфьевское ш 79Б корр"))
                and bool(demolition.FILE_NAME.search("01-07-22-14-П-ПОД1"))
                and not demolition.FILE_NAME.search("01-07-22-14-П-ПОДЗЕМНАЯ"))
    return ok


def test_lighting():
    ok = True
    got = [x["value"] for x in lighting.light_sources(
        "- в качестве источников света используются энергоэкономичные светодиодные источники с")]
    ok &= check("проект: «энергоэкономичные светодиодные источники» (ЭЭ Речникова)", got == ["светодиодные"], str(got))
    got = [x["value"] for x in lighting.light_sources("Условно-графические обозначения - Светильник светодиодный накладной 12 Вт, IP65")]
    ok &= check("рабочая стадия: условные обозначения ЭО", got == ["светодиодные"], str(got))
    got = [x["value"] for x in lighting.light_sources(
        "Освещение здания выполнено светильниками с люминесцентными и энергосберегающими лампами.")]
    ok &= check("«с люминесцентными и энергосберегающими лампами» (АР Тюменской-5)", got == ["люминесцентные"], str(got))
    for text in ("внедрение энергоэффективных (галогенных, люминесцентных и светодиодных) светильников с",
                 "освещения помещений с заменой ламп накаливания, люминесцентных ламп, выключателей",
                 "освещенность помещений: от люминесцентных ламп не менее 150 лк; от ламп накаливания",
                 "Светильник ручной, 60Вт Е27, провод 12м РВО-220/12м 70 Лампа накаливания местного освещения 12В",
                 "Прожекторы ПЗС-45 могут быть заменены на прожекторы специального назначения с галогенными лампами",
                 "Лампы накаливания, утратившие потребительские свойства. Код по ФККО",
                 # датчик движения в ЭОМ Полярной 16 и лампа в спецификации щита учёта (#109)
                 "Угол обзора 360° Коммутационная нагрузка до 2000 Вт (лампы накаливания) до 1000 Вт "
                 "(люминесцентные лампы, LED) Время задержки 10(±3) с",
                 "Выключатель автоматический 1п 6А 220В хар. С ВМ63-1С6-10УХЛ3 «КЭАЗ» 1 Или аналог Лампа "
                 "накаливания 25Вт ЛН-25 1 Или аналог Коробка испытательная переходная",
                 # выбор оставлен открытым: требование к наружному освещению в томе ЭН ДОО (#110)
                 "светильники консольного, венчающего или подвесного типа с газоразрядным источником ДНаТ, МГЛ, "
                 "или с источником света LED, тип светильника"):
        got = [x["value"] for x in lighting.light_sources(text) if x["value"] != "светодиодные"]
        ok &= check(f"не значение: «{text[:56]}…»", got == [], str(got))
    got = [x["value"] for x in lighting.light_sources("Светильник НПП 2602 с лампой накаливания 60 Вт, IP54")]
    ok &= check("лампа в строке светильника — значение", got == ["накаливания"], str(got))
    ok &= check("проект светодиодные, в РД люминесцентные — нарушение",
                lighting.decide({"светодиодные"}, {"светодиодные", "люминесцентные"})[:2]
                == ("VIOLATION_PRESENT", "CONFIGURATION_MISMATCH"))
    ok &= check("проект сам называет и светодиодные, и люминесцентные — люминесцентные в РД не замена (#110)",
                lighting.decide({"светодиодные", "люминесцентные"}, {"светодиодные", "люминесцентные"})[0]
                == "NO_VIOLATION")
    ok &= check("светодиодные в обеих стадиях — нарушения нет",
                lighting.decide({"светодиодные"}, {"светодиодные"})[:2] == ("NO_VIOLATION", "EQUAL_PD_RD"))
    ok &= check("в РД не названо — сравнение невозможно",
                lighting.decide({"светодиодные"}, set())[0] == "COMPARISON_IMPOSSIBLE")
    return ok


def test_meters():
    ok = True
    cases = [
        ("Монтажная схема подключения активного счетчика Энергомера CE308 в сети 380В", "электроэнергия"),
        ("Для учета расхода воды на вводе в здание устанавливается общий водомерный узел с водосчетчиком", "вода"),
        ("4.Фильтр магнитный фланцевый ФМФ Ø80 Водоприбор шт 1 или аналог 159. 5.Счетчик крыльчатый ВСХ-40 Водоприбор", "вода"),
        ("АНО/150321/1-РД-ИТП.УУТЭ Индивидуальный тепловой пункт. Узел учета тепловой энергии", "тепловая энергия"),
    ]
    for text, resource in cases:
        got = {m["key"] for m in metering.meters(text)}
        ok &= check(f"{resource}: «{text[:50]}…»", resource in got, str(got))
    got = metering.meters("установить пломбы на приборах учета (узлах учета) холодной воды, кранах, фланцах")
    ok &= check("договор водоснабжения «приборы учета (узлы учета)» не прибор", got == [], str(got))
    ok &= check("назван в обеих стадиях — нарушения нет",
                metering.decide("вода", True, True, True)[:2] == ("NO_VIOLATION", "EQUAL_PD_RD"))
    got = metering.decide("тепловая энергия", True, False, False)
    ok &= check("в РД нет тома раздела — сравнение невозможно с причиной",
                got[0] == "COMPARISON_IMPOSSIBLE" and "ОВ в комплекте нет" in got[2], str(got))
    got = metering.decide("тепловая энергия", True, False, True)
    ok &= check("том раздела есть, прибора в тексте нет — всё равно не нарушение",
                got[0] == "COMPARISON_IMPOSSIBLE" and "не найден" in got[2], str(got))
    return ok


def test_sources_and_protocol():
    ok = True
    rule = {"source_names": {"source_pd": ["ЭЭ", "ИОС"], "source_rd": ["*"]}}
    cat = {"source_pd": "Спецификации светильников (ЗУ/ИОС1)", "source_rd": "Спецификация оборудования (ЭОМ)"}
    ok &= check("разделы-источники из правила", matrix_rules.rule_hints(rule, cat, "source_pd") == {"ЭЭ", "ИОС"})
    ok &= check("«*» — источник не ограничен", matrix_rules.rule_hints(rule, cat, "source_rd") == set())
    ok &= check("без правила — из каталога", matrix_rules.rule_hints({}, cat, "source_rd") == {"ЭОМ", "ЭМ", "ЭО"})
    catalog = [{"parameter_id": 90, "parameter_code": "POD-090", "parameter_name": "Зоны развала", "pd_section": "Раздел 7. ПОД"},
               {"parameter_id": 91, "parameter_code": "POD-091", "parameter_name": "Методы", "pd_section": "Раздел 7. ПОД"}]
    rules = {4: {"parameters": {"POD-090": {"implemented": False, "reason": "ППР нет", "applies_if": "demolition"},
                                "POD-091": {"implemented": False, "reason": "ППР нет", "applies_if": "demolition"}}}}
    applicability = [{"parameter_code": "POD-090", "status": "NOT_APPLICABLE", "reason": "сноса на объекте нет: «…»"},
                     {"parameter_code": "POD-091", "status": "APPLICABLE", "reason": "снос на объекте предусмотрен"}]
    cov = {c["parameter_code"]: c for c in protocol.coverage(catalog, rules, [], {"PD", "RD"}, applicability)}
    ok &= check("протокол: сноса нет — NOT_APPLICABLE с цитатой",
                cov["POD-090"]["status"] == "NOT_APPLICABLE" and cov["POD-090"]["reason"].startswith("сноса"), str(cov["POD-090"]))
    ok &= check("протокол: снос есть — прежний NOT_CHECKED с причиной правила",
                cov["POD-091"]["status"] == "NOT_CHECKED" and cov["POD-091"]["reason"] == "ППР нет", str(cov["POD-091"]))
    cov = {c["parameter_code"]: c for c in protocol.coverage(catalog, rules, [], {"PD", "RD"})}
    ok &= check("протокол без проверки применимости работает как раньше", cov["POD-090"]["status"] == "NOT_CHECKED")
    return ok


def main():
    ok = True
    for title, fn in (("Применимость ПОД", test_demolition), ("Источники света", test_lighting),
                      ("Приборы учёта", test_meters), ("Источники и протокол", test_sources_and_protocol)):
        print(f"\n{title}")
        ok &= fn()
    print("\nИТОГ:", "все проверки пройдены" if ok else "ЕСТЬ СБОИ")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
