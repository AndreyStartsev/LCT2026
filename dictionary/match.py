"""Поиск терминов словаря в тексте. Задача #5.

Точное вхождение строки не работает по двум причинам, и обе выяснились на корпусе.

**Ё и Е.** В словаре «тёплый пол», в документах «теплые полы». Поиск по точной
строке даёт ноль страниц, хотя термин есть на трёх.

**Русская морфология.** В словаре «вытяжная вентиляция», в документах «вытяжной
вентиляцией», «вытяжные установки», «приточно-вытяжная». Точное вхождение даёт
ноль, а на деле термин встречается на 112 страницах.

Поэтому сопоставление идёт по основам слов: каждое значимое слово термина
усекается до основы, и термин считается найденным, если все его основы есть
в тексте. Это грубее лемматизации, но не требует словаря форм и на строительной
лексике ведёт себя предсказуемо.
"""
import re

WORD = re.compile(r"[а-яa-z0-9]+", re.I)
# Хвосты, которые русская морфология навешивает на прилагательные и существительные.
# Порядок важен: длинные раньше коротких.
_ENDINGS = """
ированных ированный ованными ающими ающего ования ованный ается
ыми ими ого его ему ому ах ях ой ей ою ею ую юю ая яя ое ее ые ие ый ий ых их
ом ем ов ев ам ям у ю а я ы и е о й ь
""".split()
# длинные окончания проверяются раньше коротких, иначе «теплый» усечётся до «теплы»,
# а «теплые» до «тепл», и одно слово перестанет совпадать с самим собой
ENDINGS = tuple(sorted(_ENDINGS, key=len, reverse=True))

# Порог в 4 символа не даёт усечь короткие слова: «полов» и «полы» оставались
# разными, и «тёплый пол» не находился там, где он есть. Три символа работают.
MIN_STEM = 3


def fold(s):
    """Приведение к сравнимому виду: нижний регистр, ё как е, единые дефисы."""
    s = (s or "").lower().replace("ё", "е")
    return s.replace("‐", "-").replace("‑", "-").replace("–", "-").replace("—", "-")


def stem(word):
    """Грубая основа слова: срезаем известное окончание, если остаётся достаточно."""
    w = fold(word)
    if len(w) <= MIN_STEM:
        return w
    for end in ENDINGS:
        if w.endswith(end) and len(w) - len(end) >= MIN_STEM:
            return w[: len(w) - len(end)]
    return w


def stems(text):
    return [stem(w) for w in WORD.findall(fold(text))]


def variant_matches(variant, page_stems):
    """Все значимые основы варианта присутствуют на странице."""
    need = [s for s in stems(variant) if len(s) >= 3]
    if not need:
        return False
    return all(s in page_stems for s in need)


def term_matches(term, page_stems, page_text=None):
    """Термин найден, если совпал любой его вариант или марка."""
    for v in term.get("variants", []):
        if variant_matches(v, page_stems):
            return True
    pat = term.get("mark_pattern")
    if pat and page_text:
        # марка это короткий код вроде П5 или В17, основы к нему неприменимы
        rx = re.compile(pat.strip("^$"), re.I)
        for w in WORD.findall(page_text):
            if rx.fullmatch(w):
                return True
    return False


def index_page(text):
    """Подготовить страницу к поиску: множество основ считается один раз."""
    return set(stems(text))
