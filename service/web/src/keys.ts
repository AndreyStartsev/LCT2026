// Клавиши экрана верификации. Задача #43.
//
// Разбор вынесен из компонента: решение по нарушению принимается одной клавишей, и
// сочетание условий, при которых она срабатывает, должно читаться целиком. Раньше
// обработчик не смотрел ни на то, что открыто в центре экрана, ни на модификаторы:
// при открытом журнале или дозагрузке клавиша 1 подтверждала скрытого кандидата.

export type KeyAction = "next" | "prev" | "confirm" | "reject" | "clarify" | "escape" | null;

export interface KeyContext {
  key: string;
  /** Модификаторы: сочетания принадлежат браузеру и системе, решение по ним не принимается. */
  ctrl?: boolean;
  meta?: boolean;
  alt?: boolean;
  shift?: boolean;
  /** Тег элемента, на котором произошло событие: в поле ввода клавиши набирают текст. */
  tag?: string;
  /** Что открыто в центре экрана: решения — только у карточки находки. */
  center: "finding" | "files" | "audit" | "reupload" | "text" | "changes";
  /** Открыт просмотр страницы во весь экран. */
  viewer?: boolean;
  /**
   * Открыто окно поверх экрана: сопоставление листов, журнал обработки, подтверждение.
   * Под ним клавиши экрана не работают — иначе «1» подтверждала запись, которой не видно,
   * а ↓ меняла её под окном.
   */
  overlay?: boolean;
  /** Клавиша зажата и повторяется: решение — только по отдельному нажатию. */
  repeat?: boolean;
  /** Открыта форма с собственными клавишами: отклонение, отмена финализации. */
  formOpen?: boolean;
  /** В центре — кандидат без решения, и решение сейчас разрешено. */
  candidateOpen?: boolean;
  busy?: boolean;
}

const FIELDS = new Set(["INPUT", "TEXTAREA", "SELECT"]);

export function keyAction(c: KeyContext): KeyAction {
  if (c.ctrl || c.meta || c.alt || c.shift) return null;
  // Открытое окно (просмотр страницы, сопоставление, журнал, подтверждение) само закрывается
  // по Esc, и все клавиши, включая Esc, принадлежат ему: иначе Esc заодно закрывал бы форму
  // отклонения под окном.
  if (c.viewer || c.overlay) return null;
  // Esc отменяет форму и из поля ввода: в форме отклонения фокус после выбора причины
  // всегда в комментарии, а подсказка обещает «Esc — отмена»
  if (c.key === "Escape") return "escape";
  if (FIELDS.has((c.tag ?? "").toUpperCase())) return null;
  if (c.center !== "finding") return null;
  if (c.key === "ArrowDown" || c.key === "j") return "next";
  if (c.key === "ArrowUp" || c.key === "k") return "prev";
  if (c.formOpen || !c.candidateOpen || c.busy) return null;
  // Зажатая «1» повторяется: после перехода к следующему кандидату повтор подтвердил бы
  // и его, не прочитанного. Стрелкам повтор нужен, решениям — нет.
  if (c.repeat) return null;
  if (c.key === "1") return "confirm";
  if (c.key === "2") return "reject";
  if (c.key === "3") return "clarify";
  return null;
}

/** Подсказка по клавишам формы отклонения; у кнопок решений клавиша — цифрой на самой кнопке. */
export const REJECT_HINT = "1–5 — причина · Ctrl+Enter — отклонить · Esc — отмена";
