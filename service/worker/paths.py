"""Путь файла на диске воркера: длинные имена папок из пакета организатора.

Предел имени в файловой системе контейнера — 255 байт, а кириллица в UTF-8 весит два
байта на знак. В пакете организатора есть папка

    «10.1 Мероприятия по обеспечению соблюдения требований энергетической эффективности
     и требований оснащенности зданий, строений и сооружений приборами учета»

— 154 знака, 290 байт. Выкладка файлов процесса падала на ней с `OSError: [Errno 36]
File name too long`, и объект не разбирался вовсе: шаг повторялся трижды и уходил в отказ.
На macOS такая папка создаётся (APFS считает знаки, а не байты), поэтому в командной
строке разбор шёл, а через сервис — нет.

Имя укорачивается с сохранением начала: по началу пути разбор определяет стадию и раздел
(`pipeline/registry.py`), и «10.1 Мероприятия по обеспечению соблюдения требований
энергетической эффективности» в первые 200 байт помещается. К обрезанному имени
добавляется отпечаток полного имени, чтобы две длинные папки с общим началом не слиплись
в одну. Путь в базе и на экране инспектора остаётся полным: укорочение живёт только на
диске воркера, поэтому места, где путь из базы встречается с путём из разбора, переводят
его этой же функцией.
"""
import hashlib
import os

# Запас к пределу в 255 байт: место под отпечаток, расширение и разделители.
MAX_NAME_BYTES = 200
TAG_LEN = 8


def _extension(name):
    """Расширение имени файла, если это похоже на расширение.

    В именах томов точки стоят в номере: «V2_01-10-01-02-05_Том 10.1.pdf», а в названиях
    папок — и подавно («10.1 Мероприятия…»). Последняя точка — не всегда начало
    расширения, поэтому хвост принимается за расширение, только если он короткий
    и без пробелов.
    """
    stem, ext = os.path.splitext(name)
    if not ext or " " in ext or len(ext.encode("utf-8")) > 10:
        return name, ""
    return stem, ext


def _short(name, keep_extension):
    if len(name.encode("utf-8")) <= MAX_NAME_BYTES:
        return name
    stem, ext = _extension(name) if keep_extension else (name, "")
    tag = hashlib.sha256(name.encode("utf-8")).hexdigest()[:TAG_LEN]
    keep = MAX_NAME_BYTES - len(ext.encode("utf-8")) - TAG_LEN - 1
    cut = stem.encode("utf-8")[:max(keep, 1)].decode("utf-8", "ignore").rstrip()
    return f"{cut}~{tag}{ext}"


def disk_path(relative_path):
    """Путь файла внутри папки объекта на диске: длинные имена укорочены.

    Короткие пути возвращаются как есть, поэтому у объектов с обычными именами
    на диске ничего не меняется.
    """
    parts = [p for p in (relative_path or "").replace("\\", "/").split("/") if p not in ("", ".")]
    if not parts:
        return relative_path
    return "/".join(_short(p, keep_extension=(i == len(parts) - 1)) for i, p in enumerate(parts))
