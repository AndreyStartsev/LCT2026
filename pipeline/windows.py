"""Окна: число и площадь проёмов по ведомостям, ПД против РД (AR-046, #193).

Решения специалиста (R3-AR-046): при отсутствии ведомости окон в ПД можно не сравнивать; любое
уменьшение площади остекления — нарушение. В ПД открытых объектов ведомостей окон нет — они только в
РД (Алтуфьевское, Полярная 16, ДОО, Речников), поэтому на корпусе правило говорит «сравнение
невозможно» с причиной. Ведомость проёмов КР («ОК-1 1500х1250(h) -2,100» у Полярной 16) — отметки
проёмов в стенах, а не ведомость окон.

Ведомость — лист с названием («Ведомость окон, витражей», «Спецификация элементов заполнения оконных
проемов») и тремя и больше размерами проёмов «ширина х высота»: так отсекается ведомость рабочих
чертежей, где то же название стоит строкой перечня листов. Строки — «марка размер количество»:
«В-1 36210х9820(h) 1» (Алтуфьевское). Двери, ворота и люки не считаются. Другие раскладки таблицы
(«Кол-во, шт.» перед размером, как у Речникова) строками не разбираются — тогда сравнение по числу
невозможно, и это сказано в записи.
"""
import re

TITLE = re.compile(r"(?:спецификац\w*|ведомост\w*)\s+(?:и\s+схем\w*\s+)?(?:элемент\w*\s+)?(?:заполнени\w*\s+)?"
                   r"(?:(?:внутренн|наружн)\w*\s+)?(?:окон|оконн\w*|витражн\w*|витраж\w*)", re.I)
SIZE = re.compile(r"(?<![\d.,])\d{3,5}\s*[xх×*]\s*\d{3,5}(?![\d.,])")
MIN_SIZES = 3
ROW = re.compile(r"(?<![А-ЯЁA-Za-zа-яё0-9])(?P<mark>(?:ОК[БВЛ]?|ОБ|О|В[НВТЖ]?|ОП|Ок)[-\s]?\d{1,3}(?:\.\d{1,2})?[а-яё*]?)\s+"
                 r"(?P<w>\d{3,5})\s*[xх×*]\s*(?P<h>\d{3,5})(?:\s*\(h\))?\s+(?P<n>\d{1,4})(?![\d.,хx×])")


def schedule(flat):
    """Лист — ведомость окон: её название или None."""
    m = TITLE.search(flat)
    return " ".join(m.group(0).split()) if m and len(SIZE.findall(flat)) >= MIN_SIZES else None


def rows(flat):
    """Строки ведомости окон: [{mark, w, h, n}] — размеры в мм."""
    return [{"mark": re.sub(r"\s", "", m.group("mark")).upper(), "w": int(m.group("w")), "h": int(m.group("h")),
             "n": int(m.group("n"))} for m in ROW.finditer(flat)]


def totals(items):
    """Число окон и площадь проёмов, м², по строкам стадии: марка берётся один раз с наибольшим числом
    (одна ведомость лежит в нескольких файлах редакций и копий)."""
    best = {}
    for r in items:
        key = (r["mark"], r["w"], r["h"])
        best[key] = max(best.get(key, 0), r["n"])
    count = sum(best.values())
    area = round(sum(n * w * h for (_m, w, h), n in best.items()) / 1e6, 2)
    return count, area, best


def smaller_marks(pd, rd):
    """Марки, у которых проём в РД меньше проектного: [(марка, «ш×в» ПД, «ш×в» РД)]."""
    pd_by = {m: (w, h) for (m, w, h) in pd}
    out = []
    for (m, w, h) in rd:
        if m in pd_by and w * h < pd_by[m][0] * pd_by[m][1]:
            out.append((m, "{}х{}".format(*pd_by[m]), f"{w}х{h}"))
    return sorted(set(out))
