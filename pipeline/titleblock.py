"""Разбор основной надписи по ГОСТ Р 21.101-2020. Задача #2.

Зачем: перечень нарушений организатора говорит номерами листов («в нарушение
листа 26 … шифр АНО/150321/1-П-ИОС5.4.2»), а формат сдачи требует номер страницы
PDF. В эталоне лист 26 тома ИОС5.4.2 это страница 104. Связку строит этот модуль.

Почему по координатам, а не по тексту: линейный текст чертежа перемешан по порядку
чтения, и в строке «Дымоудаление П 26 10. Кран шаровый» невозможно отличить номер
листа от номера пункта в списке. В основной надписи же значения стоят строго под
своими подписями, и это устойчиво.

Алгоритм:

1. Ищем подписи «Стадия», «Лист», «Листов» в правой нижней четверти листа.
2. Берём полосу сразу под ними и читаем слева направо: сначала обозначение стадии,
   потом первое целое число. Это лист. Точное попадание в колонку не требуется:
   колонки узкие и разъезжаются, а порядок значений постоянен.
3. Шифр документа ищем отдельно по образцу: он встречается и в надписи, и в штампе.
4. Если подписей нет (лист без основной надписи, титул, приложение), номер листа
   не выдумываем, а возвращаем пусто.
"""
import re

from pipeline import coords

# Зона основной надписи (штампа). По ГОСТ Р 21.101 штамп формы 1 занимает 185 × 55 мм
# в правом нижнем углу листа независимо от формата. Доли листа 0,45 и 0,70 подобраны
# на А3 и А4 и на большом листе охватывают пол-чертежа: на А0 это правые 654 мм
# и нижние 252 мм вместо 185 × 55 (#41). Поэтому зона считается в миллиметрах листа,
# а доли остаются запасным вариантом, когда размер листа неизвестен.
TB_X, TB_Y = 0.45, 0.70
TB_WIDTH_MM = 230        # 185 мм графы плюс запас на рамку и подписи слева от неё
TB_HEIGHT_MM = 90        # 55 мм штампа плюс строки над ним («Формат А3», «Изм. Лист»)
TB_LABELS_MM = 210       # подписи «Стадия», «Лист», «Листов» стоят в правой части штампа
TB_SHEET_MM = 60         # графа «Лист» — в самой нижней части штампа


def band_bounds(page_size=None, width_mm=TB_WIDTH_MM, height_mm=TB_HEIGHT_MM,
                x_default=TB_X, y_default=TB_Y):
    """Левая и верхняя границы зоны штампа в долях листа.

    Зона только сужается: на А3 и А4 миллиметры дают почти те же доли, что были
    подобраны на корпусе, а на А1 и А0 — настоящий штамп вместо четверти чертежа.
    Расширять зону на А4 нельзя: слева от штампа там стоит таблица состава проекта,
    и шифр брался бы из чужой строки (#41).
    """
    size = coords.page_mm(page_size)
    if not size:
        return x_default, y_default
    w_mm, h_mm = size
    return max(x_default, 1 - width_mm / w_mm), max(y_default, 1 - height_mm / h_mm)

# Обозначение стадии: П проектная, Р рабочая, ИД исполнительная.
STAGE_TOKENS = {"П": "PD", "Р": "RD", "ИД": "ID", "И": "ID", "РД": "RD", "ПД": "PD"}

# Посторонние номера: экспертизы, сертификаты, стандарты, СРО, исходящие письма, оборудование, поставщики
EXCLUDE_RE = re.compile(
    r"^(?:"
    r"РФ-\d"                               # РФ-77-4-59-3-19-2022-1660 (экспертиза)
    r"|\d{2}-\d-\d{2}-\d-\d{2}"             # 77-4-59-3-19-... (номер экспертизы без РФ)
    r"|RU[-._]"                            # RU.MCC..., RU-RU..., RU.0001...
    r"|[A-ZА-Я]{1,2}-RU[-._]"              # C-RU.AY04..., СС-RU...
    r"|RA\.RU"                             # RA.RU.11HB11
    r"|POCC|РОСС"                          # POCC.RU..., РОСС RU...
    r"|ЕАЭС|EAЭС"                          # сертификаты ЕАЭС
    r"|ГОСТ"                               # ГОСТ-Р-54350-2015
    r"|СП(?:\.|\d)"                        # СП.256..., СП52...
    r"|СРО[-_]"                            # СРО-И-..., СРО-П-...
    r"|ГПЗУ"                               # ГПЗУ-...
    r"|ТУ\s|ТУ[-_]"                        # ТУ-...
    r"|СТУ[-_]"                            # СТУ-1-18-02
    r"|РД-?34"                             # РД34.21.122-87
    r"|ВКП[-_]|ВКЛ[-_]|ШПК[-_]"            # марки оборудования: «ВКП-60-МВЕ220-СН-125-НО-К-КК»
    r"|KR\d{2}[-_/]|ND\d{2,3}[-_/]"        # номера поставщиков и КП
    r"|ВН[-._]ТЕР[-._]Г|ВНТЕРГ"            # фрагмент адреса
    r")",
    re.IGNORECASE | re.UNICODE
)

# Служебные номера писем, договоров и счетов отсеиваются не по началу, а по тому,
# что стоит перед ними. Раньше в чёрном списке были начала «МС-», «ДС-», «УД-»,
# «ВХ-», «ИСХ-», «ДОГ-», и вместе с письмами отбрасывался бы настоящий шифр
# «ДС-12/2024-АР» или «МС-2023-01-КЖ», а следом брался посторонний кандидат (#41).
CONTEXT_RE = re.compile(
    r"(?:исх|вх|вых)\.?\s*(?:№|N)?\s*$"          # «исх. № …», «вх.№ …»
    r"|(?:письм|договор|контракт|сч[её]т|заявк|накладн|поручени|предписани|доверенност"
    r"|уведомлени|запрос|коммерческ\w*\s+предложени)\w*\s*(?:№|N|от)?\s*$"
    r"|(?:№|N)\s*(?:договора|контракта|сч[её]та|письма)\s*$"
    # «в заключении экспертизы № ДКН-16-62-157/23», «по 2.1 технических условий МПТЦ-КТУ-100127»
    r"|(?:заключени|экспертиз|разрешени|свидетельств|лиценз)\w*\s*(?:№|N)?\s*$"
    r"|техническ\w+\s+услови\w*\s*(?:№|N)?\s*$"
    r"|(?:поставщик|изготовител|производител)\w*\s*[:\s]$",
    re.IGNORECASE | re.UNICODE
)
CONTEXT_WINDOW = 40

# Ссылка на норматив отдельным блоком в любом месте кандидата, а не только в начале.
# В ведомости покрытий листов ГП Речникова «М800, ГОСТ 8267-93 - 0,35м» склеивался
# через запятую в «М800,ГОСТ 8267-93-0,35» и был длиннее шифра штампа. ГОСТ и СНиП
# в шифре не бывают, а СП, ОСТ, ТУ и СТО — только с номером: «НВС-2025/03-СП»
# и «01-07/22-14-П-СП» — марка «Состав проекта».
NORM_RE = re.compile(
    r"(?<![А-ЯЁA-Zа-яёa-z0-9])"                                      # начало блока, а не ПОСТ, ИСП, СТУ
    r"(?:(?:ГОСТ(?:\s*Р)?|СН[иИ]П)(?![А-ЯЁA-Z])(?:\s*[-./]?\s*\d)?"  # с цифрой номера: он бывает началом кандидата
    r"|(?:СП|ОСТ|ТУ|СТО(?:\s+[А-ЯЁA-Z]{2,})?)\s*[-./]?\s*\d)",        # СП 42.13330, СТО НОСТРОЙ 2.33.14
    re.UNICODE
)

# Шифр документа. Примеры из корпуса:
#   АНО/150321/1-П-ИОС5.4.2      Тюменская-5
#   01-07/23-14-РД-ГП            Речников 7-7
#   01-07.22-14-П-ПЗУ            Речников 7-7
#   НВС-2025.03-4.2-КР2          Новослободская
#   НВС-2025/03 – СГ             Новослободская (тире с пробелами)
#   НВС-2025/03-ИОС 2.1- ПЗ      Новослободская (подраздел через пробел)
#   НСЛ-17-02/2026-1,2-КЖ1.1.4   Новослободская (запятая в этапах)
#   23.009-Р-1-КЖ2.1             Октябрьская 103
#   ЖС-РД-270121-П-ОПЗ           Алтуфьевское 79Б
#   П-2025-04-266-КЖ01           Алтуфьевское 79Б
_SEP = r"(?:\s*[-–—/._]\s*)"
# Первый разделитель — особый: точка с пробелом перед шифром принадлежит предыдущему
# предложению, а не шифру. На Новослободской F0129 адрес в надписи кончается на «…стр.1.»,
# и шифр выходил «1.24-392-П-ИОС5.2». Внутри шифра такая точка встречается («ИОС 4.3. ГЧ»),
# поэтому правило действует только на стык с первым блоком.
_SEP_HEAD = r"(?:\s*[-–—/_]\s*|\.)"
_MID_BLOCK = r"(?:[А-ЯA-Z]{2,6}\s+\d+(?:\.\d+)*|\d+(?:,\d+)+|[А-ЯA-Z0-9]{1,10})"
# Строчная буква в конце марки — часть шифра: «23.009-Р-1-КЖ2.1и», «…-АР1а». Раньше она
# молча отрезалась, и шифр листа не сходился с шифром тома (#41). Буква берётся только
# сразу за цифрой и только одна: иначе кандидат перебирался бы в соседнее предложение
# основной надписи — «…-ИОС5.5.5. 2. Объектовая» давало «…5.5.5.2.Об»
_END_BLOCK = r"(?:[А-ЯA-Z0-9]{1,10}(?<=\d)[а-яa-z](?![а-яa-zА-ЯA-Z0-9])|[А-ЯA-Z0-9]{1,10})"
# Строчная буква сразу за кандидатом значит, что последний блок — начало обычного слова,
# а не марка: в слое Новослободской F0103 за «НВС-2025/03-АТЗ.ПЗ.» идёт «Лист», и шифр
# выходил «НВС-2025/03-АТЗ.ПЗ.Л». Строчный хвост самой марки («КЖ2.1и») этим не затронут:
# он входит в кандидата целиком по первому образцу _END_BLOCK.
CODE_RE = re.compile(
    rf"\b[А-ЯA-Z0-9]{{1,8}}{_SEP_HEAD}(?:{_MID_BLOCK}{_SEP})*{_END_BLOCK}(?<![._–—\s,-])(?![а-яa-z])",
    re.UNICODE
)

# Таблица изменений над основной надписью: номер изменения в колонке «Изм.», рядом вид
# изменения («Зам.», «Нов.», «Аннул.»), номер документа («420-24») и дата («21.06.24»).
REV_NUM_RE = re.compile(r"^\d{1,2}$")
REV_ROW_RE = re.compile(r"^(?:[Зз]ам|[Нн]ов|[Ии]зм|[Аа]ннул)\.?$|^\d{1,4}[-/]\d{2,4}$|^\d{2}\.\d{2}(?:\.\d{2,4})?$")
REV_LABEL_RE = re.compile(r"^[Ии]зм\.?$")


# Номер листа стоит в надписи сразу за шифром, и распознавание читает черту графы
# как подчёркивание: «АНО/150321/1-РД-ОВ1.С _ 12». Одно число после разделителя
# с пробелами — граница шифра, а не его последний блок: внутри шифра разделители
# пишутся слитно («КЖ2.1», «-1-»), а пробелы вокруг тире у слов-марок («НВС-2025/03 – СГ»)
# этим правилом не затрагиваются.
_TRAILING_NUMBER_RE = re.compile(r"(?:\s+[-–—/._]\s*|\s*[-–—/._]\s+)\d{1,4}$")


# Номер листа обычно целый, но встречается и дробный: на Новослободской F0134 листы 6.1
# и 6.2 вставлены между шестым и седьмым, и целым числом такой номер не записать — было 61.
_SHEET_INT_RE = re.compile(r"\d{1,3}")
_SHEET_FRACTION_RE = re.compile(r"\d{1,3}[.,]\d{1,2}")


def sheet_number(token):
    """Номер листа из слова графы: целое, дробное или None. «6,1» и «6.1» — одно и то же."""
    t = str(token).strip()
    if _SHEET_INT_RE.fullmatch(t):
        return int(t) or None
    if _SHEET_FRACTION_RE.fullmatch(t):
        return float(t.replace(",", ".")) or None
    return None


def whole_first(values):
    """Первое целое, и только если целых нет — первое дробное.

    Дробный номер принимается там, где целого в графе нет: иначе в колонку «Лист»
    попадала бы дата «12.24» из соседней графы, а она читается как дробное число.
    """
    for v in values:
        if isinstance(v, int):
            return v
    return values[0] if values else None


def _strip_trailing_number(s):
    """Отрезать номер листа, приклеенный к шифру через разделитель с пробелами."""
    cut = _TRAILING_NUMBER_RE.sub("", s)
    if cut == s:
        return s
    # Остаток разбирается заново: число через пробел допустимо только в середине шифра
    # («ИОС 2.1- ПЗ»), и без отрезанного конца оно шифру уже не принадлежит. Новослободская
    # F0124 стр. 11: «НВС-2025/03-ТБЭ 12 - 3» склеен с ячейками таблицы, шифр — «НВС-2025/03-ТБЭ».
    m = CODE_RE.match(cut)
    return m.group(0) if m else cut


def _dot_separated(cand):
    """Шифр, у которого роль разделителя базового обозначения играет точка.

    «2451.П.ДР.ГИ.ТЧ» (Новослободская, F0121) — шифр, «БР100.20.8» — бортовой камень
    из ведомости. Различает их число блоков из одних букв: по ГОСТ Р 21.101 буквами
    пишут и стадию, и марку, а у марки изделия такой блок один.
    """
    blocks = cand.split(".")
    return len(blocks) >= 3 and sum(1 for b in blocks if b.isalpha()) >= 2


def _clean_code(s):
    """Приводит все варианты тире к обычному дефису и схлопывает пробелы вокруг разделителей."""
    s = re.sub(r"[\u2010\u2011\u2012\u2013\u2014\u2015\u2212]", "-", s)
    s = re.sub(r"\s*-\s*", "-", s)
    s = re.sub(r"\s*/\s*", "/", s)
    s = re.sub(r"\s*\.\s*", ".", s)
    s = re.sub(r"\s*,\s*", ",", s)
    return s.strip(" .,;-")


def _is_excluded(text, m):
    cand = m.group(0).strip(" .,;")
    if EXCLUDE_RE.search(cand):
        return True
    start = m.start()
    prefix_ctx = text[max(0, start - 10):start]
    if re.search(r"(?:РФ|RU|RA|POCC|РОСС|ГОСТ|СП|СРО|ТУ|СТУ|РД|ИСХ|МПТЦ|KR\d{2}|ND\d{2,3})[-._/]$", prefix_ctx, re.I):
        return True
    # то, что стоит перед кандидатом: «исх. № 12-34», «договор № МС-2023-01»
    if CONTEXT_RE.search(text[max(0, start - CONTEXT_WINDOW):start]):
        return True
    # Норматив внутри кандидата или норматив, номер которого начинает кандидата:
    # «СП 10.13130, СП» давал кандидата «10.13130,СП». Отрезать норматив и оставить
    # начало нельзя: перед ним в корпусе стоят марки изделий («БР100.20.8, ГОСТ6665-91»),
    # а не шифр. Поиск в окне вокруг кандидата: без текстового слоя разбирается весь
    # распознанный текст страницы, до 200 тысяч символов.
    for n in NORM_RE.finditer(text, max(0, m.start() - 20), m.end() + 20):
        if n.start() < m.end() and n.end() > m.start():
            return True
    return False


def _band(words, x_min=None, y_min=None, page_size=None, width_mm=TB_WIDTH_MM):
    bx, by = band_bounds(page_size, width_mm=width_mm)
    x_min = bx if x_min is None else x_min
    y_min = by if y_min is None else y_min
    return [w for w in (words or []) if w["bbox"][0] >= x_min and w["bbox"][1] >= y_min]


def _labels(words, page_size=None):
    """Подписи «Стадия», «Лист», «Листов» основной надписи.

    Основная надпись стоит в правом нижнем углу. Опорой служит «Листов» или «Стадия»
    из самой нижней строки подписей, а в строке — самая правая. Остальные подписи
    берутся из той же строки, ближайшие к опоре по горизонтали. Если подписаны только
    листы (последующие листы, форма 2а), опора — самое правое «Лист».

    Одного признака мало, и каждый по отдельности ломался на Тюменской-5:

    - самая нижняя подпись: на F0154 и F0155 в той же строке левее стоит надпись
      вложенной топосъёмки «Стадия И / Лист 2 / Листов 2», и номер листа выходил 2;
      на форме 2а самое нижнее «Лист» — шапка таблицы изменений «Изм. Кол.уч. Лист»;
    - самая правая подпись: на F0154, F0158 и F0190 над основной надписью стоят
      надписи топосъёмок, на доли миллиметра правее, и номер выходил 1;
    - на F0161 стр. 23 самым нижним «Лист» было вырожденное слово нулевой ширины.
    """
    cands = {"Стадия": [], "Лист": [], "Листов": []}
    x_min = band_bounds(page_size, width_mm=TB_LABELS_MM, x_default=0.50)[0]
    sheet_min = band_bounds(page_size, height_mm=TB_SHEET_MM, y_default=0.80)[1]
    for w in _band(words, x_min=x_min, page_size=page_size, width_mm=TB_LABELS_MM):
        t = w["t"].strip().rstrip(".")
        if t not in cands or w["bbox"][2] <= w["bbox"][0]:
            continue
        if t == "Лист" and w["bbox"][1] <= sheet_min:
            continue
        cands[t].append(w)
    anchor_key = next((t for t in ("Листов", "Стадия") if cands[t]), None)
    if anchor_key:
        lowest = max(w["bbox"][1] for w in cands[anchor_key])
        row = [w for w in cands[anchor_key] if lowest - w["bbox"][1] <= 0.01]
        anchor = max(row, key=lambda w: w["bbox"][0])
    elif cands["Лист"]:
        anchor_key = "Лист"
        anchor = max(cands["Лист"], key=lambda w: (w["bbox"][0], w["bbox"][1]))
    else:
        return {}
    got = {anchor_key: anchor}
    for t, ws in cands.items():
        if t == anchor_key:
            continue
        row = [w for w in ws if abs(w["bbox"][1] - anchor["bbox"][1]) <= 0.01]
        if row:
            got[t] = min(row, key=lambda w: abs(w["bbox"][0] - anchor["bbox"][0]))
    return got


def sheet_and_stage(words, page_size=None):
    """Номер листа и стадия из основной надписи. Возвращает (лист, листов, стадия).

    Число относится к колонке ближайшей по горизонтали подписи. Прежде бралось
    «первое целое в строке», и это ломалось, когда графы «Лист» в текстовом слое нет:
    на листах тома АПС Тюменской-5 номер листа нарисован векторами, в слое остаётся
    только «Листов 17», и оно становилось номером листа на каждой странице тома.

    Графа «Лист» пуста у документа из одного листа: по ГОСТ Р 21.101 её не заполняют,
    а в «Листов» ставят 1. Такой лист считается первым.

    Номер листа бывает дробным — так нумеруют лист, вставленный между соседними
    («6.1» между 6 и 7). Дробное число берётся только там, где целого в графе нет.
    """
    lab = _labels(words, page_size)
    if not lab:
        return None, None, None
    anchor = lab.get("Стадия") or lab.get("Листов") or lab.get("Лист")
    y0 = anchor["bbox"][1]
    x0 = min(v["bbox"][0] for v in lab.values()) - 0.01

    row = [w for w in words
           if y0 + 0.003 < w["bbox"][1] < y0 + 0.05 and w["bbox"][0] >= x0]
    row.sort(key=lambda w: w["bbox"][0])

    def centre(w):
        return (w["bbox"][0] + w["bbox"][2]) / 2

    columns = {"Лист": [], "Листов": []}
    stage, loose = None, []
    for w in row:
        t = w["t"].strip()
        if stage is None and t in STAGE_TOKENS:
            stage = STAGE_TOKENS[t]
            continue
        value = sheet_number(t)
        if value is None:
            continue
        if "Лист" in lab or "Листов" in lab:
            nearest = min(lab, key=lambda k: abs(centre(lab[k]) - centre(w)))
            if nearest in columns:
                columns[nearest].append(value)
        elif isinstance(value, int):
            # подписей колонок нет, значения различает только порядок: дробные числа
            # здесь не отличить от даты, и они не берутся
            loose.append(value)
    if not ("Лист" in lab or "Листов" in lab):
        # подписана только стадия: колонки не определить, остаётся порядок значений
        return (loose[0] if loose else None), (loose[1] if len(loose) > 1 else None), stage
    sheet = whole_first(columns["Лист"])
    total = whole_first(columns["Листов"])
    if sheet is None and total == 1 and "Лист" in lab:
        sheet = 1
    return sheet, total, stage


def document_code(words, text="", page_size=None):
    """Шифр документа. Ищется только в пределах основной надписи (штампа)."""
    def pick(source):
        best, best_rank = None, -1
        for m in CODE_RE.finditer(source):
            cand = _clean_code(_strip_trailing_number(m.group(0)))
            # Кандидаты сравниваются по длине до отрезания номера листа: иначе настоящий
            # шифр, укоротившись, проигрывал бы более длинной марке изделия рядом с ним.
            rank = len(_clean_code(m.group(0)))
            if _is_excluded(source, m) or EXCLUDE_RE.search(cand):
                continue
            if len(cand) < 8:
                continue
            # у шифра обязательно есть буквенная марка или обозначение стадии
            if not re.search(r"[А-ЯA-Z]{2}|-[ПР]-", cand):
                continue
            # Разделитель базового обозначения и марки по ГОСТ 21.101 — дефис или слэш.
            # У части проектировщиков его роль играет точка: «2451.П.ДР.ГИ.ТЧ» (Новослободская,
            # F0121) — такой шифр опознаётся отдельно, чтобы не принять марку изделия.
            if "-" not in cand and "/" not in cand and not _dot_separated(cand):
                continue
            if best is None or rank > best_rank:
                best, best_rank = cand, rank
        return best

    # 1. Основная надпись (штамп) внизу листа
    tb = " ".join(w["t"] for w in _band(words, page_size=page_size))
    got = pick(tb)
    if got:
        return got

    # 2. Фолбэк на text только если words не переданы вовсе (например, чистый текст)
    if not words and text:
        return pick(text)

    return None


# Таблица изменений основной надписи по ГОСТ Р 21.101: колонки «Изм.», «Кол.уч», «Лист», «№ док.»,
# «Подп.», «Дата» общей шириной 65 мм, строки по 5 мм, над подписью «Изм.» — несколько строк.
# Расстояния заданы в миллиметрах листа; доли — запасной вариант, когда размер листа неизвестен
# (#41: доли, подобранные на А3, на А0 охватывают вчетверо больше).
REV_COLUMN_MM = 6.0       # номер изменения стоит в колонке «Изм.» шириной 10 мм
REV_ABOVE_MM = 45.0       # строки таблицы над подписью
REV_ROW_MM = 2.5          # слова одной строки таблицы
REV_TABLE_MM = 70.0       # вид изменения, номер документа и дата — правее номера, в пределах таблицы
REV_FRACTIONS = (0.012, 0.08, 0.006, 0.12)
REV_KIND_RE = re.compile(r"^([Зз]ам|[Нн]ов|[Ии]зм|[Аа]ннул)\.?$")
REV_DOC_RE = re.compile(r"^\d{1,4}[-/]\d{2,4}$")
REV_DATE_RE = re.compile(r"^\d{2}\.\d{2}(?:\.\d{2,4})?$")


def change_rows(words, page_size=None):
    """Строки таблицы изменений основной надписи: [{number, kind, doc, date}] по номеру. Задача #81.

    Над подписью «Изм.» в той же колонке стоят номера изменений: 3, 2, 1. Строка
    засчитывается, только если в ней есть вид изменения, номер документа или дата:
    иначе в колонку попадает нумерованный список общих указаний («6.», «7.») или цифры
    чертежа. Прежнее правило искало «изм N» во всём тексте страницы и находило номера
    от 3 до 60 на томе ПОС Тюменской-5, где изменений нет.

    Все строки, а не только последняя, нужны сверке редакций: изменение, внесённое в лист,
    должно стоять в его штампе своим номером, и по номеру видно, каким изменением лист
    менялся, а каким — нет.
    """
    size = coords.page_mm(page_size)
    if size:
        w_mm, h_mm = size
        column, above, row_tol, table = (REV_COLUMN_MM / w_mm, REV_ABOVE_MM / h_mm,
                                         REV_ROW_MM / h_mm, REV_TABLE_MM / w_mm)
    else:
        column, above, row_tol, table = REV_FRACTIONS
    band = _band(words, page_size=page_size)
    found = {}
    for lab in band:
        if not REV_LABEL_RE.match(lab["t"].strip()):
            continue
        lx, ly = lab["bbox"][0], lab["bbox"][1]
        for w in band:
            t = w["t"].strip()
            if not REV_NUM_RE.match(t):
                continue
            x0, y0 = w["bbox"][0], w["bbox"][1]
            if abs(x0 - lx) > column or not 0 < ly - y0 < above:
                continue
            row = [v["t"].strip() for v in sorted(band, key=lambda v: v["bbox"][0])
                   if abs(v["bbox"][1] - y0) < row_tol and 0.002 < v["bbox"][0] - x0 < table]
            n = int(t)
            if not any(REV_ROW_RE.match(v) for v in row) or not 1 <= n <= 50 or n in found:
                continue
            kind = next((REV_KIND_RE.match(v).group(1).capitalize() + "." for v in row if REV_KIND_RE.match(v)), None)
            found[n] = {"number": n, "kind": kind,
                        "doc": next((v for v in row if REV_DOC_RE.match(v)), None),
                        "date": next((v for v in row if REV_DATE_RE.match(v)), None)}
    return [found[n] for n in sorted(found)]


def change_table_readable(words, page_size=None):
    """Читается ли таблица изменений основной надписи: подпись «Изм.» есть в текстовом слое.
    Штамп, нарисованный векторным чертёжным шрифтом, в слой не попадает, и по пустому
    результату `change_rows` нельзя сказать, что строк изменений в нём нет (#81)."""
    return any(REV_LABEL_RE.match(w["t"].strip()) for w in _band(words, page_size=page_size))


def revision(words, text="", page_size=None):
    """Номер последнего изменения листа по таблице изменений основной надписи. Задача #10.

    Возвращает наибольший номер из `change_rows` или None. `text` не используется
    и оставлен ради совместимости вызова.
    """
    rows = change_rows(words, page_size)
    return rows[-1]["number"] if rows else None


TITLE_PATTERNS = [
    re.compile(r"\b(Принципиальная\s+схема\s+[^\n.,;]+(?:\s+[^\n.,;]+){0,8})", re.I),
    re.compile(r"\b(Схема\s+(?:систем|системы)?\s*[^\n.,;]+(?:\s+[^\n.,;]+){0,8})", re.I),
    re.compile(r"\b(План\s+(?:помещений|этажа|кровли|подвала|на отм\.?|расположения|сетей|трасс)?[^\n.,;]+(?:\s+[^\n.,;]+){0,8})", re.I),
    re.compile(r"\b(Разрез\w*\s+[^\n.,;]+)", re.I),
    re.compile(r"\b(Фасад\w*\s+[^\n.,;]+)", re.I),
    re.compile(r"\b(Общие\s+данные[^\n.,;]*)", re.I),
    re.compile(r"\b(Спецификация\s+[^\n.,;]+)", re.I),
    re.compile(r"\b(Ведомость\s+[^\n.,;]+)", re.I),
]


def sheet_title(words, text="", page_size=None):
    """Наименование листа (графа 4 ГОСТ Р 21.101-2020)."""
    tb_band = _band(words, page_size=page_size)
    if tb_band:
        tb_text = " ".join(w["t"] for w in tb_band)
        for pat in TITLE_PATTERNS:
            m = pat.search(tb_text)
            if m:
                cand = re.sub(r"\s+", " ", m.group(1).strip(" .,;"))
                if 5 <= len(cand) <= 120:
                    return cand

    if text:
        for pat in TITLE_PATTERNS:
            m = pat.search(text)
            if m:
                cand = re.sub(r"\s+", " ", m.group(1).strip(" .,;"))
                if 5 <= len(cand) <= 120:
                    return cand

    return None


def parse(words, text="", page_size=None):
    """Полный разбор основной надписи одной страницы.

    page_size: (ширина, высота) листа в пунктах. Если известен, зона штампа считается
    в миллиметрах листа, а не в долях (#41).
    """
    sheet, total, stage = sheet_and_stage(words, page_size)
    return {
        "document_sheet_number": sheet,
        "sheets_total": total,
        "stage_from_titleblock": stage,
        "document_code": document_code(words, text, page_size),
        "sheet_title": sheet_title(words, text, page_size),
        "revision": revision(words, text, page_size),
        "has_titleblock": bool(_labels(words, page_size)),
    }
