"""Приведение значения к единице правила. Задача #94.

Движок берёт значение числом, как напечатано, а корпус печатает один и тот же размер
по-разному: «ширина проезда … 6100 мм» у Речникова и «ширина проездов … не менее 3,5 метров»
у Тюменской; толщина стен — 233 страницы в миллиметрах и 15 в метрах. Правило с абсолютным
порогом на таком корпусе либо врёт, либо слепо: порог 4,2 против напечатанных «4200» не
срабатывает никогда, а порог 800 против «0,9 м» объявляет ложное нарушение.

Поэтому у правила есть поле `unit`, и значение приводится к нему при извлечении. Если
единицу строки определить нельзя, значение **не берётся**: приводить к предполагаемой
единице — это выдумывать данные. Если единица другой размерности (площадь там, где правило
ждёт длину), значение тоже не берётся.

Что считается единицей строки: единица за числом («900 мм») или единица перед первым числом
строки — так подписаны колонки таблиц («Ширина коридора, м 2,96», «Площадь, кв.м 3663,10»).
"""
import re

# Единица: размерность и множитель к базовой единице размерности
DIMENSIONS = {
    "мм": ("length", 0.001), "см": ("length", 0.01), "дм": ("length", 0.1),
    "м": ("length", 1.0), "км": ("length", 1000.0),
    "м²": ("area", 1.0), "га": ("area", 10000.0),
    "м³": ("volume", 1.0), "л": ("volume", 0.001),
    "%": ("share", 1.0), "‰": ("share", 0.1),
    "шт": ("count", 1.0), "ед": ("count", 1.0), "мест": ("count", 1.0), "эт": ("count", 1.0),
    "чел": ("people", 1.0),
    "кВт": ("power", 1.0), "МВт": ("power", 1000.0), "Вт": ("power", 0.001),
    "Гкал/ч": ("heat", 1.0),
    "м³/ч": ("flow", 1.0), "м³/сут": ("flow_day", 1.0), "л/с": ("flow_sec", 1.0),
    "м/с": ("speed", 1.0),
    "т": ("mass", 1.0), "кг": ("mass", 0.001),
    "Ом": ("resistance", 1.0), "дБ": ("sound", 1.0), "лк": ("light", 1.0),
}

# Как единица написана в документах. Ключ — приведённое к нижнему регистру написание
# без точек и пробелов, значение — каноническая единица
ALIASES = {
    "мм": "мм", "миллиметр": "мм", "миллиметров": "мм", "мм.": "мм",
    "см": "см", "сантиметр": "см", "дм": "дм",
    "м": "м", "м.": "м", "метр": "м", "метра": "м", "метров": "м", "п.м": "м", "пм": "м",
    "пог.м": "м", "погм": "м", "км": "км",
    "м2": "м²", "м²": "м²", "кв.м": "м²", "квм": "м²", "кв.м.": "м²", "м.кв": "м²",
    "м3": "м³", "м³": "м³", "куб.м": "м³", "кубм": "м³", "м.куб": "м³",
    "га": "га", "гектар": "га", "л": "л",
    "%": "%", "процент": "%", "процентов": "%", "‰": "‰",
    "шт": "шт", "шт.": "шт", "штук": "шт", "ед": "ед", "ед.": "ед", "единиц": "ед",
    "мест": "мест", "место": "мест", "м/м": "мест", "эт": "эт", "эт.": "эт", "этаж": "эт",
    "чел": "чел", "чел.": "чел", "человек": "чел",
    "квт": "кВт", "квт.": "кВт", "мвт": "МВт", "вт": "Вт",
    "гкал/ч": "Гкал/ч", "гкал/час": "Гкал/ч",
    "м3/ч": "м³/ч", "м³/ч": "м³/ч", "м3/час": "м³/ч",
    "м3/сут": "м³/сут", "м³/сут": "м³/сут", "м3/сутки": "м³/сут",
    "л/с": "л/с", "л/сек": "л/с", "м/с": "м/с",
    "т": "т", "тонн": "т", "кг": "кг",
    "ом": "Ом", "дб": "дБ", "дба": "дБ", "лк": "лк",
}


def canon(token):
    """Каноническая единица по написанию из документа или None, если единица незнакомая."""
    if not token:
        return None
    key = re.sub(r"\s+", "", str(token)).strip().lower().replace("ё", "е")
    if key in ALIASES:
        return ALIASES[key]
    key = key.rstrip(".")
    return ALIASES.get(key)


def dimension(unit):
    """Размерность канонической единицы или None."""
    row = DIMENSIONS.get(unit or "")
    return row[0] if row else None


def convert(value, found, want):
    """Значение из единицы `found` в единицу `want` или None, если привести нельзя.

    None возвращается в трёх случаях: единица строки незнакома, единица правила незнакома,
    размерности разные. Во всех трёх значение брать нельзя.
    """
    if value is None:
        return None
    a, b = canon(found), canon(want)
    if not a or not b:
        return None
    da, db = DIMENSIONS.get(a), DIMENSIONS.get(b)
    if not da or not db or da[0] != db[0]:
        return None
    if a == b:
        return value
    # округление до шести знаков: 6100 мм / 1000 даёт 6.1000000000000005, и такое значение
    # уходило бы в запись и в файл сдачи как есть
    return round(value * da[1] / db[1], 6)


def same_dimension(found, want):
    """Одной ли размерности единица строки и единица правила."""
    a, b = dimension(canon(found)), dimension(canon(want))
    return bool(a) and a == b


# Порядок величины порога для единицы: помогает поймать правило, где порог написан
# в миллиметрах, а единица объявлена метрами. Границы широкие: это проверка схемы,
# а не проверка норматива
PLAUSIBLE = {
    "мм": (10.0, 100000.0), "см": (1.0, 10000.0), "м": (0.05, 100.0), "км": (0.01, 1000.0),
    "м²": (0.1, 1000000.0), "га": (0.001, 10000.0), "м³": (0.01, 1000000.0),
    "%": (0.01, 100.0),
}


def implausible(threshold, unit):
    """Порог, который не похож на значение в объявленной единице: (нижняя, верхняя) или None."""
    if threshold is None:
        return None
    bounds = PLAUSIBLE.get(canon(unit) or "")
    if not bounds or bounds[0] <= abs(float(threshold)) <= bounds[1]:
        return None
    return bounds
