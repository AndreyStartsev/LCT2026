"""Извлечение значений показателей из текста документа. Этап 4б плана.

Показатели первой очереди Матрицы — площади, объёмы, количества, отметки —
живут в таблицах технико-экономических показателей и в текстовой части
пояснительной записки. В текстовом слое PDF таблица превращается в сплошную строку,
и все трудности разбора возникают из этого.

## Числа

Тысячи отделяются пробелом, дробная часть запятой или точкой:

    29 200,00 м2        одно число, двадцать девять тысяч двести
    3987,30 3694,60     два числа, стоящие в соседних колонках
    1 401               одно число, тысяча четыреста один

Пробел внутри числа и пробел между числами отличаются только тем, сколько цифр
идёт после пробела: у разделителя тысяч ровно три, и перед ним группа из одной-трёх
цифр. «3987,30 3694,60» так не читается, потому что до запятой четыре цифры.

## Строка таблицы

Значения, стоящие подряд сразу за подписью, — это колонки одной строки.

    Площадь озеленения м2 3987,30 3694,60 6 Площадь участка …
    Площадь застройки, в т.ч.: 2 854,2 м2 -наземной части здания 2 559,5 м2 …

В первой строке две колонки, и значение проекта — последняя: эталон организатора
по этому листу берёт 3694,60. Вторая строка — итог и его составляющие, и итог
стоит первым, а составляющие отделены своими подписями. Отличие в том, что
между значениями колонок нет слов, а между итогом и составляющими — есть.

Номер следующей строки таблицы («6 Площадь участка») значением не является:
это одно- или двузначное целое, за которым сразу идёт слово с заглавной буквы.
Не значение и число, за которым сразу идёт ещё одна дробная часть: «6.2.6 Классы»
— номер пункта, «23.12.2022» — дата.

## Какая колонка — значение проекта

Место колонки проекта в таблицах корпуса не постоянно:

    площадь застройки 2362,5 2909,5 31        до реконструкции | после | %
    Площадь озеленения, в т.ч.: 153,9 11,0    площадь | % от площади участка
    поэтажная площадь … 14 000 13 999,7       по ГПЗУ | проект
    Предельная высота здания м 63,96 66,0     показатель | ГПЗУ

Поэтому «первая» или «последняя» в правиле — только запасной выбор, а сначала
проверяются два признака.

Доля. Последняя колонка — процент, если она равна доле одной из колонок от строки
той же таблицы, где процент равен 100: 2909,5 от 9456 — 31 %, а 2362,5 — 25 %.
Процент считают от значения проекта, так что доля заодно называет его колонку.
Сумма строк так не умеет: 2362,5 + 7093,5 и 2909,5 + 6546,5 одинаково дают 9456.
Если строки со 100 нет, доля признаётся по итогу, записанному в той же таблице,
когда от него же считана доля ещё хотя бы одной строки: 1826,6 и 2669 от 6052 —
30,18 и 44,10 %.

Шапка. Подписи колонок перед строкой: своя — «Проект», «после реконструкции»,
«Корректировка», чужая — «ГПЗУ», «до реконструкции», «положительное заключение».
Решает последняя из них, если перед ней стоит подпись другой роли: своя — значение
в последней колонке, чужая — в первой. Подпись, за которой сразу идёт число,
принадлежит строке, а не шапке: «Площадь участка в границах ГПЗУ га 1,1417».
«м² %» сразу за парой подписей отбрасывает колонку процентов и без строки со 100.
"""
import functools
import re

from pipeline import units

# Число: сначала вариант с разделителем тысяч, затем обычный. Порядок важен:
# жадный первый вариант должен забрать «29 200,00» целиком.
# Группа разрядов — ровно три цифры: «250 1850» — две колонки, 250 и 1850, а не «250 185» и ещё ноль (#229)
NUMBER = r"(?:\d{1,3}(?: ?\s\d{3}(?!\d))+(?:[.,]\d+)?|\d+(?:[.,]\d+)?)"
NUMBER_RE = re.compile(NUMBER)

# Единицы, которые могут стоять между подписью и значением или после значения.
#
# «м2» и «м3» пишут и через пробел («29 200,00 м 2»), поэтому пробел допускается. Но тогда
# в «Ширина коридора, м 2,96» выражение съедало «м 2» вместе с первой цифрой значения и
# оставляло «,96»: значение терялось целиком. В корпусе так записаны «Высота верхнего этажа,
# м 3,8», «Высота оконных проемов, м 2,8», «высота защищаемого помещения, м 2,6». Поэтому
# двойка и тройка не считаются частью единицы, если сразу за ними идёт дробная часть числа:
# у настоящей единицы дальше пробел или конец («м2 1 401»), у значения — запятая или точка.
UNIT = (r"(?:кв\.?\s?м\.?|м\s?²|м\s?2(?![.,]\d)|м\s?³|м\s?3(?![.,]\d)|куб\.?\s?м\.?|га|м/с|‰|%|"
        r"шт\.?|ед\.?|эт\.?|мест|м\.?|мм|кВт|Гкал/ч|м³/сут|м3/сут|м³/ч|м3/ч)")
UNIT_RE = re.compile(r"^\s*" + UNIT + r"(?=[\s,.;:)]|$)", re.I)


def parse_number(s):
    """Строка числа в float. «29 200,00» -> 29200.0, «159,95» -> 159.95."""
    t = re.sub(r"[\s ]", "", s).replace(",", ".")
    try:
        return float(t)
    except ValueError:
        return None


@functools.lru_cache(maxsize=16)
def flatten(text):
    """Текст страницы в одну строку: таблицы в слое разорваны переносами.

    Одну страницу разбирают все правила очереди, и каждое сводило её в строку заново:
    на Алтуфьевском это 47 % времени разбора (замер 24.09). Результат запоминается для
    последних страниц: функция чистая, а строка неизменяема.
    """
    return re.sub(r"\s+", " ", text or "").strip()


def _skip_unit(s, pos):
    m = UNIT_RE.match(s[pos:])
    return pos + m.end() if m else pos


def _take_unit(s, pos):
    """(позиция за единицей, сама единица) — единица, написанная в позиции pos, или None."""
    m = UNIT_RE.match(s[pos:])
    return (pos + m.end(), m.group(0).strip()) if m else (pos, None)


def _is_row_index(s, start, end, first=True):
    """Номер следующей строки таблицы: короткое целое, за которым идёт слово
    с заглавной буквы или пункт вида «2.1 Площадь».

    Не первой колонкой номер пункта бывает и перед подписью строчными: «895,0 3.2
    подземная площадь», «3 326,0 3.1 - площадь застройки наземной части». Первым
    числом за подписью так читается и значение с точкой, «16.5 метров», поэтому
    строчные проверяются только дальше в строке.
    """
    token = s[start:end]
    if not re.fullmatch(r"\d{1,2}(?:\.\d{1,2})?", token):
        return False
    rest = s[end:end + 6]
    # «6 Площадь участка», «1. Грунт планировки» и «3.Максимальная плотность» — номера строк
    if re.match(r"(?:\.\s?|\s)(?:[-–—]\s)?[А-ЯЁA-Z]", rest):
        return True
    return (not first and "." in token and bool(re.match(r"\s(?:[-–—]\s)?[а-яё]", rest))
            and not UNIT_RE.match(s[end:end + 24]))


def values_after(flat, label_end, max_gap=40, with_units=False):
    """Значения, стоящие подряд сразу за подписью: колонки одной строки.

    Возвращает список (значение, исходная строка числа). Пустой список, если
    за подписью в пределах max_gap символов нет числа.

    `with_units` — вернуть тройки (значение, строка числа, единица): единица своя, если
    написана за числом («900 мм»), иначе единица подписи колонки («Ширина коридора, м 2,96»).
    Нужна для приведения к единице правила (#94, `pipeline/units.py`).
    """
    pos, lead_unit = _take_unit(flat, label_end)
    # между подписью и первым значением допускаются двоеточие, «в т.ч.», скобки
    lead = re.match(r"[\s,.:;()\-–—]*(?:в\s?т\.?\s?ч\.?[:\s]*)?", flat[pos:])
    pos += lead.end() if lead else 0
    pos, second = _take_unit(flat, pos)
    lead_unit = lead_unit or second
    out = []
    first = True
    while True:
        gap = re.match(r"[\s:;]*", flat[pos:])
        start = pos + (gap.end() if gap else 0)
        if first and start - label_end > max_gap:
            break
        m = NUMBER_RE.match(flat, start)
        if not m:
            break
        if _is_row_index(flat, m.start(), m.end(), first):
            break
        # «6.2.6 Классы» и «23.12.2022»: за числом ещё одна дробная часть
        if re.match(r"[.,]\d", flat[m.end():m.end() + 2]):
            break
        # после числа не должно сразу идти продолжение слова: «2.1Площадь»
        value = parse_number(m.group(0))
        if value is None:
            break
        pos, own = _take_unit(flat, m.end())
        out.append((value, m.group(0), own or lead_unit) if with_units else (value, m.group(0)))
        first = False
        # следующая колонка допускается только через пробел, без слов между
        if not re.match(r"\s+" + NUMBER, flat[pos:]):
            break
    return out


# Подписи колонок в шапке таблицы показателей. Своя колонка — значение этого документа,
# чужая — то, с чем документ себя сопоставляет. Общие «Показатель», «Количество»
# своими считаются только перед чужой: «Показатель | ГПЗУ» у Октябрьской. Доля —
# колонка процентов за колонками площади: «м² м² %», «Площадь, кв.м % от площади».
CAPTION_RE = re.compile(
    r"(?P<other>до\s+(?:реконстр|корректир|изменени)\w*|существующ\w*\s+(?:положени|состояни)\w*"
    r"|положительн\w*\s+заключени\w*|предельн\w*\s+(?:параметр|значени|показател)\w*"
    r"|допустим\w*\s+(?:по|значени)\w*|\bГПЗУ\b|\bбыло\b"
    # норма рядом с проектом: «По проекту | Нормативное», «Требуется | Принято» (#41)
    r"|нормативн\w*|\bнорматив\b|\bпо\s+норме\b|\bпо\s+нормам\b|\bтребуется\b"
    r"|\bтребуемо[ег]\w*|по\s+расч[её]ту|расч[её]тн\w*\s+(?:значени|показател)\w*|\bСП\s?\d)"
    r"|(?P<own>после\s+(?:реконстр|корректир|изменени)\w*|\bпо\s+проекту\b|\bпроект\b"
    r"|проектн\w*\s+(?:значени|показател|положени|состояни)\w*|показател\w*\s+по\s+ПД\b"
    r"|\bкорректировка\b|\bстало\b|\bпринято\b|\bпринимаетс\w*|\bфактическ\w*)"
    r"|(?P<share>(?:м\s?²|м2|кв\.?\s?м\.?|га)\s+%|%\s+от\b)"
    r"|(?P<generic>\bпоказател\w*|\bзначени[ея]\b|\bколичество\b|\bкол-?во\b|\bвеличина\b)",
    re.I)
HEADER_LOOKBACK = 1200   # шапка Октябрьской стоит за 650 символов до строки высоты
HEADER_PAIR_SPAN = 250   # своя и чужая подписи одной шапки стоят рядом
LONG_ROW = 5             # столько чисел подряд без шапки — ряд, а не строка показателей (#145)
SHARE_WINDOW = 3000      # строка «100 %» ищется в своей таблице, а не по всей странице
HUNDRED_RE = re.compile(r"(?<![\d,.])100(?:[.,]0+)?(?![\d,.])")
NUMBER_START_RE = re.compile(r"(?<![\w,.])\d")


def _decimals(raw):
    m = re.search(r"[.,](\d+)$", raw)
    return len(m.group(1)) if m else 0


def _followed_by_value(flat, end):
    """За подписью сразу идёт число: подпись из строки таблицы, а не из шапки."""
    lead = re.match(r"[\s,.:;()*\-–—]*(?:в\s?т(?:ом)?\.?\s?ч(?:исле)?\.?[:\s]*)?", flat[end:])
    pos = _skip_unit(flat, end + lead.end())
    pos += re.match(r"\s*", flat[pos:]).end()
    m = NUMBER_RE.match(flat, pos)
    return bool(m) and not _is_row_index(flat, m.start(), m.end())


SERIES_RE = re.compile(r"(?:\s+[-+−]\s?\d+(?:[.,]\d+)?){2}")


def _series_follows(flat, label_end, rows):
    """За последним числом строки идут ещё два числа со знаком: это ряд картограммы, а не строка."""
    last = rows[-1][1]
    at = flat.find(last, label_end)
    return at >= 0 and bool(SERIES_RE.match(flat, at + len(last)))


def _shares_of_common_total(flat, start, values):
    """Последняя колонка — доля от общего итога, которого на листе нет (#145).

    Баланс благоустройства школы на Полярной 25 (РД ГП, стр. 5): «м2 331,80 1,52 … м2 2333,33 10,68 …
    Площадь озеленения : м2 7173,7 32,83 … м2 4194,02 19,20». Итог — площадь участка 21 850 м² —
    записан на другом листе, строки со 100 нет, и правило «последняя колонка» брало долю 32,83 за
    площадь озеленения. Доля признаётся, если «значение ÷ доля × 100» у этой строки и ещё хотя бы
    у двух строк той же таблицы с тем же числом колонок сходятся в пределах округления доли.
    """
    k = len(values)
    pct, raw = values[-1]
    if not _decimals(raw) or not 1 <= pct < 100:
        return []

    def span(value, share, share_raw):
        # итог, от которого доля считана, с погрешностью округления самой доли
        half = 0.5 * 10 ** -_decimals(share_raw)
        return value * 100 / (share + half), value * 100 / max(share - half, 1e-9)

    rows = []
    for d in NUMBER_START_RE.finditer(flat, max(0, start - SHARE_WINDOW), start + SHARE_WINDOW):
        run = values_after(flat, d.start(), max_gap=0)
        if (len(run) == k and 0 < run[-1][0] < 100 and _decimals(run[-1][1])
                and [v for v, _ in run] != [v for v, _ in values]):
            rows.append(run)
    out = []
    for j in range(k - 1):
        if values[j][0] <= pct:
            continue
        lo, hi = span(values[j][0], pct, raw)
        agree = {tuple(v for v, _ in r) for r in rows if r[j][0] > r[-1][0]
                 and (lambda s: s[0] <= hi and lo <= s[1])(span(r[j][0], r[-1][0], r[-1][1]))}
        if len(agree) >= 2:
            out.append(j)
    return out


def header_roles(flat, start):
    """Что говорят подписи шапки перед строкой: (где колонка проекта, доля ли последняя).

    Где колонка проекта — "first", "last" или None, если шапка молчит. Решает последняя
    своя или чужая подпись, и только в паре с подписью другой роли перед ней: одинокое
    «ГПЗУ» из текста над таблицей о колонках ничего не говорит. Подпись доли тоже
    учитывается только в такой шапке, сразу за парой: «% от кадастровой стоимости»
    и «КБп, % от 10 до 50» стоят над таблицами, где процентов в колонках нет.
    """
    lo = max(0, start - HEADER_LOOKBACK)
    caps = [(lo + m.start(), m.lastgroup) for m in CAPTION_RE.finditer(flat[lo:start])
            if not _followed_by_value(flat, lo + m.end())]
    specific = [(p, role) for p, role in caps if role in ("own", "other")]
    if not specific:
        return None, False
    pos, role = specific[-1]
    before = {r for p, r in caps if pos - HEADER_PAIR_SPAN <= p < pos}
    if role == "own" and "other" in before:
        side = "last"
    elif role == "other" and before & {"own", "generic"}:
        side = "first"
    else:
        return None, False
    return side, any(r == "share" and pos < p <= pos + HEADER_PAIR_SPAN for p, r in caps)


def share_sources(flat, start, values):
    """Колонки, долей которых в процентах является последняя колонка строки.

    Доля считается от строки той же таблицы с тем же числом колонок и 100 в последней,
    ближайшей к строке. Если такой строки нет, доля проверяется по итогу таблицы
    (`_shares_of_total`). Пустой список — последняя колонка не доля или проверить нечем.
    Последняя колонка, равная 100, не проверяется: строка подтверждала бы сама себя,
    а в корпусе это «Кольцевая 3,2 100» — длина и диаметр трубы. Доля меньше процента
    тоже: при допуске 0,01 к «0,06» совпадение находится случайно.
    """
    k = len(values)
    pct, raw = values[-1]
    if k < 2 or not 1 <= pct < 100:
        return []
    totals = []
    for hundred in HUNDRED_RE.finditer(flat, max(0, start - SHARE_WINDOW), start + SHARE_WINDOW):
        # начало строки ищется среди чисел перед сотней: «9456 9456 100»
        for m in NUMBER_RE.finditer(flat, max(0, hundred.start() - 30 * k), hundred.start()):
            if m.start() and (flat[m.start() - 1].isalnum() or flat[m.start() - 1] in ",."):
                continue
            run = values_after(flat, m.start(), max_gap=0)
            if len(run) == k and run[-1][0] == 100:
                # сначала ближайшая строка выше, затем ниже
                totals.append((m.start() >= start, abs(start - m.start()), run))
                break
    if not totals:
        return _shares_of_total(flat, start, values) or _shares_of_common_total(flat, start, values)
    total = min(totals)[2]
    tol = 10 ** -_decimals(raw)
    return [j for j in range(k - 1)
            if total[j][0] > 0 and abs(values[j][0] / total[j][0] * 100 - pct) <= tol]


def _shares_of_total(flat, start, values):
    """Колонки, долей которых является последняя колонка, когда строки со 100 в таблице нет.

    Баланс территории ДОО на Полярной (РД ГП2, стр. 5): «Общая площадь работ по
    благоустройству… м2 6052 96,28 … Площадь покрытий… м2 2669 44,10 … Площадь
    озеленения : м2 1826,6 30,18». Итог 6052 сам записан долей от участка побольше,
    строки со 100 нет, шапка «Кол-во %» стоит за 1800 символов до строки, и правило
    «последняя колонка» брало долю 30,18 за площадь озеленения (#109).

    Доля признаётся, если число, от которого она считана, стоит в той же таблице,
    и хотя бы ещё одна строка с тем же числом колонок — доля от него же. Одного итога
    мало: на плотном листе число, от которого «доля» сходится с допуском, находится
    случайно. Доли берутся только с дробной частью: у целой допуск в процент, и
    случайное совпадение не редкость.
    """
    k = len(values)
    pct, raw = values[-1]
    if not _decimals(raw):
        return []
    numbers, rows = set(), []
    # начала чисел ищутся по цифрам, а не разбором подряд: подряд «м2 6052» читается
    # как «2 605» с разделителем тысяч, и итог 6052 не находится
    for d in NUMBER_START_RE.finditer(flat, max(0, start - SHARE_WINDOW), start + SHARE_WINDOW):
        m = NUMBER_RE.match(flat, d.start())
        value = parse_number(m.group(0))
        if value:
            numbers.add(value)
        run = values_after(flat, m.start(), max_gap=0)
        if (len(run) == k and 1 <= run[-1][0] < 100 and _decimals(run[-1][1])
                and [v for v, _ in run] != [v for v, _ in values]):
            rows.append(run)
    out = []
    for j in range(k - 1):
        v = values[j][0]
        for total in sorted(numbers):
            if total <= v or abs(v / total * 100 - pct) > 10 ** -_decimals(raw):
                continue
            if any(r[j][0] > 0 and abs(r[j][0] / total * 100 - r[-1][0]) <= 10 ** -_decimals(r[-1][1])
                   for r in rows):
                out.append(j)
                break
    return out


def pick_column(flat, start, values, rule="last"):
    """Номер колонки строки, в которой стоит значение показателя, и чем он выбран.

    Возвращает (номер, способ): «single» — колонка одна; «share» — последняя колонка
    оказалась процентом от неё; «header» — так говорят подписи шапки; «rule» — ни доля,
    ни шапка не сказали, и колонку выбрало правило по положению.

    Способ «rule» — догадка: на чужой шапке («Вариант 1 | Вариант 2», «I этап | II этап»)
    положение колонки ничего не значит. Он доходит до находки полем column_choice,
    чтобы инспектор видел, чем выбрано значение (#41).
    """
    k = len(values)
    if k < 2:
        return 0, "single"
    sources = share_sources(flat, start, values)
    if sources and len({values[j][0] for j in sources}) == 1:
        return sources[0], "share"
    side, share = header_roles(flat, start)
    last = k - 2 if sources or (share and values[-1][0] <= 100) else k - 1
    if side:
        return (last if side == "last" else 0), "header"
    return (last if rule == "last" else 0), "rule"


def _row_label(flat, start, end):
    """Подпись своей строки таблицы: от конца предыдущего значения до первой цифры.

    Исключения проверяются только здесь. Раньше они проверялись в окне ±50 символов
    и задевали соседние строки: на листе ведомости «Общая площадь озеленения,
    кв.м. 3663,10» стоит между «под деревьями» и «газонов в газонных решётках»,
    и настоящий итог отбрасывался из-за соседей.
    """
    back = flat[max(0, start - 60):start]
    prev_num = list(NUMBER_RE.finditer(back))
    left = start - (len(back) - prev_num[-1].end()) if prev_num else max(0, start - 60)
    ahead = re.search(r"\d", flat[end:end + 50])
    right = end + (ahead.start() if ahead else 50)
    return flat[left:right]


_TWIN = re.compile(r"^(\d{1,3})\s(\1)$")


def _split_twin_groups(rows):
    """Две одинаковые группы через пробел в строке с колонками — две колонки, а не число с разрядами:
    «188 188» у итога баланса земляных масс Новослободской — насыпь 188 и выемка 188 м³, а не 188 188 (#229)."""
    out = []
    for value, raw, unit in rows:
        twin = _TWIN.match(raw.replace("\u00a0", " "))
        if twin:
            out += [(float(twin.group(1)), twin.group(1), unit), (float(twin.group(2)), twin.group(2), unit)]
        else:
            out.append((value, raw, unit))
    return out


def find_values(text, label_patterns, exclude_patterns=(), rule="last", limit_patterns=(), unit=None,
                max_columns=None):
    """Все вхождения показателя на странице.

    label_patterns — регулярные выражения подписи. exclude_patterns — слова,
    которые делают строку составляющей, а не итогом: «Площадь застройки наземной
    части» при поиске площади застройки. Проверяются только в подписи своей строки.

    limit_patterns — слова, которые называют в подписи предел, а не значение:
    «Предельная высота здания – 85 м» в томе АР Полярной 16 — предел по ГПЗУ, а на
    листе буклета «предельная высота здания 1 этаж 2 этаж» за подписью идут номера
    этажей (#109). Такая строка берётся, только если шапка таблицы называет колонку
    проекта: в ТЭП Октябрьской строка «Предельная высота здания м 63,96 66,0» стоит под
    шапкой «Показатель | ГПЗУ», и 63,96 — высота здания по проекту.

    Перекрывающиеся совпадения подписей считаются одним: «Общая площадь
    озеленения» и вложенная в неё «площадь озеленения» — одна строка, а не две,
    иначе значение получает двойной голос.

    rule — запасной выбор колонки, если строка таблицы сама её не называет
    (`pick_column`). В columns все колонки строки, в value и raw — выбранная.

    unit — единица правила (#94). Значение приводится к ней: «6100 мм» при unit «м» даёт 6,1.
    Строка, у которой единицу определить нельзя или она другой размерности, не берётся вовсе:
    приводить к предполагаемой единице значит выдумывать данные. В находке остаётся `unit` —
    единица, как она написана в строке, и `unit_to` — единица правила.

    max_columns — сколько колонок у строки показателя: числа за ними — уже соседняя таблица, слитая
    в тексте слоя со строкой. У итога баланса земляных масс колонок две, насыпь и выемка; если текст
    слоя продолжается числами соседнего чертежа («… 1850 1850 20,00 20,00 20,00 …»), без предела строка
    сходила за ряд картограммы и отбрасывалась (#229).
    """
    flat = flatten(text)
    found, taken = [], []
    matches = []
    for pat in label_patterns:
        for m in re.finditer(pat, flat, re.I):
            matches.append(m)
    # длинные подписи первыми: они точнее и забирают место у вложенных
    matches.sort(key=lambda m: (-(m.end() - m.start()), m.start()))
    for m in matches:
        if any(m.start() < e and s < m.end() for s, e in taken):
            continue
        row = _row_label(flat, m.start(), m.end())
        if any(re.search(x, row, re.I) for x in exclude_patterns):
            continue
        rows = values_after(flat, m.end(), with_units=True)
        if max_columns:
            rows = _split_twin_groups(rows)[:max_columns]
        if not rows:
            continue
        vals = [(v, raw) for v, raw, _u in rows]
        taken.append((m.start(), m.end()))
        column, choice = pick_column(flat, m.start(), vals, rule)
        if choice != "header" and any(re.search(x, row, re.I) for x in limit_patterns):
            continue
        if choice in ("rule", "single") and _series_follows(flat, m.end(), rows):
            # за значением идут ещё числа со знаком: «Выемка -3.47 -0.82 -1.25 0.00 -86.73 …» — ряд
            # картограммы, а разбор колонок останавливается на минусе и видел одно число (#145)
            continue
        if choice == "rule" and len(vals) >= LONG_ROW:
            # пять и больше чисел подряд без шапки — не строка показателей, а ряд картограммы или
            # номера этажей: «Выемка -3.47 -0.82 -1.25 0.00 -86.73 …» и «(высота здания) 1 5 10 14 21 …»
            # у школы на Полярной 25 давали объём грунта 3,47 м³ и высоту здания 1 м (#145)
            continue
        value, raw, found_unit = rows[column]
        # приведение — после выбора колонки: доля в процентах нужна `pick_column` как есть,
        # а приводится только выбранное значение
        if unit:
            converted = units.convert(value, found_unit, unit)
            if converted is None:
                continue                  # единицу не определить или она другой размерности
            value = converted
        found.append({
            "value": value,
            "columns": [units.convert(v, u, unit) if unit else v for v, _raw, u in rows],
            "column_choice": choice,
            "raw": raw,
            "label": m.group(0),
            "snippet": flat[max(0, m.start() - 30):m.end() + 70],
            "pos": m.start(),
            **({"unit": units.canon(found_unit), "unit_to": units.canon(unit)} if unit else {}),
        })
    found.sort(key=lambda c: c["pos"])
    return found


# ---------- ведомости ----------

MAX_ROW_NAME = 250
SCHEDULE_ROW_RE = re.compile(r"(кв\.?\s?м\.?|м\s?²|м2)\s+(" + NUMBER + r")")


def schedule_rows(text, header_pattern):
    """Строки ведомости с площадями: список (наименование, значение).

    Ведомость проездов, тротуаров, дорожек и площадок в текстовом слое выглядит так:

        Проезды с асфальтобетонным покрытием в границах проектирования I кв.м. 43,0
        Проезды с асфальтобетонным покрытием на кровле паркинга … I* кв.м. 86,0
        Тротуары с плиточным покрытием в границах проектирования III кв.м. 2048,0

    Наименование строки — текст от предыдущего значения до единицы измерения.
    Разбор начинается от заголовка ведомости: без заголовка страница не считается
    ведомостью, иначе в сумму попадут площади из журнала изменений и спецификаций.
    """
    flat = flatten(text)
    head = re.search(header_pattern, flat, re.I)
    if not head:
        return []
    body = flat[head.end():]
    rows, prev = [], 0
    for m in SCHEDULE_ROW_RE.finditer(body):
        name = body[prev:m.start()].strip()
        # Таблица кончилась, если «наименование» неправдоподобно длинное. На листе
        # ведомости Речникова за последней строкой идёт спецификация бортов, и она
        # случайно заканчивается на «кв.м. 5,5»: без обрыва эта «строка» длиной
        # 6832 символа попадала в сумму плиточного покрытия, потому что где-то
        # внутри неё тоже есть слово «плитка». Настоящие строки не длиннее 190.
        if len(name) > MAX_ROW_NAME:
            break
        value = parse_number(m.group(2))
        prev = m.end()
        if value is not None and name:
            rows.append((name, value, m.group(2)))
    return rows


def schedule_sum(text, header_pattern, row_pattern, exclude_patterns=()):
    """Сумма площадей строк ведомости, чьё наименование подходит под row_pattern."""
    rows = schedule_rows(text, header_pattern)
    picked = [(n, v, r) for n, v, r in rows
              if re.search(row_pattern, n, re.I)
              and not any(re.search(x, n, re.I) for x in exclude_patterns)]
    if not picked:
        return None
    total = round(sum(v for _, v, _ in picked), 2)
    return {"value": total, "rows": [(n[-70:], v) for n, v, _ in picked],
            "raw": f"{total:.2f}".replace(".", ","), "columns": [v for _, v, _ in picked]}


# ---------- перечни: позиции, строка по наименованию, наличие систем (#84) ----------

MIN_POSITIONS = 3         # ряд короче трёх номеров — не ведомость, а совпадение чисел
MAX_POSITIONS = 400       # длиннее ведомости МАФ не бывает; защита от колонки чисел
POSITION_RE = re.compile(r"(?<![\d,.])(\d{1,3})(?:\.(\d{1,2}))?(?![\d,.])")
HEIGHT_RE = re.compile(r"\bh\s*[=:]\s*(" + NUMBER + r")\s*м", re.I)


def schedule_positions(text, header_pattern):
    """Позиции ведомости, идущие подряд от единицы: (количество, фрагмент) или None.

    Ведомость малых архитектурных форм — перечень, а не показатель: единицы измерения
    у строк нет, и `schedule_rows` её не читает. Зато у каждой строки есть номер позиции,
    и номера идут подряд: 1, 2, 3. Числа между ними — количества, артикулы, размеры —
    пропускаются, потому что ищется только следующий по счёту номер.

    Ряд обязан начинаться с единицы. На листе с продолжением ведомости стоят позиции
    4, 5, 17, 27 — если считать и его, перечень выйдет короче настоящего, а решение
    по нему — «позиций стало меньше», то есть ложное нарушение.

    Подпозиции («12.1») ряд не двигают: это уточнение строки, а не новая позиция.
    """
    flat = flatten(text)
    head = re.search(header_pattern, flat, re.I)
    if not head:
        return None
    body = flat[head.end():]
    want, start, end = 1, None, None
    for m in POSITION_RE.finditer(body):
        if m.group(2):
            continue
        if int(m.group(1)) != want:
            continue
        if start is None:
            start = m.start()
        end, want = m.end(), want + 1
        if want > MAX_POSITIONS:
            break
    count = want - 1
    if count < MIN_POSITIONS:
        return None
    return count, " ".join(body[start:end][:220].split())


def item_with_height(text, row_pattern):
    """Строка перечня с высотой рядом: (фрагмент, высота в метрах, число после высоты).

    Ограждение в ведомости записано одной строкой вместе с типом и высотой:
    «Ограждение территории, м. пог. секция забора 2, h=2,0м 174.45». Высота нужна,
    чтобы поймать занижение, текст строки — чтобы поймать замену типа, число после
    высоты — протяжённость.

    Требование высоты рядом отсекает условные обозначения: в легенде чертежа
    «ограждение территории» тоже написано, но без «h=».
    """
    flat = flatten(text)
    for m in re.finditer(row_pattern, flat, re.I):
        window = flat[m.start():m.start() + 200]
        h = HEIGHT_RE.search(window)
        if not h:
            continue
        height = parse_number(h.group(1))
        if height is None:
            continue
        tail = re.search(NUMBER, window[h.end():h.end() + 40])
        length = parse_number(tail.group(0)) if tail else None
        return " ".join(window[:h.end() + (tail.end() if tail else 0)].split()), height, length
    return None


def features_named(text, features):
    """Какие из названных систем упомянуты на странице: список имён.

    `features` — пары «имя, образец»: наличие системы в стадии проверяется по тому,
    названа ли она в разделе. Это проверка наличия, а не значения: параметр говорит
    об исключении лотков или дренажа из рабочей стадии, а не об их размере.
    """
    flat = flatten(text)
    return [name for name, pattern in features if re.search(pattern, flat, re.I)]
