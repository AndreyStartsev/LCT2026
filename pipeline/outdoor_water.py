"""Наружное противопожарное водоснабжение здания: расход и число гидрантов. PPM-114, #145.

Параметр — расход на наружное пожаротушение самого здания и то, от скольких пожарных гидрантов
он обеспечен. В ПД это записка ИОС2 или ПБ: «Расход воды на наружное пожаротушение здания –
30,0 л/с» (Речников), «наружного пожаротушения проектируемого здания предусмотрен в количестве
не менее 30 л/с, … от двух существующих пожарных гидрантов» (Полярная 16), «Наружное
пожаротушение обеспечивается не менее чем от трех пожарных гидрантов» (ДОО).

Расход сети или квартала — не параметр здания (черновик, принятый специалистом): строка баланса
водопотребления «Наружное пожаротушение — 110 л/с» (Тюменская-5, ПД и РД ВВ), расход «для расчета
магистральных кольцевых линий», нагрузка в точке подключения по ТУ, потребность стройплощадки
в ПОС. Такие значения отбрасываются по окружению подписи. Подпись, где сказано «здания», берётся
всегда: у Полярной 16 рядом с расходом здания стоит «кольцевой сети» — о гидрантах, а не о расходе.

Покрытие здания радиусом гидранта — геометрия плана НВК, текст её не даёт.

Четвёртый круг (R4-Q-PPM-114, Р-108): 110 л/с — расход сети и квартала, и если в ПД есть только он,
специалист велел «не сравнивать». В корпусе такой расход подписан и без слов о сети: «наружное
пожаротушение - 110 л/с» (ПЗ Октябрьской), «Система наружного пожаротушения 110л/с» (ИОС2.1
Новослободской), «Расход воды на наружное пожаротушение составляет 110 л/с» (ИОС2.2 ДОО), а расход
здания в корпусе — 20–30 л/с. Поэтому расход от `NETWORK_FLOW` л/с без слова «здания» считается
расходом сети. Меньше гидрантов при том же расходе — нарушение, как и было; расстояние от гидранта
до здания специалист велел брать из ПД, но оно — геометрия плана.
"""
import re

NUMBERS = {"двух": 2, "трех": 3, "трёх": 3, "четырех": 4, "четырёх": 4, "пяти": 5}

FLOW = re.compile(
    r"(?:расход\w*\s+(?:воды\s+)?(?:на\s+(?:нужды\s+)?|для\s+(?:обеспечения\s+)?)|систем\w+\s+)?"
    r"наружн\w+\s+(?:противо)?пожаротушени\w*"
    r"(?P<tail>[^.;]{0,80}?)(?<![\d,.])(?P<value>\d{1,3}(?:[,.]\d{1,2})?)\s*л\s?/\s?се?к?(?![а-яё])", re.I)
HYDRANTS = re.compile(
    r"(?<![а-яё])(?:от|с\s+помощью)\s+(?P<n>двух|тр[её]х|четыр[её]х|пяти|[2-9])\s+"
    r"(?P<kind>(?:существующ|проектируем|установленн|нов)\w*\s+)?(?:пожарн\w+\s+)?гидрант\w*", re.I)
# окружение, в котором расход — не здания: баланс, сеть, квартал, стройплощадка, условия подключения
FOREIGN = re.compile(r"баланс|кольцев|магистральн|квартал|застройк|Q\s?пож|строительств|стройплощадк"
                     r"|точке\s+подключени|технически\w+\s+услови|\bТУ\b|потребност", re.I)
BUILDING = re.compile(r"здани", re.I)
# расход сети и квартала, а не здания, если «здания» при нём не сказано (R4-Q-PPM-114)
NETWORK_FLOW = 100


def _value(raw):
    return float(raw.replace(",", "."))


def flows(flat):
    """Расходы на наружное пожаротушение на странице: значение, «здания ли», подпись."""
    out = []
    for m in FLOW.finditer(flat):
        span = flat[m.start():m.end()]
        building = bool(BUILDING.search(span))
        if not building:
            around = flat[max(0, m.start() - 150):m.start()] + flat[m.end():m.end() + 100]
            if FOREIGN.search(around) or FOREIGN.search(m.group("tail")):
                continue
        value = _value(m.group("value"))
        if not 5 <= value <= 300 or (value >= NETWORK_FLOW and not building):
            continue
        out.append({"value": value, "building": building, "raw": f"{m.group('value')} л/с",
                    "snippet": " ".join(flat[max(0, m.start() - 30):m.end() + 60].split())})
    return out


def hydrants(flat):
    """Сколько пожарных гидрантов обеспечивает здание: число и «существующие ли»."""
    out = []
    for m in HYDRANTS.finditer(flat):
        word = m.group("n").lower()
        n = int(word) if word.isdigit() else NUMBERS.get(word)
        if not n:
            continue
        existing = bool(m.group("kind") and m.group("kind").lower().startswith("существ"))
        out.append({"value": n, "existing": existing, "raw": m.group(0),
                    "snippet": " ".join(flat[max(0, m.start() - 80):m.end() + 40].split())})
    return out


def show(key, values):
    """«30 л/с» или «2 гидранта»."""
    if key == HYDRANT_KEY:
        return ", ".join(f"{v} {'гидрант' if v == 1 else 'гидранта' if v < 5 else 'гидрантов'}"
                         for v in sorted(values))
    return ", ".join(f"{v:g} л/с".replace(".", ",") for v in sorted(values))


FLOW_KEY = "расход на наружное пожаротушение"
HYDRANT_KEY = "число пожарных гидрантов"


def reductions(pd, rd):
    """Ключи, где в РД значение меньше проектного наибольшего: [(ключ, ПД, РД)]."""
    out = []
    for key in (FLOW_KEY, HYDRANT_KEY):
        if pd.get(key) and rd.get(key):
            smaller = [v for v in rd[key] - pd[key] if v < max(pd[key])]
            if smaller:
                out.append((key, sorted(pd[key]), sorted(rd[key])))
    return out
