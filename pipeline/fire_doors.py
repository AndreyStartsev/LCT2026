"""Предел огнестойкости противопожарных преград по местам. PPM-103, задача #93.

Стадии адресуют предел по-разному, и это главная трудность параметра:

    рабочая стадия, спецификация:  «Д11 ДПС 01 Пр 2430(h)-1210 EI 30»      — ключ марка
    проектная стадия, проза:       «двери указанных лифтовых холлов должны
                                    быть с пределом огнестойкости не менее EIS60»  — ключ место

Ключ сравнения — **место**: лестничная клетка, лифтовой холл, тамбур-шлюз, техническое
пространство, электрощитовая, венткамера, шахта лифта, автостоянка, коридор. Сравнивать
по марке нельзя: на Алтуфьевском марка Д-6 подписана и EI30, и EI45, и EI60, на Октябрьской
ДП1.1 — от EI30 до EI120, и какая дверь какая, видно только на плане. Такая марка попадает
в пояснение записи, а не в вердикт.

## Что считается утверждением о пределе

Число со шкалой рядом со словом «огнестойкость». Подписи на планах («EI-30» посреди
экспликации) утверждением не считаются: в плоском тексте чертежа рядом с ними может стоять
что угодно. Замер 24.09: таких подписей по корпусу 16 892, а утверждений о пределе — 2 798.

## Предмет берётся слева от числа

В одном предложении стоят два предмета и два предела: «выделить противопожарными
перегородками с пределом огнестойкости не менее EI 90 c заполнением проёмов
противопожарными дверями EI 60». Поэтому вид преграды — ближайшее слово слева от числа:
дверь, люк, ворота, клапан — «door»; стена, перегородка, перекрытие, шахта — «barrier».
Ключ сравнения — место и вид вместе: дверь с EI и стена с REI — разные величины.

## Шкалы не мешаются

Значение — минуты плюс набор критериев (E — целостность, I — теплоизоляция, S — дымогазо-
непроницаемость, W — тепловой поток, R — несущая способность). «REI60 → EI90» не «класс
понижен», а сравнение стены с дверью: такие пары не сравниваются вовсе. Нарушение — минуты
меньше наименьшего проектного требования того же места и вида либо потеря критерия при тех
же минутах (EIS60 → EI60).
"""
import re

# Предел: REI 120, EIS60, EI-30, R90. Шкала — набор букв, минуты — число
LIMIT_RE = re.compile(r"(?<![A-Za-zА-Яа-я0-9])(?P<let>REI|EIS|EIW|EIWS|EI|RE|R|E|I)\s?-?\s?(?P<min>\d{2,3})(?![\d])")
MINUTES = (15, 30, 45, 60, 90, 120, 150, 180, 240)
# Предел назван словом, а не подписан на плане
WORD_RE = re.compile(r"огнестойкост", re.I)
WORD_BACK, WORD_FWD = 120, 60
CLAUSE_BACK, CLAUSE_FWD = 260, 80
PAGE_BACK = 300              # предмет строки спецификации стоит до границы предложения

# Место: чем адресует проектная стадия
PLACES = (
    ("Лестничные клетки", r"л[ес]стничн\w+\s+клетк\w*|незадымляем\w+\s+л[ес]стничн\w*"),
    ("Лифтовые холлы", r"лифтов\w+\s+холл\w*"),
    ("Шахты лифтов", r"шахт\w+\s+лифт\w*|лифтов\w+\s+шахт\w*"),
    ("Тамбур-шлюзы", r"тамбур[\s-]*шлюз\w*"),
    ("Техническое пространство", r"техническ\w+\s+(?:пространств\w*|подполь\w*|этаж\w*)|техподполь\w*"),
    ("Электрощитовые", r"электрощитов\w*|щитов\w+\s+помещени\w*"),
    ("Венткамеры", r"венткамер\w*|вентиляционн\w+\s+камер\w*"),
    ("Насосные", r"насосн\w*"),
    ("Тепловой пункт", r"тепл\w+\s+пункт\w*|\bИТП\b"),
    ("Кладовые", r"кладов\w*"),
    ("Мусорокамера", r"мусорокамер\w*|мусоросборн\w*"),
    ("Автостоянка", r"автостоянк\w*|паркинг\w*"),
    ("Коридоры", r"коридор\w*"),
    ("Эвакуационные выходы", r"эвакуационн\w+\s+выход\w*"),
)
_PLACE_RES = [(name, re.compile(rx, re.I)) for name, rx in PLACES]

DOOR_RE = re.compile(r"двер\w*|люк\w*|ворот\w*|калитк\w*|клапан\w*|заполнени\w+\s+про[ёе]м\w*"
                     r"|противопожарн\w+\s+штор\w*|занавес\w*", re.I)
BARRIER_RE = re.compile(r"стен\w*|перегородк\w*|перекрыти\w*|покрыти\w*|шахт\w*|преград\w*"
                        r"|марш\w*|площадк\w*|конструкци\w*|узл\w*|проход\w*", re.I)
KIND_NAMES = {"door": "заполнение проёмов", "barrier": "ограждающие конструкции"}
# Марка заполнения проёма: «Д11», «Д-6», «ДПС 01», «ДП1.1», «Л-1»
MARK_RE = re.compile(r"(?<![A-Za-zА-Яа-я0-9])(?:ДПС|ДПМ|ДП|ЛП|Д|Л)\s?-?\s?\d{1,3}(?:[./-]\d{1,3})?(?![\d])")
ATLEAST_RE = re.compile(r"не\s+(?:менее|ниже)\s*$", re.I)


def limits(flat, clause_bounds=None):
    """Утверждения о пределе огнестойкости на странице.

    [{place, kind, minutes, letters, raw, mark, atleast, snippet}] — только там, где предел
    назван словом и предмет определён. Место может быть None: тогда сравнивать не по чему.
    """
    out = []
    for m in LIMIT_RE.finditer(flat):
        minutes = int(m.group("min"))
        if minutes not in MINUTES:
            continue
        around = flat[max(0, m.start() - WORD_BACK):m.end() + WORD_FWD]
        if not WORD_RE.search(around):
            continue                      # подпись на плане, а не утверждение о пределе
        start = clause_bounds(flat, min(len(flat), m.start() + 1)) if clause_bounds else 0
        left = flat[max(start, m.start() - CLAUSE_BACK):m.start()]
        kind = _kind(left)
        if not kind:
            # Строка спецификации начинается предметом, а предел стоит в конце строки, уже
            # за границей предложения: «Дверь наружная противопожарная … 2100х1050 Д11 ДПС 01
            # Пр 2430(h)-1210 EI 30». Такая строка места не называет и в сравнение не идёт,
            # но её марка нужна для пояснения о неоднозначных марках (#93)
            kind = _kind(flat[max(0, m.start() - PAGE_BACK):m.start()])
        if not kind:
            continue                      # предмет не назван: дверь это или стена — неизвестно
        place = _place(left)
        out.append({
            "place": place, "kind": kind, "minutes": minutes,
            "letters": canon_letters(m.group("let")),
            "raw": f"{m.group('let').upper()}{minutes}",
            "mark": _mark(left), "atleast": bool(ATLEAST_RE.search(left[-30:])),
            "snippet": " ".join(flat[max(start, m.start() - 150):m.end() + CLAUSE_FWD].split()),
        })
    return out


def _kind(left):
    door = [x.start() for x in DOOR_RE.finditer(left)]
    barrier = [x.start() for x in BARRIER_RE.finditer(left)]
    if door and (not barrier or door[-1] > barrier[-1]):
        return "door"
    return "barrier" if barrier else None


def _place(left):
    best = None
    for name, rx in _PLACE_RES:
        for m in rx.finditer(left):
            if best is None or m.start() > best[1]:
                best = (name, m.start())
    return best[0] if best else None


def _mark(left):
    """Марка заполнения проёма: первая в строке. В строке спецификации сначала стоит марка
    чертежа, потом тип изделия: «Д11 ДПС 01 Пр 2430(h)-1210» — на планах подписана Д11."""
    m = MARK_RE.search(left[-90:])
    return m.group(0).upper().replace(" ", "") if m else None


# Ключ для утверждений без места: они в сравнение не идут, но их марки нужны в пояснении —
# именно там живёт случай «одна марка, три предела» (#93)
NO_PLACE_KEY = "Место не названо"


def key_of(place, kind):
    """Ключ сравнения: место и вид преграды вместе."""
    return f"{place} — {KIND_NAMES[kind]}"


def value_of(row):
    """Значение кандидата: минуты и набор критериев. Хешируемое, как требует общий путь."""
    return (row["minutes"], row["letters"])


# Порядок критериев в обозначении: REI, EIS, EIW, EIWS — сначала несущая способность,
# потом целостность и теплоизоляция, потом дым и тепловой поток
CRITERIA_ORDER = "REIWS"


def canon_letters(letters):
    """Набор критериев в принятом порядке: «IER» → «REI»."""
    got = set((letters or "").upper())
    return "".join(c for c in CRITERIA_ORDER if c in got)


def show(value):
    minutes, letters = value
    return f"{letters or 'R'}{minutes}"


def reductions(pd, rd):
    """Ключи, где рабочая стадия слабее проектной. [(ключ, было, стало, почему)].

    pd, rd: ключ → набор значений (минуты, буквы). Сравниваются только ключи, названные
    в обеих стадиях: место без пары сравнивать не с чем.

    Нарушение — одно из двух:
    * наименьшие минуты рабочей стадии ниже наименьшего проектного требования;
    * при тех же минутах в рабочей стадии потерян критерий: EIS60 → EI60 (нет дымогазо-
      непроницаемости). Наборы букв, у которых нет общих критериев, не сравниваются —
      это разные величины.
    """
    out = []
    for key in sorted(set(pd) & set(rd)):
        p, r = pd[key], rd[key]
        why = []
        p_min, r_min = min(m for m, _l in p), min(m for m, _l in r)
        if r_min < p_min:
            why.append(f"предел снижен с {p_min} до {r_min} минут")
        lost = _lost_criteria(p, r)
        if lost:
            why.append("потерян критерий " + ", ".join(sorted(lost)))
        if why:
            out.append((key, sorted({show(v) for v in p}), sorted({show(v) for v in r}), "; ".join(why)))
    return out


def _lost_criteria(p, r):
    """Критерии, которых при тех же минутах в рабочей стадии не стало."""
    lost = set()
    for minutes, letters in p:
        same = [l for m, l in r if m == minutes]
        if not same:
            continue
        if not any(set(letters) & set(l) for l in same):
            continue                      # разные величины: R против EI — не сравниваем
        for missing in set(letters) - set().union(*(set(l) for l in same)):
            lost.add(missing)
    return lost


def ambiguous_marks(rows):
    """Марки, под которыми в стадии стоит несколько разных пределов: {марка: {пределы}}."""
    by_mark = {}
    for row in rows:
        if row.get("mark"):
            by_mark.setdefault(row["mark"], set()).add(row["raw"])
    return {mark: limits_ for mark, limits_ in by_mark.items() if len(limits_) > 1}
