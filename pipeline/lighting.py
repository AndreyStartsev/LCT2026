"""Источники света светильников: светодиодные или нет. Четвёртая очередь Матрицы, ZU-130, #28.

Проект задаёт энергосберегающее освещение словами: «в качестве источников света используются
энергоэкономичные светодиодные источники» (ЭЭ Речникова), «Светильник светодиодный, потолочный»
(таблица светильников по помещениям). Рабочая стадия называет светильник в условных обозначениях
ЭО: «Светильник светодиодный накладной 12 Вт, IP65». Значение стадии — набор видов источников
света: светодиодные, люминесцентные, накаливания, галогенные, ДРЛ, ДНаТ.

Упоминание засчитывается только рядом со светильником, лампой или освещением. Не засчитываются
рекомендации и нормы: «с заменой ламп накаливания, люминесцентных ламп» и «внедрение
энергоэффективных (галогенных, люминесцентных и светодиодных) светильников» (ТБЭ), «от
люминесцентных ламп не менее 150 лк» и «не должно быть … ламп накаливания» (указания к АПС),
«прожекторы … могут быть заменены на прожекторы с галогенными лампами» (временное освещение ПОС),
«освещенность для ламп накаливания 30 люкс» (лифты), «Светильник ручной … Лампа накаливания 12В»
(переносные светильники в спецификациях ИТП), «Лампы накаливания, утратившие потребительские
свойства» (отходы в ООС), «Коммутационная нагрузка до 2000 Вт (лампы накаливания) до 1000 Вт
(люминесцентные лампы, LED)» (датчик движения в ЭОМ Полярной 16, #109).

Слово «лампа» в самом упоминании светильника не делает: «Лампа накаливания 25Вт ЛН-25» между
автоматическим выключателем и испытательной коробкой в спецификации щита учёта — деталь щита,
а не освещение здания (#109). Светильник, лампа или освещение ищутся рядом, вне упоминания.
"""
import re

LED = "светодиодные"
KINDS = (
    (LED, re.compile(r"(?<![а-яё])светодиод\w*", re.I)),
    ("люминесцентные", re.compile(r"(?<![а-яё])люминесцентн\w*(?:\s+и\s+\w+)?\s+(?:ламп|источник)\w*", re.I)),
    ("накаливания", re.compile(r"ламп\w*\s+накаливани\w*", re.I)),
    ("галогенные", re.compile(r"(?<![а-яё])(?:металло)?галогенн\w+\s+ламп\w*", re.I)),
    ("ДРЛ", re.compile(r"(?<![А-ЯЁа-яё])ДРЛ(?![А-ЯЁа-яё])")),
    ("ДНаТ", re.compile(r"(?<![А-ЯЁа-яё])ДНаТ(?![А-ЯЁа-яё])")),
)
NEAR_LIGHT = re.compile(r"светильник|ламп|освещени|источник\w*\s+света|светов\w+\s+указател", re.I)
NOT_DESIGN = re.compile(
    r"замен\w*|внедрени\w*|(?<![а-яё])от\s+|не\s+должно\s+быть|могут\s+быть|рекоменд\w*|допускается"
    r"|(?<![а-яё])уч[её]т\w*|ручн\w+|переносн\w+|освещенност\w*\s+для|коммутационн\w*|коммутируем\w*", re.I)
# после упоминания: лампы как отходы в ООС
WASTE_AFTER = re.compile(r"^[^.;]{0,20}?(?:утративш\w+|отход\w*)", re.I)
# после упоминания — «или» со светодиодным: выбор оставлен открытым, это не решение о лампе.
# «…подвесного типа с газоразрядным источником ДНаТ, МГЛ, или с источником света LED» —
# требование к наружному освещению в томе ЭН ДОО на Полярной 25 (#110)
LED_ALTERNATIVE_AFTER = re.compile(r"^[^.;]{0,60}?(?<![а-яё])или(?![а-яё])[^.;]{0,40}?(?:LED|светодиод)", re.I)
WINDOW = 60


def light_sources(flat):
    """Виды источников света на странице с цитатами: [{value, raw, snippet}]."""
    out = []
    for kind, rx in KINDS:
        for m in rx.finditer(flat):
            around = flat[max(0, m.start() - WINDOW):m.start()] + " " + flat[m.end():m.end() + WINDOW]
            if not NEAR_LIGHT.search(around):
                continue
            # рекомендация или норма стоит в том же предложении перед упоминанием
            sentence = re.split(r"[.;]", flat[max(0, m.start() - 120):m.start()])[-1]
            after = flat[m.end():m.end() + 120]
            if NOT_DESIGN.search(sentence) or WASTE_AFTER.search(after[:60]) \
                    or (kind != LED and LED_ALTERNATIVE_AFTER.search(after)):
                continue
            out.append({"value": kind, "raw": m.group(0),
                        "snippet": " ".join(flat[max(0, m.start() - 70):m.end() + 50].split())})
    return out


def show(kinds):
    return ", ".join(sorted(kinds, key=lambda k: (k != LED, k))) or None


def decide(pd, rd):
    """Решение по наборам видов источников света. Возвращает (метка, тип, пояснение)."""
    if not pd and not rd:
        return None, None, "вид источников света не назван ни в одной стадии"
    if not pd:
        return "COMPARISON_IMPOSSIBLE", None, "в проектной стадии вид источников света не назван"
    if not rd:
        return "COMPARISON_IMPOSSIBLE", None, "в рабочей стадии вид источников света не назван"
    # замена — вид, которого проект не называет: если проект сам называет и светодиодные,
    # и люминесцентные (ИОС1.1 ДОО на Полярной 25), люминесцентные в рабочей стадии — не замена
    other = rd - {LED} - pd
    if LED in pd and other:
        return ("VIOLATION_PRESENT", "CONFIGURATION_MISMATCH",
                f"в проекте светодиодные, в рабочей стадии есть {show(other)}")
    if pd == rd:
        return "NO_VIOLATION", "EQUAL_PD_RD", f"в обеих стадиях: {show(pd)}"
    return ("NO_VIOLATION", "NON_TRIGGERING_DIFFERENCE_NO_DECREASE",
            f"в проекте {show(pd)}, в рабочей стадии {show(rd)}")
