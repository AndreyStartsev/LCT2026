"""Объём бетона по элементу из ведомостей расхода: KR-067, черновик шестого круга.

Триггер Матрицы — «итоговое расхождение объёмов материалов между ПД, РД и ИД > 2 %». Сводных
ведомостей по зданию в ПД корпуса нет, поэтому сравнивается объём бетона одного элемента, если
обе стадии его называют: ПД КР Новослободской — «Ведомость расхода бетона для устройства
обвязочной балки … Бетон тяжёлый В25 W8 F200 П4 … м³ 47,8800», РД ограждения котлована — «Объем
бетона на устройство обвязочного пояса - 49,5 м3». Ключ — элемент: «обвязочная балка» и
«обвязочный пояс» — один элемент (словарь `SAME`).

Масса стали по ведомостям расхода — многоколоночные таблицы, их итог к элементу по тексту
не привязать; она пока не сравнивается.
"""
import re

# «нарушения нет» в записи: чем рабочая стадия сошлась с проектом
SAME = "в допуске"

_EL = r"(?P<el>[а-яё]+(?:\s+[а-яё]+){0,2}?)"
_V = r"(?P<v>\d+(?:[.,]\d+)?)"
SHEET = re.compile(rf"ведомост\w*\s+расход\w*\s+бетона\s+(?:для|на)\s+(?:устройств\w+\s+)?{_EL}\s+"
                   rf"(?:№|Поз|Марка|Наименование)[^|]{{0,200}}?(?:м³|м3)\s*{_V}(?![\d,.])", re.I)
NOTE = re.compile(rf"объ[её]м\w*\s+бетона\s+на\s+устройство\s+{_EL}\s*[-–—:]\s*{_V}\s*(?:м3|м³|куб)", re.I)
# одно и то же у разных авторов: обвязочная балка ПД — обвязочный пояс РД
SAME = {"балк": "пояс"}
STOP = {"для", "на", "из", "устройства", "устройство"}


def element_key(words):
    """Ключ элемента: основы слов (четыре буквы), синонимы сведены — «обвя пояс»."""
    stems = []
    for w in words.lower().split():
        if w in STOP:
            continue
        stem = w[:4]
        stems.append(SAME.get(stem, stem))
    return " ".join(stems[:2])


def takeoffs(flat):
    """Объёмы бетона по элементам на странице: [{key, value, raw, label, snippet}], value — м³."""
    out = []
    for pat in (SHEET, NOTE):
        for m in pat.finditer(flat):
            v = float(m.group("v").replace(",", "."))
            if v <= 0:
                continue
            out.append({"key": element_key(m.group("el")), "value": v, "raw": f"{m.group('v')} м³",
                        "label": m.group("el"),
                        "snippet": " ".join(flat[max(0, m.start() - 20):m.end() + 40].split())})
    return out


def changes(pd, rd, tolerance=0.02):
    """Расхождение объёма элемента больше допуска: [(ключ, проект, рабочая, почему)]."""
    out = []
    for key in sorted(set(pd) & set(rd)):
        p, r = max(pd[key]), max(rd[key])
        rel = (r - p) / p if p else 0.0
        if abs(rel) > tolerance:
            out.append((key, pd[key], rd[key], f"{p:g} → {r:g} м³, {rel:+.1%} при допуске {tolerance:.0%}"))
    return out


