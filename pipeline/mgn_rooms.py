"""Универсальные кабины и санузлы для МГН в экспликациях: площадь по номеру помещения. Третья очередь, #27.

В экспликациях Речникова строка помещения в текстовом слое идёт подряд: номер, наименование,
площадь — «1.1-4 Универсальная кабина МГН 5,1». Номер помещения одинаков в ПД (ОДИ, АР)
и в РД (АР), по нему площади и сравниваются. Размеры кабины в плане («не менее 2,2 х 2,25 м»)
в тексте есть только как требование, поэтому уменьшение габаритов видно по площади.

Строка ведомости отделки «1.1-14 Универсальная кабина МГН Монолитные железобетонные конструкции»
площади после наименования не несёт и не берётся.
"""
import re

ROOM = r"-?\d{1,2}(?:\.\d{1,2})?-\d{1,3}[а-я]?|\d{1,4}[а-я]?"
NAME = (r"(?:Универсальн\w+|Доступн\w+)\s+кабин\w*(?:\s+(?:уборной|МГН|для\s+(?:МГН|инвалидов)))?"
        r"|(?:Санузел|Уборная|С/у)\s+(?:для\s+)?(?:МГН|инвалидов)")
TOILET = re.compile(rf"(?<![\w.,/-])({ROOM})\s+({NAME})\s+(\d{{1,3}}[,.]\d{{1,2}})(?![\d,.])")
# площадь в экспликации округлена до десятых: разница меньше — не уменьшение
TOLERANCE = 0.05


def toilet_areas(flat):
    """Кабины и санузлы для МГН на странице: номер помещения, наименование, площадь."""
    return [{"room": m.group(1), "name": m.group(2), "area": float(m.group(3).replace(",", ".")),
             "raw": f"{m.group(3)} м²", "snippet": " ".join(flat[max(0, m.start() - 40):m.end() + 40].split())}
            for m in TOILET.finditer(flat)]


def reductions(pd, rd):
    """Помещения, у которых площадь в РД меньше проектной наибольшей. pd, rd: номер → набор площадей."""
    out = []
    for room in sorted(set(pd) & set(rd), key=_key):
        smaller = [a for a in rd[room] - pd[room] if a < max(pd[room]) - TOLERANCE]
        if smaller:
            out.append((room, [_area(a) for a in sorted(pd[room])], [_area(a) for a in sorted(rd[room])]))
    return out


def _area(value):
    return f"{value:g} м²".replace(".", ",")


def _key(room):
    return [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", room)]
