"""Починка кириллицы, раскодированной не той кодовой страницей. Задача #98.

Часть чертежей приходит с текстовым слоем, в котором русские слова выглядят так:

    «1 13 14 À È Ñåêöèÿ 1 Ñåêöèÿ 2 Áëîê-ñõåìà 24 Ð Ñîãëàñîâàíî Èíâ. №ïîäë.»

Это не сломанный шрифт и не картинка: байты кириллицы cp1251 раскодированы как latin-1.
Обратное преобразование возвращает текст полностью — «Секция 1 Секция 2 Блок-схема 24 Р
Согласовано Инв. №подл.» — и стоит одного вызова, без распознавания и без модели.

Замер 24.09 по корпусу: из 65 402 страниц с текстом так испорчены **1050** — 992 у Полярной
16, 24 у Полярной 25, 17 у Тюменской, остальные единицами. Для правил это была пустота:
подпись «толщина» в виде «òîëùèíà» не находит ни одно выражение.

## Почему по словам, а не целиком

Страница бывает смешанной: часть надписей раскодирована верно, часть нет. Преобразование
всей страницы ломает верную часть — кириллица в latin-1 не кодируется. Поэтому починка
идёт по словам: слово целиком из знаков диапазона latin-1 пробуется обратным
преобразованием и принимается только если получилось кириллическое слово.

## Слова из одной буквы (Р-140)

До 28.09 чинились только слова от двух букв, и в починенном тексте оставались предлоги,
союзы и буквы, приклеенные к числам: «Плиты перекрытия ñ отм.+10,400, наружные стены 4-го è
выше этажей … из монолитного бетона класса Â25W4F75». Класс B25 правила не видели, и у
Полярной 16 плиты надземной части выходили ложным нарушением «РД B30/B35 → ИД B25».

Одна буква сама по себе ничего не доказывает: «à» и «é» — обычные слова французского и
португальского текста, а в корпусе есть и такие инструкции. Поэтому одиночная буква чинится
только в тексте, где неверная кодировка уже доказана: там не меньше `MIN_WORDS_FOR_LETTERS`
целых слов (серия не прилегает к другим буквам) стали кириллицей. Замер по сырому слою
корпуса: где таких слов от одного до четырёх, там слой сканера, мусорный шрифт или штамп
с одним словом; у испорченных страниц их от десяти, промежуточных нет. Буква должна стоять
отдельным словом: соседи — цифры, пробелы и знаки («Â25», «2-õ», «À-È»), но не буквы.

Не чинятся никогда:
- «Ø» и «ø»: в испорченном шрифте этим кодом записан знак диаметра — «Ø10 À500Ñ» значит
  «⌀10 А500С», а не «Ш10»;
- «×» и «÷»: на той же странице они стоят в правильном тексте — «100×100×55», «10÷15»;
- «¨» и «¸» отдельным словом: это куски скобок формульного шрифта, а не «Ё» и «ё».

«Â» перед классом бетона по прочности («Â25», «Â7,5») чинится и без счёта слов: в латинском
тексте такого сочетания не бывает, а класс бетона — то, ради чего правила читают лист.
"""
import math
import re

# Слово из знаков, куда попадает кириллица cp1251, прочитанная как latin-1
SUSPECT_RE = re.compile(r"[¨¸À-ÿ]{2,}")
CYRILLIC_WORD_RE = re.compile(r"^[А-Яа-яЁё]+$")
MIN_WORDS = 2          # одно случайное слово — повод не трогать страницу
# Одиночная буква-кандидат, без ×, Ø, ÷ и ø (см. выше); чинится, только если стоит отдельным словом
LETTER_RE = re.compile(r"[À-ÖÙ-öù-ÿ]")
MIN_WORDS_FOR_LETTERS = 5
# «Â» вплотную перед классом бетона по прочности: B3,5 … B100
CONCRETE_CLASS_RE = re.compile(
    r"Â(?=(?:3[,.]5|5|7[,.]5|10|12[,.]5|15|20|22[,.]5|25|27[,.]5|30|35|40|45|50|55|60|70|80|90|100)"
    r"(?![\d]|[,.]\d))")


def fix_word(word):
    """Кириллическое слово из неверно раскодированного или None."""
    try:
        got = word.encode("latin-1").decode("cp1251")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return None
    return got if CYRILLIC_WORD_RE.match(got) else None


def _alone(text, start, end):
    """Знаки text[start:end] стоят отдельным словом: по краям не буквы, а цифры, пробелы, знаки.

    Буквой считается то, что считает буквой `str.isalpha`: «²» и «½» для выражения `\\w` — тоже
    буквы, и «ì²» (м²) иначе осталось бы непочиненным.
    """
    return (start == 0 or not text[start - 1].isalpha()) and (end == len(text) or not text[end].isalpha())


def letters_allowed(text):
    """Доказана ли в тексте неверная кодировка настолько, чтобы чинить слова из одной буквы.

    Считаются целые слова — серии, не прилегающие к другим буквам: серия внутри латинского
    слова («informações») неверную кодировку не доказывает.
    """
    if not text:
        return False
    whole = sum(1 for m in SUSPECT_RE.finditer(text) if _alone(text, m.start(), m.end()))
    return whole >= MIN_WORDS_FOR_LETTERS


def repair(text, min_words=MIN_WORDS, letters=None):
    """(текст, сколько слов починено). Текст возвращается как есть, если чинить нечего.

    `letters` — чинить ли слова из одной буквы: None — решает сам текст (`letters_allowed`),
    True или False — решено снаружи. Так чинятся слова страницы по одному: у отдельного слова
    своего счёта нет, и решение берётся по странице целиком.
    """
    if not text:
        return text, 0
    fixed = []

    def one(m):
        got = fix_word(m.group(0))
        if got:
            fixed.append(got)
            return got
        return m.group(0)

    def letter(m):
        return one(m) if _alone(m.string, m.start(), m.end()) else m.group(0)

    out = SUSPECT_RE.sub(one, text)
    if len(fixed) < min_words:
        out, fixed = text, []
    if letters is None:
        letters = letters_allowed(text)
    out = (LETTER_RE if letters else CONCRETE_CLASS_RE).sub(letter, out)
    return out, len(fixed)


def repair_words(words, text):
    """Слова страницы по одному — теми же решениями, что и её текст в `repair(text)`.

    У отдельного слова своего счёта нет. Слово от двух букв чинится, если таких на странице
    не меньше `MIN_WORDS`, одиночная буква — если страница доказала кодировку, «Â» перед
    классом бетона — всегда. Иначе слова с координатами расходились бы с текстом страницы.
    """
    many = len(SUSPECT_RE.findall(text or "")) >= MIN_WORDS
    letters = letters_allowed(text)
    return [repair(w, min_words=1 if many else math.inf, letters=letters)[0] for w in words]


def looks_broken(text):
    """Похоже ли, что в тексте есть неверно раскодированная кириллица."""
    return bool(text) and repair(text)[1] > 0
