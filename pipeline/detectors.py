"""Число пожарных извещателей по видам: спецификация ПД против спецификации РД (PPM-108, #189).

Решения специалиста (R3-PPM-108):
- автономные дымовые извещатели в квартирах считаются в составе АПС («ИП 212-142» у Полярной 16);
- уменьшение в пределах допуска (уточнение планировок) — не нарушение. Допуск правила — 5 %;
- две цифры в колонке количества — если спецификация прямо не называет вторую запасом, запаса нет.
  У ДОО «ИП 212-64-R3 W1.02 Рубеж шт. 287 289» в выпуске 06.10.25, а в выпуске 14.02.25 — «шт. 287»:
  вторая цифра — количество после изменения («шт. 2 3 ПС 2, ППА 1» — три прибора, два в ПС и один в
  ППА). Берётся последняя.

Строка спецификации: «19 Извещатель пожарный дымовой … ДИП-34А-03 НВП Болид шт 172 20 …» или
«Извещатель пожарный дымовой адресный ДИП-34А-03 337 шт.». Число перед «шт», за которым стоит своё
число, — часть обозначения («С2000-СП4/220 шт 119»); число в скобках («(12шт.)») — подпись на схеме. Вторая цифра за количеством бывает
номером следующей строки («шт. 1518 4 Извещатель» у Полярной 16): такая не берётся — она равна номеру
строки плюс один или отличается от количества больше чем вдвое.

Вид — по словам строки или по обозначению по ГОСТ Р 53325: ИП 1хх — тепловой, ИП 2хх — дымовой,
ИП 3хх — пламени, ИП 4хх — газовый, ИПР — ручной, ИП 212/101 — комбинированный. Охранные извещатели
(ИО, магнитоконтактные, объёмные) и принадлежности («защитный кожух для ручных пожарных
извещателей», базы, кронштейны) в счёт не идут. Расстановка по планам текстом не проверяется.
"""
import re

TOLERANCE_PCT = 5
TYPES = (("ручной", r"ручн\w*|(?<![А-ЯЁа-яё])ИПР(?![а-яё])"),
         ("комбинированный", r"комбинир\w*|ИП\s?212\s?/\s?101|ИП\s?101\s?/\s?212"),
         ("пламени", r"пламен\w*|(?<![А-ЯЁа-яё])ИП\s?3\d\d(?!\d)"),
         ("газовый", r"газов\w*|(?<![А-ЯЁа-яё])ИП\s?4\d\d(?!\d)"),
         ("тепловой", r"теплов\w*|(?<![А-ЯЁа-яё])ИП\s?1\d\d(?!\d)"),
         ("дымовой", r"дымов\w*|(?<![А-ЯЁа-яё])ИП\s?2\d\d(?!\d)|(?<![А-ЯЁа-яё])ДИП|ИПДЛ|ИПД(?![а-яё])"))
TYPE_RE = [(name, re.compile(p, re.I)) for name, p in TYPES]
# «звуковой» и «объёмный» не признак охранного: у автономного дымового бывает «со встроенным звуковым
# оповещателем», а охранный объёмный без вида пожарного извещателя и так не считается
SECURITY = re.compile(r"охранн\w*|магнит\w*|геркон|(?<![А-ЯЁа-яё])ИО[\s-]?\d|вибрац\w*", re.I)
# принадлежность, а не извещатель: слово стоит в той же строке перед словом «извещатель»
ACCESSORY = re.compile(r"кожух|основани|(?<![а-яё])баз[аеуы](?![а-яё])|кронштейн|розетк|корзин|колпак|переходник|"
                       r"держател|монтажн\w*\s+коробк", re.I)
ROW = re.compile(r"(?P<name>(?:извещател|(?<![А-ЯЁа-яё])ИПР|(?<![А-ЯЁа-яё])ДИП|(?<![А-ЯЁа-яё])ИП\s?\d{3})[^;]{0,300}?)"
                 r"(?:(?<![А-ЯЁа-яё])шт\.?\s*(?P<a>\d{1,5})(?:\s+(?P<b>\d{1,5}))?(?![\d.,])"
                 r"|(?<![\d.,/-])(?P<c>\d{1,5})\s*шт(?![а-яё])(?!\.?\s*\d))", re.I)
ROW_NO = re.compile(r"(?:^|\s)(\d{1,3})(?:\.(\d{1,3}))?\s+$")


# тома пожарной сигнализации по обозначению: «ПС» у ДОО, «СПА» у Полярной 16
FIRE_MARK = re.compile(r"(?:А?У?ПС|СПА|СПС|АПС|СОУЭ|АУПС)(?![А-ЯЁа-яё])", re.I)


def doc_allowed(doc):
    """Тома, где лежит спецификация АПС: сети связи (ИОС5, СС), пожарная безопасность, тома ПС, СПА, АПС.

    Общая пояснительная записка не берётся: у Алтуфьевского ОПЗ другого проекта перечисляет извещатели
    с количеством («ИПР 513-3AM — 32 шт.»), и сумма с ИОС5 считала бы их дважды. ИОС5 узнаётся и по
    обозначению: у ДОО подраздел «ИОС5.4» в реестре без раздела СС.
    """
    doc = doc or {}
    if doc.get("stage") not in ("PD", "RD", "RD_ID_MIXED"):
        return False
    mark = doc.get("mark") or ""
    return doc.get("section") in ("SS", "PB") or bool(FIRE_MARK.match(mark)) or mark.upper().startswith("ИОС5")


def type_of(name):
    return next((t for t, rx in TYPE_RE if rx.search(name)), None)


def _second(a, b, row):
    """Вторая цифра колонки количества — количество после изменения или номер следующей строки."""
    if b is None:
        return None
    if row is not None and b == row + 1:
        return None
    return b if a / 2 <= b <= a * 2 else None


def rows(flat):
    """Строки спецификации с пожарными извещателями: [{key: вид, value: шт., raw, snippet}]."""
    out = []
    for m in ROW.finditer(flat):
        name = m.group("name")
        before = flat[max(0, m.start() - 80):m.start()]
        # начало своей строки: после количества предыдущей
        prefix = re.split(r"(?<![А-ЯЁа-яё])шт\.?", before, flags=re.I)[-1]
        # «(12шт.)» — подпись на структурной схеме, а не строка спецификации
        if SECURITY.search(name) or ACCESSORY.search(prefix) or (m.group("c") and flat[max(0, m.start("c") - 1)] == "("):
            continue
        kind = type_of(name)
        if not kind:
            continue
        if m.group("c"):
            count, raw = int(m.group("c")), f"{m.group('c')} шт."
        else:
            row = ROW_NO.search(before)
            a = int(m.group("a"))
            b = _second(a, int(m.group("b")) if m.group("b") else None,
                        int(row.group(2) or row.group(1)) if row else None)
            count = b if b is not None else a
            raw = f"шт. {a}" + (f" {b}" if b is not None else "")
        if count <= 0:
            continue
        out.append({"key": kind, "value": count, "raw": raw, "autonomous": bool(re.search(r"автономн", name, re.I)),
                    "snippet": " ".join(flat[max(0, m.start() - 20):m.end() + 30].split())})
    return out


def totals(cands, group_of):
    """Число извещателей по видам: {вид: шт.}.

    Внутри документа строки складываются. Документы одной цепочки редакций — копии одного тома
    («(ВП)» и «(ОП)»): у вида берётся наибольшее число среди них. Разные тома складываются.
    """
    per_file = {}
    for c in cands:
        per_file.setdefault(c["file_id"], {}).setdefault(c["key"], 0)
        per_file[c["file_id"]][c["key"]] += c["value"]
    groups = {}
    for fid, counts in per_file.items():
        g = groups.setdefault(group_of(fid), {})
        for kind, n in counts.items():
            g[kind] = max(g.get(kind, 0), n)
    out = {}
    for counts in groups.values():
        for kind, n in counts.items():
            out[kind] = out.get(kind, 0) + n
    return out


def compare(pd, rd, tolerance=TOLERANCE_PCT):
    """(меньше сверх допуска, нет в РД, в допуске или больше): [(вид, ПД, РД, %)] и [вид]."""
    fewer, missing, ok = [], [], []
    for kind in sorted(pd):
        if kind not in rd:
            missing.append(kind)
            continue
        pct = round((pd[kind] - rd[kind]) / pd[kind] * 100)
        (fewer if pct > tolerance else ok).append((kind, pd[kind], rd[kind], pct))
    return fewer, missing, ok


def show(counts):
    """«дымовой — 337, ручной — 69 шт.»"""
    return ", ".join(f"{k} — {n}" for k, n in sorted(counts.items(), key=lambda kv: -kv[1])) + " шт." if counts else None


# ---------- состав и ёмкость АПС: IOS5-080 (#190) ----------
#
# Решения специалиста (R3-IOS5-080): ёмкость АПС — число адресных устройств; объединение ЗКПС в РД при
# том же числе извещателей — не нарушение; если ПД описывает ЗКПС только текстом, число ЗКПС не
# сравнивается. Поэтому метки ЗКПС берутся только со страниц, где их три и больше (структурная схема,
# планы), и идут в пояснение, а решает число адресных устройств.

ZONE = re.compile(r"ЗКПС[_\s]?(?P<z>(?:ду|д\.у\.)?\s?\d+(?:\.\d+)?)", re.I)
MIN_ZONES_ON_PAGE = 3
QTY = re.compile(r"(?<![А-ЯЁа-яё])шт\.?\s*(?P<a>\d{1,5})(?:\s+(?P<b>\d{1,5}))?(?![\d.,])"
                 r"|(?<![\d.,/-])(?P<c>\d{1,5})\s*шт(?![а-яё])(?!\.?\s*\d)", re.I)
# адресное устройство: «адресный», «адресно-аналоговый» или протокол R3 у Рубежа («МДУ-1С прот.R3», «АМ-1-R3»)
ADDRESSABLE = re.compile(r"адресн\w*|прот\.?\s?R3|[-\s]R3(?![A-Za-z0-9])", re.I)
# охранные адресные устройства: объёмные, магнитоконтактные, звуковые «разбития стекла», радиоканальные
SECURITY_DEVICE = re.compile(r"охранн\w*|магнит\w*|геркон|(?<![А-ЯЁа-яё])ИО[\s-]?\d|вибрац\w*|объ[её]мн\w*|"
                             r"С2000-(?:СМК|ИК|СТ|ШИК)|Ладога|Фотон|Астра", re.I)
# количество в скобках — подпись на структурной схеме («1ИЗ1.250 (12шт.)», ИОС5.4 ДОО), а не строка спецификации
IN_BRACKETS = re.compile(r"\(\s*$")
# приборы, питание, шкафы и материалы — не адресные устройства линии, хотя «контроллер адресных устройств»
NOT_DEVICE = re.compile(r"контроллер|прибор|блок\w*\s+индикац|пульт|источник|ИБП|ИВЭПР|шкаф|бокс|аккумулятор|кабел|"
                        r"коробк|лоток|ЦПИУ|программ|монитор|сервер|преобразовател|(?<![А-ЯЁа-яё])ШУ[НЗ]", re.I)
DEVICE_KEY = "адресные устройства"


def zones(flat):
    """Метки ЗКПС страницы, если их три и больше: «ду1», «1.6» (у «ЗКПС_ду1» и «ЗКПС ду1» одна метка)."""
    found = {re.sub(r"\s", "", m.group("z")).lower().replace("д.у.", "ду") for m in ZONE.finditer(flat)}
    return sorted(found) if len(found) >= MIN_ZONES_ON_PAGE else []


def device_rows(flat):
    """Строки спецификации с адресными устройствами АПС: [{key, value: шт., raw, snippet}].

    Строка — текст между количеством предыдущей строки и своим количеством. Охранные устройства,
    приборы, питание и шкафы не считаются. Тома без пожарных извещателей (охрана, СКУД) отсекает
    построитель записи: адресные расширители и «звуковые» извещатели тома охраны Тюменской (5.5.2)
    по строке от пожарных не отличить.
    """
    out, prev = [], 0
    for m in QTY.finditer(flat):
        name = flat[prev:m.start()]
        before = flat[max(0, m.start() - 80):m.start()]
        prev = m.end()
        if IN_BRACKETS.search(before) or not ADDRESSABLE.search(name) or NOT_DEVICE.search(name) \
                or SECURITY_DEVICE.search(name):
            continue
        if m.group("c"):
            count, raw = int(m.group("c")), f"{m.group('c')} шт."
        else:
            row = ROW_NO.search(re.split(r"(?<![А-ЯЁа-яё])шт\.?", before, flags=re.I)[-1] or before)
            a = int(m.group("a"))
            b = _second(a, int(m.group("b")) if m.group("b") else None,
                        int(row.group(2) or row.group(1)) if row else None)
            count = b if b is not None else a
            raw = f"шт. {a}" + (f" {b}" if b is not None else "")
        if count > 0:
            out.append({"key": DEVICE_KEY, "value": count, "raw": raw,
                        "snippet": " ".join(flat[max(0, m.start() - 90):m.end() + 10].split())})
    return out
