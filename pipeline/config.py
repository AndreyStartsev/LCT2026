def register_object(object_id, root, name=None, split="UPLOAD"):
    """Объект, пришедший загрузкой в сервис: корень — рабочий каталог процесса.

    Модули конвейера находят файлы объекта через OBJECTS, поэтому загруженная папка
    регистрируется здесь же. Идентификаторы файлов по-прежнему берутся из реестра
    организатора по SHA-256, так что загрузка его объекта даёт его идентификаторы.
    """
    OBJECTS[object_id] = {"name": name or object_id, "root": root, "split": split}
    return OBJECTS[object_id]

