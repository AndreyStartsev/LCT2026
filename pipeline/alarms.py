"""Тип системы оповещения и управления эвакуацией (СОУЭ). PPM-110, #145, Р-106.

Тип СОУЭ (1–5) задаёт раздел ПБ или ИОС5: «Для оповещения и управления эвакуацией при пожаре
предусмотрена СОУЭ 3-го типа» (Тюменская-5), «здание оснащается СОУЭ - 3 типа» (ДОО), «СОУЭ не
ниже 4-го типа» (Новослободская). Рабочая стадия — общие данные тома ПС/СОУЭ. Черновик специалист
принял как есть: тип в РД ниже проектного — нарушение.

Не тип объекта: условие из инструкции «при отсутствии на объекте СОУЭ 3-го типа и выше» (ИД
Речникова) и «экстренной связи … СОУЭ не ниже 3-го типа» (ИРД Новослободской) — требование к
другой системе.
"""
import re

TYPE = re.compile(r"СОУЭ\s*(?:\([^)]{0,40}\)\s*)?(?:[-–—:]\s*)?(?:не\s+(?:ниже|менее)\s+)?(?P<n>[1-5])\s*-?\s*(?:го\s+)?тип\w*"
                  r"|(?P<n2>[1-5])\s*-?\s*(?:го\s+)?тип\w*\s+(?:системы\s+)?СОУЭ", re.I)
FOREIGN = re.compile(r"при\s+отсутствии|экстренн\w+\s+связ|для\s+СОУЭ", re.I)


def soue_types(flat):
    """Тип СОУЭ на странице: [{value, raw, snippet}]."""
    out = []
    for m in TYPE.finditer(flat):
        if FOREIGN.search(flat[max(0, m.start() - 60):m.end()]):
            continue
        n = int(m.group("n") or m.group("n2"))
        out.append({"value": float(n), "raw": f"{n}-го типа",
                    "snippet": " ".join(flat[max(0, m.start() - 80):m.end() + 30].split())})
    return out
