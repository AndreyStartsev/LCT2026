"""Значения, привязанные к конструктивному элементу. Вторая очередь Матрицы, задача #26.

У объектного показателя первой очереди одно значение на стадию: площадь застройки,
этажность. У конструктивного своё значение у каждого элемента: «фундаментная плита —
бетон класса B40», «стена в грунте — B25». Эталон организатора так и записывает:
три записи KR-055 на Новослободской с разными элементами в локации. Поэтому здесь
извлекается пара «элемент — значение», а решение принимается по каждому элементу.

## Как значение привязывается к элементу

Класс бетона ищется только в бетонном окружении: рядом слова «бетон», «класс», «кл.»,
за ним марки F и W или он стоит в перечне «классы по прочности на сжатие». Иначе
«В1» из обозначения вытяжной системы стал бы классом бетона.

Элемент берётся из того же предложения или пункта перечня, ближайший к значению.
Предложение без элемента, которое начинается с «Характеристики бетона» или
«Материал», продолжает предыдущее: так устроена пояснительная записка КР Речникова,
где заголовок элемента стоит за предложение до класса.

Если в предложении элемента нет вовсе, как в таблице материалов на листе, элемент
берётся со страницы, если на ней назван ровно один элемент, а затем из пути файла:
«Подземная автостоянка/4. КЖ2.1 Вертикальные конструкции -1 этажа». Такая привязка
помечается: понижение класса только по ней не объявляется.

## Подвохи, найденные в корпусе

- «Все несущие конструкции нулевого цикла кроме фундаментной плиты выполнены из бетона
  класса В60» — ближайший элемент исключён словом «кроме», значение к плите не относится.
- «Бетонная подготовка из бетона класса В7,5», «фундамент под кран», «сваи-пустышки»,
  отмостка и бортовой камень — не несущие конструкции здания, значения отбрасываются.
- «6.2.12. Подпорные стены. … Выравнивающая стенка – монолитная железобетонная толщиной 100мм
  бетона класса В30»: подпорная стена участка названа в заголовке раздела и в первых предложениях,
  а дальше описана по частям. Стенка без части здания, перед которой текст называл только
  подпорную стену и её части, — тоже подпорная стена (`retaining_passage`).
- «Пилоны, колонны, стены -3 по +1 В60»: этажи от минус третьего относятся к подземной
  части, хотя диапазон заходит на первый этаж. Так их записал эталон организатора.
- «Толщиной 800 мм с уширением под колонну 1000 мм»: местное утолщение не толщина плиты.
- Исполнительная схема Полярной 16: в спецификации листа «Бетонирование плиты перекрытия
  Бетон B25» часть здания не названа, и значение уходило в обе части — в подземной выходило
  ложное понижение B35 → B25. Часть здания называет штамп листа: «…плиты перекрытия в осях
  1-13/А-И на отм.+52.400».
- «Плиты покрытия вентшахт … Бетон В25», «Стены лифтовых надстроек … В25» и общие указания листа
  стен технического чердака Полярной 16 части здания не называют, и значения уходили и в подземную
  часть. Это конструкции над последним этажом: значение идёт только в надземную часть, если
  в предложении нет подземной части, автостоянки или стилобата (`roof_context`).
- «Плита перекрытия подвала (отм. -0,150), максимальным пролетом 7,250 м – железобетонная, толщиной
  200 мм, из монолитного бетона В35W4F75» в ПД КР1 Полярной 16: класс в 127 знаках от элемента, дальше
  окна NEAR, а после «отм.» граница предложения. Класс плиты подвала в ПД не брался, хотя толщину 200 мм
  из того же предложения читали. Элемент, который открывает предложение прозы, берётся и дальше NEAR
  (`_sentence_head`), в таблице окно прежнее.
"""
import re

# ---------- классы бетона ----------

CONCRETE_CLASSES = (7.5, 10, 12.5, 15, 20, 22.5, 25, 27.5, 30, 35, 40, 45, 50, 55, 60, 70, 80, 90, 100)

# «стали кл. В 100x100»: класс плотности воздуховода и его сечение, а не бетон B100. За классом бетона
# размер не стоит; таблицы воздуховодов в XLSX дошли до правил с #112, и у ДОО так появлялось «B100» в ИД
_CLASS_RE = re.compile(r"(?<![\w/])[BВ]\s?(\d{1,3}(?:[,.]5)?)(?![\d])(?!\s?[xх×*]\s?\d)")
_CONCRETE_BEFORE = re.compile(r"бетон\w*|класс\w*|\bкл\.|марк\w*\s+конструкци", re.I)
_MARKS_AFTER = re.compile(r"^\s*[,;]?\s*(?:\(?\s*)?(?:марк\w*\s+)?[FW]\s?\d", re.I)
_CLASS_LIST = re.compile(r"класс\w*\s+(?:бетона\s+)?по\s+прочности", re.I)


def class_label(number):
    """B40, B7,5: латинская B и запятая, как в эталоне организатора."""
    text = f"{number:g}".replace(".", ",")
    return f"B{text}"


def class_mentions(flat):
    """Классы бетона на странице: (начало, конец, число). Только в бетонном окружении."""
    out = []
    for m in _CLASS_RE.finditer(flat):
        number = float(m.group(1).replace(",", "."))
        if number not in CONCRETE_CLASSES:
            continue
        before = flat[max(0, m.start() - 45):m.start()]
        after = flat[m.end():m.end() + 25]
        if (_CONCRETE_BEFORE.search(before) or _MARKS_AFTER.search(after)
                or _CLASS_LIST.search(flat[max(0, m.start() - 900):m.start()])):
            out.append((m.start(), m.end(), number))
    return out


# ---------- элементы ----------

UNDERGROUND = "подземной части"
ABOVEGROUND = "надземной части"
MIXED = "по всей высоте"     # «плита -2го до кровли»: элемент обеих частей, локации нет

# Тип элемента: регулярное выражение и нужна ли зона. Порядок важен: «стена в грунте»
# проверяется раньше стен, «фундаментная плита» раньше плит перекрытия. «Грунт» бывает и без
# окончания: на исполнительной схеме Новослободской так и написано — «Бетонирование стены в грунт
# методом ВПТ (бетон B25W8F200)», и стена в грунте становилась стеной вертикальных конструкций
# обеих частей здания (#116); «в грунтовых водах» и «в грунтах» стеной в грунте не становятся
ELEMENT_TYPES = (
    ("Стена в грунте", r"стен\w*\s+в\s+грунт(?:е|(?![а-яёa-z]))", False),
    ("Фундаментная плита", r"фундаментн\w*\s+плит\w*|фунд\.\s*плит\w*|плит\w*\s+фундамент\w*|фундаментн\w*\s+плиту", False),
    # распределительный ростверк — отдельный элемент: у Полярной 16 в РД он В20 отдельной строкой
    # ведомости, плитный — В35, как в ПД, а ПД класса распределительного не называет. Слитые вместе,
    # они давали «понижение B35 → B20/B35»; специалист: «скорее всего, в ПД просто не указан класс
    # распределительного ростверка» (#136)
    ("Распределительный ростверк", r"распределительн\w*\s+ростверк\w*", False),
    ("Ростверки", r"ростверк\w*", False),
    # «стены лестниц» и «стены лестничных клеток» — вертикальные конструкции, а не лестницы
    ("Лестницы", r"(?<!стены\s)(?<!стен\s)(?:лестничн\w+\s+(?:марш|площадк)\w*|лестниц[аыу]?\b|марш\w*\s+и\s+площадк\w*)", False),
    ("Плиты перекрытия", r"плит\w*\s+(?:перекрыти|покрыти)\w*|плит[аы]\s+(?=-?\d{1,2}\s*-?го\b)|перекрыти\w*|покрыти\w+\s+(?:стилобата|паркинга)|горизонтальн\w+\s+конструкци\w*|переходн\w+\s+(?:плит|элемент)\w*", True),
    ("Вертикальные конструкции", r"вертикальн\w+\s+(?:несущ\w+\s+)?конструкци\w*|пилон\w*|колонн\w*|(?<!в\s)(?<!подпорн\w\s)(?<!подпорные\s)стен\w*|стены\s+подвала", True),
)
_ELEMENT_RES = [(name, re.compile(rx, re.I), zoned) for name, rx, zoned in ELEMENT_TYPES]

# Не несущие конструкции здания: значения рядом с ними не относятся к элементам Матрицы.
# «Смотровые устройства» — колодцы кабельной канализации связи: в технических условиях ПАО МГТС из ПЗ
# Полярной 16 «плиты перекрытия и разгрузочные плиты для смотровых устройств, из бетона класса не менее
# В25» становились плитами перекрытия здания, а «колодцы» стоят дальше окна в 90 знаков (Р-143)
_NOT_STRUCTURAL_WORDS = (
    r"подготовк\w*|стяжк\w*|отмостк\w*|бортов\w*|благоустр\w*|форшахт\w*|под\s+кран|пустышк\w*"
    r"|лотк\w*|лоток|обойм\w*|канал\w*|колодц\w*|смотров\w+\s+устройств\w*|{mix}тротуар\w*|дорожк\w*|площадк\w+\s+(?:для|под)"
    r"|приямк\w*|подпорн\w+\s+стен\w*|ограждени\w+\s+территори\w*|обвязочн\w+\s+пояс\w*|сва[ийяе]\w*|БСС|БНС")
_NOT_STRUCTURAL = re.compile(_NOT_STRUCTURAL_WORDS.format(mix=r"\bБСТ\b|"), re.I)
# В актах освидетельствования класс бетона записан как марка смеси по документу о качестве:
# «бетонной смеси … партии БСТ В25 П4 F200 W8». В чертежах «БСТ» — строка спецификации
# без элемента, в акте — то, из чего построено (#42).
_NOT_STRUCTURAL_BUILT = re.compile(_NOT_STRUCTURAL_WORDS.format(mix=""), re.I)
# Папки исполнительной документации ограждения котлована: «Ограждение котлована. СВГ»,
# «…БСС» — стена в грунте траншейная и из буросекущих свай (свайная стена в грунте);
# форшахта и обвязочный пояс — не она
_PIT_WALL_PATH = re.compile(r"\bСВГ\b|ограждени\w+\s+котлован\w*\W+(?:СВГ|БСС|буросекущ\w*)", re.I)
_EXCEPT = re.compile(r"(?:кроме|за\s+исключением|помимо)\s+$", re.I)
# Элемент после предлога — не то, о чём говорит значение: «выпуски из фундаментной плиты»
# на листе стен, «опирание на плиту», «гидроизоляция по плите»
_PREPOSITION = re.compile(
    r"(?:^|[\s«(\"])(?:из|на|над|под|от|до|к|по)\s+(?:(?:ж/б|монолитн\w+|железобетонн\w+|сборн\w+)\s+)*[«\"]?$", re.I)

_NEG_RANGE = re.compile(r"(?:(?<=\s)|^)-\s?\d{1,2}(?:-?го)?\s*(?:по|до)\s*(?:\+?\s?(\d{1,2})|\+?\s?(кровл\w*))", re.I)
_UNDER = re.compile(
    r"подземн\w*|нулево\w+\s+цикл\w*|подвал\w*|техподпол\w*|техническ\w+\s+подпол\w*"
    r"|(?<![\w.,])-\s?\d\s*(?:-?го\s+)?(?:подземн\w+\s+)?эт\w*|отм\.?\s*-\s?\d|минус\s+\d|на\s+отм\w*\.?\s*-", re.I)
# отметка со знаком: «на отм. -5.250» — подземная часть, «с отм. +1.620» — надземная (#62).
# Диапазон этажей с положительными номерами — надземная часть: «Наружные стены 2-24 этажей» в КР1 ПД
# Полярной 16. Дефис перед номером этажа ниже читается как минус («-1 этажа» надземной частью не
# считается), и «24» из «2-24» отбрасывалось так же: класс стен уходил в обе части здания (Р-144).
# Диапазон, который начинается с минуса или тире, сюда не попадает: «-3 по +1» и «-2го до кровли»
# разбирает _NEG_RANGE
_ABOVE = re.compile(
    r"надземн\w*|типов\w+\s+этаж\w*|(?<![\w-])\+\s?\d{1,2}\s*(?:по|до)|(?:^|\s)(?:с|со)\s+\d{1,2}\s*(?:-?го)?\s*(?:по|до)\s+\d{1,2}"
    r"|(?<![-−–—\d.,])\b\d{1,2}\s*[-−–—]\s*\d{1,2}\s*(?:-?го\s+)?этаж\w*"
    r"|(?<![-\d.,])\b\d{1,2}\s*(?:-?го\s+)?этаж\w*|кровл\w*|чердак\w*|отм\w*\.?\s*\+\s?\d", re.I)


def zone_of(text):
    """Подземная или надземная часть по тексту рядом с элементом, иначе None."""
    if not text:
        return None
    neg = _NEG_RANGE.search(text)
    if neg:
        # эталон относит «-3 по +1» к подземной части; диапазон до кровли — вся высота здания
        if neg.group(2) or int(neg.group(1)) > 2:
            return MIXED
        return UNDERGROUND
    under, above = _UNDER.search(text), _ABOVE.search(text)
    if under and (not above or under.start() <= above.start()):
        return UNDERGROUND
    if above:
        return ABOVEGROUND
    return None


# Явная отметка листа — в метрах со знаком: «на отм.+52.400» в штампе исполнительной схемы или
# диапазон «+28,400...+70,400» на её разрезе. Одиночное «-0.100» без «отм.» на этих листах —
# образец знака в условных обозначениях («проектная отметка верха плиты»), а не отметка плиты,
# а нулевая отметка («+0,000=146.200» — привязка к абсолютной) части здания не называет
_LEVEL = r"([+\-−–])\s?(\d{1,3})[.,](\d{3})(?!\d)"
_SHEET_LEVEL = re.compile(r"(?<![а-яё])отм(?:етк\w*|\.)?\s*" + _LEVEL, re.I)
_SHEET_RANGE = re.compile(_LEVEL + r"\s*(?:\.{2,3}|…)\s*" + _LEVEL)


def sheet_zone(flat):
    """Часть здания по явным отметкам листа: все выше нуля — надземная, все ниже — подземная,
    отметки обоих знаков или ни одной — None."""
    signs = set()
    for rx in (_SHEET_LEVEL, _SHEET_RANGE):
        for m in rx.finditer(flat):
            groups = m.groups()
            for i in range(0, len(groups), 3):
                sign, whole, frac = groups[i:i + 3]
                if int(whole) or int(frac):
                    signs.add("+" if sign == "+" else "-")
    if signs == {"+"}:
        return ABOVEGROUND
    if signs == {"-"}:
        return UNDERGROUND
    return None


# ---------- конструкции уровня кровли ----------

# Вентшахты, лифтовые надстройки, технический чердак, парапеты, выходы на кровлю, машинное помещение
# лифтов стоят над последним этажом. Предложение о них часть здания обычно не называет, и значение уходило
# в обе части: у Полярной 16 «Плиты покрытия вентшахт … Бетон В25» из КЖ6.2 становилось классом плит
# перекрытия подземной части, в ПД туда же шли «Плиты покрытий лифтовых надстроек … В25» (Р-143).
# Чердак и выход на кровлю `zone_of` и так относит к надземной части, но здесь они нужны для листа: лист
# стен технического чердака называет свои стены «вертикальными конструкциями» без части здания. Подсказка
# слабая: она только сужает значение, которое иначе ушло бы в обе части, и не спорит с частью здания,
# названной где-либо ещё. Одна «кровля» подсказкой не считается: «плита -2го до кровли» — вся высота здания
_ROOF_LEVEL = re.compile(
    r"вент(?:иляционн\w+\s+|\.\s*)?шахт\w*|надстро\w*|надстра\w*|парапет\w*|чердак\w*|чердач\w+"
    r"|машинн\w+\s+(?:помещени|отделени)\w*|выход\w*\s+на\s+кровл\w*", re.I)
# «Парапетная стенка», «чердачные стены»: конструкция кровли названа прилагательным перед элементом
_ROOF_ADJ = re.compile(r"(?:парапетн|чердачн)\w*\s+$", re.I)
# Конструкция кровли, названная частью подземной: «вентшахты подземной автостоянки», «вент.шахт подземного
# этажа», «парапет стилобата». Шахта подземной автостоянки выходит наверх во дворе, а покрытие стилобата
# и паркинга — крыша подземной части; значит, на листе конструкции кровли не только над последним этажом.
# Через конец предложения не смотрим: «…обеспечивают выход на кровлю. Выходы из подземного этажа…»
_ROOF_OF_UNDER = re.compile(r"[\s(«\"]{1,3}(?:[а-яё.]+\s+){0,2}?"
                            r"(?:подземн|автостоянк|паркинг|стилобат|подвал|техподпол|подпол)\w*", re.I)
_UNDER_ROOF = re.compile(_UNDER.pattern + r"|автостоянк\w*|паркинг\w*|стилобат\w*", re.I)
ROOF_AFTER = 60      # «плиту покрытия по профилированному настилу над вентиляционными шахтами»
# Дополнение элемента кончается на запятой, тире, точке с запятой, конце предложения: «стены, парапеты — B30» —
# это стены вообще и парапеты, а не стены парапетов
_ROOF_TAIL_STOP = re.compile(r"[,;]|\s[-–—]\s|\.\s+[А-ЯЁA-Z]")
# Шифр документа: «130-1222-ОК-1/Н-КЖ1.1», «24-П-ПИР-Р-КЖ5.4». Так начинается строка перечня комплектов
# и ссылка на другой том: «…-КЖ1.1 Секция 1. Вертикальные конструкции с отм. -0,150 до отм.+4,500» —
# это содержание другого тома, а не этого листа
_DOC_CODE = re.compile(r"[\w.]+(?:[-/][\w.]+){1,8}-(?:КЖИ|КЖ|КР|КМ|АР)\d*[\d.]*", re.I)
DOC_REF_AFTER = 80
ROOF_SHEET_MIN = 2   # лист конструкций кровли называет их не один раз: лист стен чердака — десяток


def _roof_word(flat, lo, hi):
    """Слово конструкции кровли между lo и hi, не названной частью подземной."""
    for m in _ROOF_LEVEL.finditer(flat, lo, hi):
        if not _ROOF_OF_UNDER.match(flat, m.end(), m.end() + 40):
            return True
    return False


def roof_element(flat, s, e):
    """Элемент [s, e) — конструкция уровня кровли: «плиты покрытия вентшахт», «стены лифтовых надстроек»,
    «парапетная стенка». Слово стоит при элементе: прилагательным перед ним или в дополнении сразу после —
    до знака препинания, класса бетона или следующего элемента."""
    if _ROOF_ADJ.search(flat, max(0, s - 30), s):
        return True
    hi = min(len(flat), e + ROOF_AFTER)
    for rx in (_ROOF_TAIL_STOP, _CLASS_RE):
        stop = rx.search(flat, e, hi)
        if stop:
            hi = stop.start()
    other = element_mentions(flat[e:hi])
    if other:
        hi = e + other[0][0]
    return _roof_word(flat, e, hi)


def roof_context(flat):
    """Что лист говорит о конструкциях кровли: None — подсказку не применять, иначе типы элементов,
    которые лист называет только конструкциями кровли.

    None — лист называет конструкцию кровли частью подземной («вентшахты подземной автостоянки»): на таком
    листе вентшахта или парапет над последним этажом не стоят.

    Тип элемента — лист конструкций кровли: у Полярной 16 это общие данные КЖ7.1 «Вертикальные
    железобетонные конструкции выше отм.+73,400» — стены технического чердака, лифтовых надстроек,
    парапетов. Общие указания листа говорят «Вертикальные конструкции — монолитные железобетонные стены …
    В25» без части здания, и это стены чердака. Условие: элементы этого типа названы конструкциями кровли
    не меньше ROOF_SHEET_MIN раз, а подземными — ни разу. Строки перечня комплектов и ссылки на другие тома
    не считаются: «КЖ1.1 Секция 1. Вертикальные конструкции с отм. -0,150 до отм.+4,500» есть на общих
    данных каждого комплекта, и о содержании этого листа она не говорит.
    """
    for m in _ROOF_LEVEL.finditer(flat):
        if _ROOF_OF_UNDER.match(flat, m.end(), m.end() + 40):
            return None
    refs = [m.end() for m in _DOC_CODE.finditer(flat)]
    roof, under = {}, set()
    for s, e, name, zoned in element_mentions(flat):
        if not zoned or any(0 <= s - r <= DOC_REF_AFTER for r in refs):
            continue
        if zone_of(flat[s:e + 40]) == UNDERGROUND:
            under.add(name)
        elif roof_element(flat, s, e):
            roof[name] = roof.get(name, 0) + 1
    return frozenset(name for name, n in roof.items() if n >= ROOF_SHEET_MIN and name not in under)


def element_mentions(flat):
    """Упоминания элементов: (начало, конец, тип, нужна ли зона). Пересечения отдаются
    раньше найденному типу: «стена в грунте» не превращается ещё и в «стену»."""
    taken, out = [], []
    for name, rx, zoned in _ELEMENT_RES:
        for m in rx.finditer(flat):
            if any(m.start() < e and s < m.end() for s, e in taken):
                continue
            taken.append((m.start(), m.end()))
            out.append((m.start(), m.end(), name, zoned))
    out.sort()
    return out


ZONED = ("Вертикальные конструкции", "Плиты перекрытия")


def location_name(element, zone):
    if element in ZONED:
        return f"{element} {zone}" if zone and zone != MIXED else None
    return element


def location_names(element, zone):
    """Локации значения: обычно одна, но у элемента без названной части здания — обе.

    Пояснительная записка описывает конструкции здания целиком: «стены внутренние
    и наружные — из тяжёлого бетона В30», «плиты перекрытия — В30». Части здания
    в таком предложении нет, и раньше значение пропадало: у контрольного объекта так
    терялись 16 классов бетона из 43 в проектной стадии, а рабочая стадия называла
    те же конструкции с частью здания — сравнивать было не с чем. Сказанное обо всех
    стенах относится и к подземным, и к надземным, поэтому значение идёт в обе локации.

    То же для «по всей высоте»: «плита от -2-го до кровли» — это обе части здания.
    Сузить до одной части может `bind`: по отметкам листа исполнительной схемы (`sheet_zone`)
    и у конструкций кровли (`roof_context`).
    """
    if element not in ZONED:
        return [element]
    if zone and zone != MIXED:
        return [f"{element} {zone}"]
    return [f"{element} {UNDERGROUND}", f"{element} {ABOVEGROUND}"]


# ---------- границы предложений ----------

_BOUNDARY = re.compile(r"(?:(?<=[.;:])\s+(?=[А-ЯЁA-Z0-9·•\-–—«\"„])|\s[·•]\s|\s\d{1,2}\.\s(?=[А-ЯЁ])|\s-\s(?=[а-яё]))")
_CONTINUES = re.compile(r"^\W*(?:характеристик\w*\s+бетона|материал\w*|бетон\w*|класс\w*|марк\w*|-\s*бетона)", re.I)
# Обрывок предыдущего предложения после двоеточия: «…безбалочная): 250, 900 мм.»
_FRAGMENT = re.compile(r"^[\s\d.,;:хx×*/()-]*(?:мм|м|шт)?[\s.,;:)]*$", re.I)


def clause_bounds(flat, pos):
    """Начало предложения или пункта перечня, в котором стоит позиция."""
    start = 0
    for m in _BOUNDARY.finditer(flat, max(0, pos - 400), pos):
        start = m.end()
    return start


NEAR = 120           # элемент в предложении ищется не дальше: в таблице предложение длинное
_TABLE_HEAD = re.compile(r"ведомост\w+\s+расхода\s+бетона|марка\s+конструкци\w*", re.I)
MIN_STRUCTURAL_CLASS = 20   # B7,5–B15 в корпусе — подготовка, стяжка, благоустройство

# Предложение прозы, которое открывает элемент (Р-145). В пояснительной записке предложение бывает длиннее
# NEAR: «Плита перекрытия подвала (отм. -0,150), максимальным пролетом 7,250 м – железобетонная, толщиной
# 200 мм, из монолитного бетона В35W4F75» (ПД КР1 Полярной 16, стр. 28) — класс в 127 знаках от элемента.
# Сокращение перед отметкой или номером предложение не кончает: `_BOUNDARY` видит конец предложения после
# «отм.», и `clause_bounds` начинал это предложение с «-0,150)»
_ABBREV_END = re.compile(r"(?<![а-яё])(?:отм|пп?|см|рис|табл|прил|разд|стр|ст|ч)\.$", re.I)
_NUMBER_START = re.compile(r"[\d+\-−–—]")
HEAD_BACK = 400      # начало предложения ищется так же далеко, как у clause_bounds
# перед элементом — номер пункта «8.», маркер перечня, скобка или кавычка
_LEAD = re.compile(r"\W*(?:\d{1,2}(?:\.\d{1,2})*\.?\s)?\W*")
# Слово с заглавной буквы посреди предложения — шапка или ячейка таблицы («Материал», «Бетон») либо начало
# следующего предложения без точки. Сокращения заглавными («ГОСТ», «СП», «А500С») им не считаются
_TITLE_WORD = re.compile(r"(?<!\w)[А-ЯЁ][а-яё]+")
# конец предложения за значением: точка, «;», «!» или «?», а за ними — новое предложение или конец текста
_PROSE_END = re.compile(r"[^.;!?]*?[.;!?](?=\s+[А-ЯЁA-Z«\"„\d]|\s*$)")


def bind(flat, pos, page_loc=None, path_loc=None, path_zone=None, lookback=4, window=360, as_built=False,
         level_zone=None, roof=frozenset()):
    """Элементы для значения в позиции pos: (локации, привязка, фрагмент) или None.

    Привязка CLAUSE — элемент назван в том же предложении не дальше NEAR символов,
    открывает предложение прозы с классом (`_sentence_head`) или назван в заголовке,
    который продолжает «Характеристики бетона»; PAGE — элемент в таблице
    сразу после значения или назван без части здания, которая есть на листе; PATH — элемент
    из пути файла; SHEET — единственный элемент листа, только для страниц-доказательств.
    Значение, сказанное про несколько элементов через «и», относится ко всем.

    `level_zone` — часть здания по явным отметкам листа (`sheet_zone`): ею сужается значение,
    которое иначе ушло бы в обе части, потому что часть здания не названа нигде ближе.
    `roof` — что лист говорит о конструкциях кровли (`roof_context`): None — ничего не сужать,
    иначе типы элементов, которые лист называет только конструкциями кровли. Значение конструкции
    кровли, как и значение с такого листа, сужается до надземной части.
    """
    start = clause_bounds(flat, pos)
    not_structural = _NOT_STRUCTURAL_BUILT if as_built else _NOT_STRUCTURAL
    if not_structural.search(flat[max(start, pos - 90):pos]):
        return None
    # подпорная стена названа раньше, а значение — о её части: «Выравнивающая стенка – … В30»
    if retaining_passage(flat, pos):
        return None
    lo = max(start, pos - NEAR)
    # таблица «Ведомость расхода бетона / Марка конструкции»: элемент стоит после класса,
    # а выше — перечень листов, и ближайший элемент позади относится к другому листу
    if _TABLE_HEAD.search(flat[max(0, pos - 80):pos]):
        ahead = _ahead(flat, pos)
        if ahead:
            return [ahead], "PAGE", flat[max(0, pos - 60):pos + 160]
    mentions = _mentions(flat, lo, pos)
    cur, hops = start, 0
    # назад идём только через «Характеристики бетона:» и обрывки размеров, а не через штамп листа
    link = bool(_CONTINUES.search(flat[start:pos]))
    while not mentions and link and hops < lookback and pos - cur < window:
        prev = clause_bounds(flat, max(0, cur - 1))
        if prev >= cur:
            break
        piece = flat[prev:cur]
        if not_structural.search(piece):
            return None
        mentions = _mentions(flat, prev, cur)
        link = bool(_CONTINUES.search(piece) or _FRAGMENT.match(piece))
        cur, hops = prev, hops + 1
    if not mentions:
        # элемент дальше NEAR, но предложение прозы с классом начинается с него
        head = _sentence_head(flat, pos, not_structural)
        if head:
            mentions = [head]
            start = lo = cur = head[0]
    if mentions:
        locs, zones = [], {}
        for s, e, name, zoned in _conjunct(flat, mentions):
            zone = None
            if zoned:
                # часть здания ищется от предыдущего элемента предложения, а не на 60 знаков назад:
                # в «колонны подземной части В40, колонны надземной части В30» второй элемент
                # получал зону первого (#41, проверка вне корпуса)
                earlier = [m[1] for m in mentions if m[1] <= s]
                lo_zone = max(start, s - 60, max(earlier) if earlier else 0)
                for prev_class in _CLASS_RE.finditer(flat, lo_zone, s):
                    lo_zone = max(lo_zone, prev_class.end())     # зона первого элемента кончается на его классе
                zone = (zone_of(flat[lo_zone:min(pos, e + 80)]) or _heading_zone(flat, s, name)
                        or path_zone)
                zones[s] = zone
            loc = location_name(name, zone)
            if loc and loc not in locs:
                locs.append(loc)
        if locs:
            return locs, "CLAUSE", flat[min(lo, cur):pos + 25]
        # «для стен В60»: элемент назван, а часть здания — только на листе или в пути
        named = {m[2] for m in mentions}
        for loc, how in ((page_loc, "PAGE"), (path_loc, "PATH")):
            if loc and any(loc.startswith(n) for n in named):
                return [loc], how, flat[min(lo, cur):pos + 25]
        # часть здания не названа нигде: сказанное обо всех стенах или плитах относится к обеим,
        # если её не называют отметки листа и если это не конструкция кровли
        both = []
        for s, e, name, zoned in _conjunct(flat, mentions):
            zone = level_zone
            if zone is None and zoned and zones.get(s) != MIXED and _roof_value(flat, s, e, name, pos, roof):
                zone = ABOVEGROUND
            for loc in location_names(name, zone):
                if loc not in both:
                    both.append(loc)
        if both:
            return both, "CLAUSE", flat[min(lo, cur):pos + 25]
        return None
    ahead = _ahead(flat, pos)
    if ahead:
        return [ahead], "PAGE", flat[max(0, pos - 60):pos + 160]
    if path_loc:
        return [path_loc], "PATH", flat[max(0, pos - 80):pos + 25]
    if page_loc:
        # единственный элемент листа: на Алтуфьевском так к лестницам уходил класс из указаний
        # по анкеровке арматуры. Годится как страница-доказательство, но не как значение.
        return [page_loc], "SHEET", flat[max(0, pos - 80):pos + 25]
    return None


def _mentions(flat, lo, hi):
    """Элементы между lo и hi, кроме исключённых словом «кроме» и не несущих."""
    out = []
    for s, e, name, zoned in element_mentions(flat[lo:hi]):
        s, e = lo + s, lo + e
        before = flat[max(0, s - 40):s]
        if _EXCEPT.search(before) or _PREPOSITION.search(before) or _NOT_STRUCTURAL.search(flat[s:e]):
            continue
        out.append((s, e, name, zoned))
    return out


# Подпорная стена участка — не стена здания, рядом со значением её отбрасывает `_NOT_STRUCTURAL`. Но раздел
# о ней называет её в заголовке и первых предложениях, а дальше описывает по частям. ПД школы Полярная 25,
# КР, «6.2.12. Подпорные стены»: «Подпорная стена принята консольного типа из бурокасательных свай
# с устройством обвязочной балки по верху свай и парапетной стенки … С лицевой стороны ПС выполняется
# выравнивающая стенка…», а через шесть предложений — «Выравнивающая стенка – монолитная железобетонная
# толщиной 100мм бетона класса В30» и «Парапетная стенка – … В30». Подпорная стена стоит дальше 90 знаков
# от класса, и обе стенки становились стенами здания. Значению без элемента в предложении — то же: в «Основной
# материал подпорной стены - тяжёлый бетон класса по прочности В25» граница « - » отрезает подпорную стену
# от класса, и класс уходил единственному элементу листа — ростверку ограждения территории
_RETAINING = re.compile(r"подпорн\w+\s+стен\w*", re.I)
RETAINING_BACK = 1500     # на листах школы от класса стенки до названия подпорной стены — до 1 220 знаков
# Заголовок следующего раздела: «6.2.13. Ограждение территории СОШ», строка «2.1 Схема расположения котлована»
# таблицы изменений. Пункт с одним номером раздела не кончает: под заголовком «Конструктивные решения подпорной
# стены» так и идут её данные — «1. Материал железобетонных конструкций ПС, В25 F200 W8» (ПД ДОО, КР)
_SECTION = re.compile(r"(?:^|\s)\d{1,2}(?:\.\d{1,2}){1,3}\.?\s+(?=[А-ЯЁ])")
# предложение значения дочитывается и после класса: элементы бывают названы за ним — «В25, W6, F150 – фундамент,
# несущие конструкции подземной части…» (заключение экспертизы ДОО)
RETAINING_AHEAD = 80


def _bare_wall(text, s, e, name):
    """Упоминание [s, e) — стена или стенка без части здания: так подпорную стену называют по частям.
    Стена в грунте, колонны, пилоны и «каркасно-стеновая» система здания — другое."""
    if name != "Вертикальные конструкции" or not re.match(r"стен(?!ов)", text[s:e], re.I):
        return False
    return not zone_of(text[max(clause_bounds(text, s), s - 30):e + 40])


def retaining_passage(flat, pos):
    """Значение в pos сказано о подпорной стене участка, а не о здании.

    Подпорная стена названа раньше — в заголовке раздела или в предыдущих предложениях, не дальше
    RETAINING_BACK знаков, — и с тех пор до конца предложения значения текст не назвал ничего, кроме стен
    и стенок без части здания: это её части, «парапетная стенка», «выравнивающая стенка». Другой элемент
    (колонны, плита, стены подвала) или заголовок нового раздела — значит, текст перешёл к другому.
    Парапеты здания так не отбрасываются: перед ними подпорная стена не названа.
    """
    last = None
    for m in _RETAINING.finditer(flat, max(0, pos - RETAINING_BACK), pos):
        last = m
    if last is None:
        return False
    end = pos + RETAINING_AHEAD
    stop = _BOUNDARY.search(flat, pos, end)
    gap = flat[last.end():stop.start() if stop else end]
    if _SECTION.search(gap):
        return False
    return all(_bare_wall(gap, s, e, name) for s, e, name, _zoned in element_mentions(gap))


_JOIN = re.compile(r"^[\s,]*(?:и|а\s+также)?[\s,]*$", re.I)


def _conjunct(flat, mentions):
    """Последний элемент и те, что связаны с ним перечислением: «пилоны, колонны, стены»,
    «вертикальные конструкции и плита перекрытия»."""
    group = [mentions[-1]]
    for m in reversed(mentions[:-1]):
        if _JOIN.match(flat[m[1]:group[-1][0]]):
            group.append(m)
        else:
            break
    return list(reversed(group))


def _sentence_start(flat, pos):
    """Начало предложения со значением в pos — как у `clause_bounds`, но «(отм. -0,150)» и «п. 5.3»
    предложение не кончают. None — начала нет в HEAD_BACK знаках."""
    start = None
    for m in _BOUNDARY.finditer(flat, max(0, pos - HEAD_BACK), pos):
        if _ABBREV_END.search(flat, max(0, m.start() - 8), m.start()) and _NUMBER_START.match(flat, m.end()):
            continue
        start = m.end()
    return start


def _sentence_head(flat, pos, not_structural):
    """Элемент, который открывает предложение прозы с классом в pos: (начало, конец, тип, нужна ли зона) или None.

    NEAR ограничивает поиск элемента из-за таблиц: строки листа слиты в одну, и дальше 120 знаков стоит элемент
    соседней строки. Поэтому окно расширяется только для прозы: между элементом и классом нет ни другого
    элемента, ни класса, ни слова с заглавной буквы, а предложение кончается точкой не дальше NEAR знаков
    за классом. В таблице так не бывает: в спецификации КЖ6.1 Полярной 16 строка «Плита покрытия на отм. +77,590
    в осях В/7 10ГС1 ГОСТ 34028-2016 … Материал ГОСТ 26633-2015 Бетон В30 W6 F150, м³ 0,8» идёт за шапкой
    «… Масса ед., кг Примеч.», слова «Материал» и «Бетон» — ячейки, а точки за классом нет.
    """
    start = _sentence_start(flat, pos)
    if start is None:
        return None
    s = _LEAD.match(flat, start, pos).end()
    found = element_mentions(flat[s:pos])
    if len(found) != 1 or found[0][0] != 0:
        return None
    _, length, name, zoned = found[0]
    e = s + length
    if (_NOT_STRUCTURAL.search(flat[s:e]) or not_structural.search(flat[start:pos])
            or _CLASS_RE.search(flat, e, pos) or _TITLE_WORD.search(flat, e, pos)):
        return None
    value = _CLASS_RE.match(flat, pos)
    after = value.end() if value else pos
    end = _PROSE_END.match(flat, after)
    if not end or end.end() - pos > NEAR or _CLASS_RE.search(flat, after, end.end()):
        return None
    return s, e, name, zoned


def _roof_value(flat, s, e, name, pos, roof):
    """Значение в pos у элемента [s, e) — о конструкции кровли: элемент назван ею («плиты покрытия
    вентшахт») или лист называет такие элементы только конструкциями кровли (`roof_context`). Не так,
    если в предложении элемента названы подземная часть, автостоянка, паркинг или стилобат."""
    if roof is None or not (name in roof or roof_element(flat, s, e)):
        return False
    lo = max(clause_bounds(flat, s), s - 60)
    hi = pos + 25
    stop = _BOUNDARY.search(flat, pos, hi)
    if stop:
        hi = stop.start()
    return not _UNDER_ROOF.search(flat, lo, hi)


def _heading_zone(flat, s, name, back=250):
    """Зона из заголовка того же элемента чуть выше: «Плита перекрытия над -1 подземным
    этажом. Толщина плиты перекрытия …: 250, 900 мм. Характеристики бетона: B35»."""
    lo = max(0, s - back)
    for hs, he, hname, _ in reversed(element_mentions(flat[lo:s])):
        if hname != name:
            continue
        zone = zone_of(flat[lo + hs:lo + he + 60])
        if zone:
            return zone
    return None


def _ahead(flat, pos, window=160):
    """Элемент сразу после значения в таблице листа: «Марка конструкции B60, F150, W8 …
    Ж/б стены на отм.-13.750». Только с зоной и без другого класса по дороге."""
    tail = flat[pos:pos + window]
    first = _CLASS_RE.search(tail)
    nxt = _CLASS_RE.search(tail, first.end()) if first else None
    if nxt:
        tail = tail[:nxt.start()]
    for s, e, name, zoned in element_mentions(tail):
        if (_NOT_STRUCTURAL.search(tail[max(0, s - 30):e + 10]) or _EXCEPT.search(tail[max(0, s - 25):s])
                or _PREPOSITION.search(tail[max(0, s - 40):s])):
            continue
        zone = zone_of(tail[s:e + 40]) if zoned else None
        loc = location_name(name, zone)
        if loc:
            return loc
    return None


def page_location(flat):
    """Элемент страницы, если на ней назван ровно один (с зоной для стен и плит)."""
    names = set()
    for s, e, name, zoned in element_mentions(flat):
        if (_EXCEPT.search(flat[max(0, s - 25):s]) or _PREPOSITION.search(flat[max(0, s - 40):s])
                or _NOT_STRUCTURAL.search(flat[max(0, s - 30):e + 10])):
            continue
        zone = zone_of(flat[s:e + 40]) if zoned else None
        loc = location_name(name, zone)
        if loc:
            names.add(loc)
    return names.pop() if len(names) == 1 else None


def path_context(relative_path):
    """Элемент и зона из пути файла. Папки РД Речникова названы по элементам и этажам:
    «1. Подземная автостоянка/4. КЖ2.1 Вертикальные конструкции -1 этажа. Парковка»."""
    parts = re.split(r"[\\/]+", relative_path or "")
    text = " ".join(parts[-3:-1] + [re.sub(r"\.\w+$", "", parts[-1])]) if parts else ""
    zone = zone_of(text)
    if _PIT_WALL_PATH.search(text):
        return "Стена в грунте", zone
    names = set()
    for s, e, name, zoned in element_mentions(text):
        if _NOT_STRUCTURAL.search(text[max(0, s - 30):e + 10]):
            continue
        loc = location_name(name, zone if zoned else None)
        if loc is None:
            return None, zone
        names.add(loc)
    return (names.pop() if len(names) == 1 else None), zone


# ---------- извлечение ----------

def _not_structural_near(flat, s, e, width=60, as_built=False):
    """Слово не несущей конструкции рядом со значением, в пределах его предложения:
    «Бетон кл. B10 (бетонная подготовка)», «B30 … Фундамент монолитный под кран»."""
    not_structural = _NOT_STRUCTURAL_BUILT if as_built else _NOT_STRUCTURAL
    lo = max(clause_bounds(flat, s), s - width)
    after = flat[e:e + width]
    stop = _BOUNDARY.search(after)
    if stop:
        after = after[:stop.start()]
    return bool(not_structural.search(flat[lo:s]) or not_structural.search(after))


def concrete_classes(flat, relative_path="", as_built=False):
    """Пары «элемент — класс бетона» на странице.

    `as_built` — страница исполнительной документации: марка смеси «БСТ В25» из документа
    о качестве — класс построенного, а не строка спецификации (#42).
    """
    path_loc, path_zone = path_context(relative_path)
    page_loc = level_zone = roof = None
    out = []
    for s, e, number in class_mentions(flat):
        if number < MIN_STRUCTURAL_CLASS:
            continue
        if _not_structural_near(flat, s, e, as_built=as_built):
            continue
        if page_loc is None:
            page_loc = page_location(flat) or ""
            # отметки листа — только в исполнительной документации: исполнительная схема снята
            # с одного уровня или с одинаковых этажей, а лист проекта и рабочей стадии бывает
            # сводным по всей высоте
            level_zone = sheet_zone(flat) if as_built else None
            roof = roof_context(flat)
        got = bind(flat, s, page_loc or None, path_loc, path_zone, as_built=as_built, level_zone=level_zone,
                   roof=roof)
        if not got:
            continue
        locs, how, snippet = got
        for loc in locs:
            out.append({"location": loc, "binding": how, "value": number,
                        "raw": class_label(number), "snippet": " ".join(snippet.split())[-220:]})
    return out


# Плитный ростверк — та же фундаментная плита: каталог так и называет параметр, «толщина фундаментной плиты /
# ростверка». Том КЖ пишет «Ростверк пристроенной автостоянки представляет собой монолитную железобетонную
# плиту толщиной 500мм»; без этой формы у Полярной 17 толщину РД давала сноска тома дренажа (#229)
_PLATE_THICKNESS = re.compile(
    r"(?:фундаментн\w*\s+плит\w*|плит\w*\s+фундамент\w*|фундамент\w*[^.;]{0,60}?плит\w*"
    r"|(?<![а-яё])ростверк\w*[^.;]{0,90}?плит\w*)"
    r"[^.;]{0,90}?(?:толщин\w*|\bh\s*=|\bt\s*=)\s*(?:[–—:-]\s*)?(\d{3,4})"
    r"|толщин\w*\s+(?:монолитн\w+\s+)?(?:железобетонн\w+\s+)?фундаментн\w*\s+плит\w*[^.;]{0,60}?(\d{3,4})",
    re.I)
_MORE_MM = re.compile(r"(\d{3,4})\s*(?:мм|mm)|(?:и|,|/)\s*(\d{3,4})(?=\s*(?:мм|mm|\s*\(|\s*$|[,.;]))", re.I)
# «приямок» — с беглым «о»: основа «приямк» ловит «приямка» и «приямков», но не «приямок»
_LOCAL_THICKENING = re.compile(r"уширени\w*|утолщени\w*|капител\w*|приям(?:ок|к)\w*|под\s+(?:колонн|пилон)\w*|лифт\w*"
                               r"|подготовк\w*", re.I)


# Толщина плиты перекрытия и покрытия: те же формы записи, что у фундаментной плиты, но
# свой элемент и свой диапазон. Диапазон обязателен: фильтр фундаментной плиты (300–3000)
# выбрасывает перекрытие 200 мм, а её диапазон, применённый к перекрытию, впустил бы
# толщину стены и размер проёма (#92)
_NO_BREAK = r"(?:(?!\.\s+[А-ЯЁ])[^;])"       # любой знак, кроме конца предложения и точки с запятой
_SLAB_THICKNESS = re.compile(
    r"(?:плит\w*\s+(?:перекрыти|покрыти)\w*|(?:перекрыти|покрыти)\w+\s+(?:над|под)\b" + _NO_BREAK + r"{0,40})"
    + _NO_BREAK + r"{0,90}?(?:толщин\w*|\bh\s*=|\bt\s*=)\s*(?:[–—:-]\s*)?(\d{2,4})"
    r"|толщин\w*\s+(?:монолитн\w+\s+)?(?:железобетонн\w+\s+)?плит\w*\s+(?:перекрыти|покрыти)\w*"
    + _NO_BREAK + r"{0,60}?(\d{2,4})",
    re.I)
SLAB_RANGE = (150, 500)          # диск перекрытия: тоньше 150 мм не бывает, толще 500 — это уже плита-стена
FOUNDATION_RANGE = (300, 3000)
ZONE_BACK = 260                  # часть здания ищется в этом окне слева: «перекрытие над -1 этажом»


# Строка журнала изменений листа: «Откорректировано положение границы между плитами
# толщиной 900мм и 250 мм». Это запись о правке, а не проектное решение о конструкции,
# и на Речникове из неё получалось ложное понижение (#92)
_REVISION_NOTE = re.compile(r"откорректирован\w*|скорректирован\w*|измен[её]н\w*|замен[её]н\w*"
                            r"|добавлен\w*|исключ[её]н\w*|аннулирован\w*|перечень\s+изменени\w*", re.I)
REVISION_BACK = 120


def _thickness_rows(flat, pattern, low, high, strict_tail=False, local_head=False):
    """Толщины по шаблону: [(числа, фрагмент, начало совпадения)].

    `local_head` — строка, где между названием элемента и первым числом стоит местный элемент
    («Фундаментная плита приямок, h=600 мм» в томе ДР Новослободской), не берётся целиком: это
    толщина приямка, уширения или плиты под лифтом, а не плиты. Раньше `_LOCAL_THICKENING`
    отсекал такие слова только перед числами хвоста.

    `strict_tail` — не брать из хвоста числа внутри скобок и дробные части чисел. На листах
    перекрытий за толщиной идёт таблица нагрузок и отметок («толщиной 250мм 2 1,46 (149)
    2,352 (240)», «на отм. +4,400 … +73,400»), и разбор хвоста приносил из неё 352 и 400
    как толщины: на Полярной-16 из этого получалось ложное понижение.
    """
    out = []
    for m in pattern.finditer(flat):
        if _NOT_STRUCTURAL.search(flat[max(0, m.start() - 20):m.start() + 20]):
            continue
        if strict_tail and _REVISION_NOTE.search(flat[max(0, m.start() - REVISION_BACK):m.start()]):
            continue
        if local_head and _LOCAL_THICKENING.search(m.group(0)):
            continue
        first = int(m.group(1) or m.group(2))
        values = {first}
        end = m.end()
        tail = flat[end:end + 120]
        stop = re.search(r"\.\s+[А-ЯЁ]|;|толщин|\b[ht]\s*=", tail, re.I)
        tail = tail[:stop.start()] if stop else tail
        other = element_mentions(tail)
        if other:
            tail = tail[:other[0][0]]
        for mm in _MORE_MM.finditer(tail):
            if _LOCAL_THICKENING.search(tail[max(0, mm.start() - 30):mm.start()]):
                break
            num_start = mm.start(1) if mm.group(1) else mm.start(2)
            before = tail[:num_start]
            if strict_tail:
                if before.count("(") > before.count(")"):
                    continue          # число внутри скобок — нагрузка или ссылка, а не толщина
                if re.search(r"\d[.,]$", before):
                    # дробная часть числа: «2,352 (240)» — нагрузка, «+73,400» — отметка.
                    # Разделитель без пробела; перечисление «350, 250, 200 мм» так не отбрасывается
                    continue
            values.add(int(mm.group(1) or mm.group(2)))
        values = {v for v in values if low <= v <= high}
        if values:
            out.append((sorted(values), flat[max(0, m.start() - 20):end + len(tail)].strip(), m.start()))
    return out


# Распределительный ростверк — отдельный элемент (#136), его толщина — не толщина плиты
_DISTRIBUTION = re.compile(r"распределительн\w*\s+$", re.I)


def plate_thickness(flat):
    """Толщины фундаментной плиты в миллиметрах на странице: [(числа, фрагмент)]."""
    return [(values, snippet) for values, snippet, pos
            in _thickness_rows(flat, _PLATE_THICKNESS, *FOUNDATION_RANGE, local_head=True)
            if not _DISTRIBUTION.search(flat[max(0, pos - 30):pos])]


# Обозначение толщины на чертеже: «t=180», «h=250». Это подпись участка схемы армирования,
# а не проектное решение об элементе: на одном листе участков несколько, и наименьший из них
# сам по себе понижением не является. Проза («плита перекрытия толщиной 200 мм») — решение
_SHEET_MARK = re.compile(r"\b[ht]\s*=\s*\d", re.I)


def slab_thickness(flat):
    """Толщины плит перекрытия и покрытия: [(числа, фрагмент, зона, форма записи)]. Задача #92.

    Форма записи — «prose» (сказано словами) или «mark» (обозначение участка листа, «t=180»).
    От неё зависит крепость привязки: по подписи участка вердикт не выдаётся.

    Зона — часть здания, названная рядом («перекрытие над подземной автостоянкой»,
    «плита покрытия на отм. +19,800»). Без зоны значение не выбрасывается: сказанное
    о перекрытиях без части здания относится к обеим, и локации даёт `location_names` —
    так же, как у класса бетона (#52). Иначе на объекте, где проектная стадия описывает
    перекрытия целиком, сравнивать было бы не с чем.
    """
    out = []
    for values, snippet, pos in _thickness_rows(flat, _SLAB_THICKNESS, *SLAB_RANGE, strict_tail=True):
        zone = zone_of(flat[slice(*_zone_window(flat, pos))])
        form = "mark" if _SHEET_MARK.search(snippet) else "prose"
        out.append((values, snippet, zone, form))
    return out


def _zone_window(flat, pos, ahead=120):
    """Границы окна, в котором ищется часть здания: своё предложение и немного вперёд.

    `clause_bounds` берётся от pos + 1: он ищет границу в полуинтервале до pos, и граница,
    стоящая ровно на pos (значение — первое слово предложения), иначе не находится, а окно
    уезжает в предыдущую фразу. Так «перекрытие над подземной автостоянкой» делало подземным
    и следующее перекрытие.
    """
    left = clause_bounds(flat, min(len(flat), pos + 1))
    stop = re.search(r"[.;]\s+[А-ЯЁA-Z]", flat[pos:pos + ahead])
    right = pos + (stop.start() if stop else ahead)
    return max(left, pos - ZONE_BACK), right
