"""Диаметры стояков водопровода и горячей воды по номерам. Пятая очередь Матрицы, #29.

На планах ИОС2 и ВК Алтуфьевского стояк подписан одинаково в обеих стадиях:
«Ст В1-1 ⌀32х3», «Ст Т3-3 ⌀25х2.3». Номер стояка — ключ сравнения, как номер
группы у схем ВРУ. Подписи участков магистралей без номера («В1-⌀40х3.5») не
сравниваются: без номера не сказать, какой участок какому соответствует.

Стояк — один элемент, поэтому любой диаметр в РД меньше проектного наибольшего —
уменьшение, в отличие от толщины фундаментной плиты, где новое значение может
относиться к другой части здания.
"""
import re

SYSTEMS = ("В1", "В2", "Т3", "Т4")
RISER = re.compile(r"Ст\.?\s*(В1|В2|Т3|Т4)\s?-\s?(\d{1,3})\s+[⌀ØФ∅]\s?(\d{2,3})(?:\s?[хx×]\s?(\d{1,2}(?:[,.]\d)?))?")


def riser_labels(flat):
    """Подписи стояков на странице: номер, наружный диаметр, подпись как напечатано."""
    out = []
    for m in RISER.finditer(flat):
        wall = f"х{m.group(4)}" if m.group(4) else ""
        out.append({"riser": f"Ст {m.group(1)}-{m.group(2)}", "diameter": int(m.group(3)),
                    "raw": f"⌀{m.group(3)}{wall}",
                    "snippet": " ".join(flat[max(0, m.start() - 60):m.end() + 40].split())})
    return out


def reductions(pd, rd):
    """Стояки, у которых в РД есть диаметр меньше проектного наибольшего.

    pd, rd: номер стояка → набор диаметров. Возвращает [(номер, диаметры ПД, диаметры РД)].
    """
    out = []
    for riser in sorted(set(pd) & set(rd), key=_key):
        smaller = [d for d in rd[riser] - pd[riser] if d < max(pd[riser])]
        if smaller:
            out.append((riser, sorted(pd[riser]), sorted(rd[riser])))
    return out


def _key(riser):
    return [int(x) if x.isdigit() else x for x in re.split(r"(\d+)", riser)]
