"""Приборы учёта энергоресурсов по видам: электроэнергия, вода, тепло. Четвёртая очередь, ZU-129, #28.

Триггер каталога — отсутствие в РД счётчиков. По тексту отсутствие не доказывается: прибор бывает
только на схеме без текстового слоя или в другом томе («общий водомерный узел с водосчетчиком
(см. проект наружных сетей водоснабжения)» у Речникова). Поэтому правило подтверждает наличие:
учёт вида ресурса, названный в проекте, найден в рабочей стадии — нарушения нет; не найден —
сравнение невозможно с объяснением, есть ли вообще рабочая документация этого раздела.

Засчитываются только упоминания прибора: «счетчик Энергомера CE308», «водомерный узел»,
«Счетчик крыльчатый ВСХ-40», «теплосчетчик», «узел учета тепловой энергии». Общие слова договора
водоснабжения «приборы учета (узлы учета) холодной воды» в РД Тюменской-5 и Алтуфьевского
не засчитываются.
"""
import re

RESOURCES = (
    ("электроэнергия", "EOM", re.compile(
        r"сч[её]тчик\w*\s+(?:активн\w+\s+)?(?:(?:электрическ\w+\s+)?энерги|электроэнерги)\w*|электросч[её]тчик\w*"
        r"|Энергомера|Меркурий[\s-]?\d{3}|(?<![\w.])[CС][EЕ]\s?30[1-8](?!\d)"
        r"|уч[её]т\w*\s+(?:активной\s+)?электр\w*\s*энерги\w*", re.I)),
    ("вода", "VK", re.compile(
        r"водомерн\w+\s+узл?\w*|водосч[её]тчик\w*|сч[её]тчик\w*\s+(?:крыльчат\w+\s+)?(?:холодной\s+|горячей\s+)?воды"
        r"|расходомер[\s-]сч[её]тчик\w*|сч[её]тчик\w*\s+крыльчат\w*|(?<![\w-])ВС[ХГЭ]Д?-\s?\d{2,3}(?!\d)|(?<![\w-])ВСКМ",
        re.I)),
    ("тепловая энергия", "OV", re.compile(
        r"теплосч[её]тчик\w*|узл?\w*\s+уч[её]та\s+тепловой\s+энергии|(?<![\w.])УУТЭ(?![\w])|(?<![\w.])ВИС\.Т", re.I)),
)
SECTIONS = {name: section for name, section, _ in RESOURCES}
SECTION_NAMES = {"EOM": "ЭОМ", "VK": "ВК", "OV": "ОВ"}


def meters(flat):
    """Упоминания приборов учёта на странице: [{key, value, raw, snippet}]."""
    out = []
    for name, _section, rx in RESOURCES:
        for m in rx.finditer(flat):
            out.append({"key": name, "value": name, "raw": m.group(0),
                        "snippet": " ".join(flat[max(0, m.start() - 70):m.end() + 50].split())})
    return out


def decide(resource, in_pd, in_rd, rd_has_section):
    """Решение по одному виду ресурса. Возвращает (метка, тип, пояснение) или (None, None, …)."""
    if not in_pd and not in_rd:
        return None, None, f"учёт ({resource}) не назван ни в одной стадии"
    if not in_pd:
        return "NO_VIOLATION", "NON_TRIGGERING_DIFFERENCE_NO_DECREASE", \
            f"учёт ({resource}) назван в рабочей стадии, в проекте в тексте не найден"
    if in_rd:
        return "NO_VIOLATION", "EQUAL_PD_RD", f"учёт ({resource}) назван в обеих стадиях"
    if rd_has_section:
        return "COMPARISON_IMPOSSIBLE", None, (
            f"учёт ({resource}) в проекте назван, в тексте рабочей документации раздела не найден; "
            f"прибор мог остаться на схеме без текстового слоя или в другом томе")
    return "COMPARISON_IMPOSSIBLE", None, (
        f"учёт ({resource}) в проекте назван, рабочей документации раздела {SECTION_NAMES[SECTIONS[resource]]} в комплекте нет")
