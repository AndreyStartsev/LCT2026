"""Деформационные швы здания: наличие, ширина и материал заполнения, ПД против РД (KR-063, #192).

Решения специалиста (R3-KR-063):
- узла шва может не быть, но указание — в записке или примечании; если узел дан, сравниваются
  материал заполнения и ширина;
- для вывода «шва нет в РД» достаточно схем плиты и вертикальных конструкций.

Шов ищется в томах КР обеих стадий: подпись на плане («Деформационный шов t=30мм», «30мм
Деформационный шов», «д.ш. — деформационный шов» в условных обозначениях), фраза записки
(«секция отделена от остальной части здания деформационным швом 50 мм», «блоки … разделены
деформационным швом шириной 100 мм»), примечание о заполнении («Заполнение деформационного шва
производить экструзионным пенополистиролом CARBON PROF»).

Не шов здания: швы в стяжке и в полу («нарезать деформационные швы … с шагом»), в отмостке и
тротуарах, на кровле и фасаде; рабочий шов бетонирования; нормы и общие фразы («необходимость или
отсутствие … деформационных швов», «расстояние между деформационными швами»). Прицельного вопроса
модели здесь нет: подписи шва на схемах плиты и стен открытых объектов лежат в текстовом слое.
"""
import re

JOINT = re.compile(r"(?:деформационн|температурн|осадочн)\w*\s+(?:шв\w*|шов)", re.I)
LEGEND = re.compile(r"д\.\s?ш\.\s*[-–—]?\s*деформационн\w+\s+шов", re.I)
# ширина: «шов 50 мм», «шов t=30мм», «шириной 100 мм» за словом или «30мм Деформационный шов» перед ним
WIDTH_AFTER = re.compile(r"^\s*(?:шириной\s+|t\s*=\s*)?(?P<w>\d{2,3})\s*мм", re.I)
WIDTH_BEFORE = re.compile(r"(?<![\d.,])(?P<w>\d{2,3})\s*мм\s*$", re.I)
NOT_BUILDING = re.compile(r"стяжк|(?<![а-яё])пол(?:а|у|ы|ов|ах)?(?![а-яё])|отмостк|тротуар|асфальт|с\s+шагом|нарез|"
                          r"кровл|покрыти\w+\s+пол|облицовк|фасад|витраж|проезд|благоустр|кабел|лотк|трубопровод|"
                          r"рабоч\w+\s+шов", re.I)
NORM = re.compile(r"необходимост|отсутстви|расстояни\w*\s+между|допуска\w*|следует|не\s+требуется|не\s+менее|"
                  r"(?<![А-ЯЁа-яё])СП\s*\d", re.I)
MATERIALS = (("герметик", r"герметик"), ("гидрошпонка", r"гидрошпонк|ультрабанд"),
             ("пенополистирол", r"пенополистирол|пеноплэкс|carbon\s+(?:prof|solid)|xps"),
             ("пенополиэтилен", r"пенополиэтилен|вилатерм|шнур"), ("минеральная вата", r"минерал\w*\s+ват|минват"),
             ("лента НЕОДИЛ", r"неодил"))
MATERIAL_RE = [(name, re.compile(p, re.I)) for name, p in MATERIALS]
# схемы плиты и вертикальных конструкций: на них отсутствие шва уже вывод (решение специалиста)
SCHEME = re.compile(r"(?:план|схем\w*)\s+(?:\S+\s+){0,3}?(?:фундаментн\w+\s+плит|плит\w*\s+(?:перекрыти|покрыти|на\s+отм)"
                    r"|вертикальн\w+\s+(?:конструкц|несущ)|стен\s+и\s+(?:колонн|пилонов)|опалубк\w*\s+(?:плит|стен))",
                    re.I)
JOINT_KEY = "деформационный шов"


def _snippet(flat, start, end, before=90, after=90):
    return " ".join(flat[max(0, start - before):end + after].split())


def statements(flat):
    """Упоминания шва здания на странице: [{key, value: ширина мм или None, materials, raw, snippet}]."""
    out = []
    for m in JOINT.finditer(flat):
        before, after = flat[max(0, m.start() - 80):m.start()], flat[m.end():m.end() + 80]
        if NOT_BUILDING.search(before[-50:] + " " + after[:60]) or NORM.search(before[-60:]):
            continue
        w = WIDTH_AFTER.search(after) or WIDTH_BEFORE.search(before)
        width = float(w.group("w")) if w else None
        if width is not None and not 10 <= width <= 300:
            width = None
        around = flat[max(0, m.start() - 120):m.end() + 160]
        materials = sorted({name for name, rx in MATERIAL_RE if rx.search(around)})
        raw = " ".join(flat[max(0, m.start() - (len(w.group(0)) if w and w.re is WIDTH_BEFORE else 0)):
                            m.end() + (w.end() if w and w.re is WIDTH_AFTER else 0)].split())
        out.append({"key": JOINT_KEY, "value": width, "materials": materials, "raw": raw,
                    "snippet": _snippet(flat, m.start(), m.end())})
    return out


def schemes(flat):
    """Лист — схема плиты или вертикальных конструкций: название листа или None."""
    m = SCHEME.search(flat)
    return " ".join(m.group(0).split()) if m else None


def show_widths(widths):
    return ", ".join(f"{w:g} мм" for w in sorted(widths))
