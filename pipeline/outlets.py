"""Диаметры выпусков канализации из здания по номерам. IOS3-074, #145.

Выпуск подписан на плане подвала и на схеме одинаково в обеих стадиях: «Выпуск К1.1-1 ∅150»
(ИОС3 Полярной 16), «Выпуск К2-3 | ∅150» (ВК1 Речникова), без номера — «Выпуск К2 Ø250»
(Алтуфьевское, обе стадии). Ключ сравнения — обозначение выпуска как напечатано: система и
номер. Выпуск без номера — свой ключ, «К2», и с «К2-3» не сопоставляется: специалист велел
сравнивать только одинаково обозначенные значения (Р-91, п. 3). По той же причине наружный
диаметр полимерной трубы к условному не приводится: «⌀110» и «⌀100» — разные числа.

В параметр входят бытовая К1 (с подсистемами К1.1, К1.2) и внутренний водосток К2 — так
назван параметр в Матрице. Выпуски К3, К4, К11, К13 не сравниваются.

Четвёртый круг (R4-Q-IOS3-074, Р-108): если в одной стадии выпуски системы без номеров, а в другой
с номерами (Речников, Алтуфьевское П-2025), наименьший диаметр системы не сравнивается — запись
идёт инспектору (`numbering_mismatch`, needs_expert). Магистрали внутри здания специалист тоже
включил в параметр; их подписи («К1.2-⌀110») пока не разбираются.

Подписи участков магистралей («К1.2-⌀110») и диаметры тех же выпусков на планах заземления
ЭОМ и ЭН не источник: там выпуск подписан наружным диаметром трубы. Разделы отбирает правило
(поле `documents`), а не этот разбор.
"""
import re

# «Выпуск К1.1-1 ∅150», «Выпуски К2-3 | ⌀150», «Выпуск К2 Ø250». Система — К1 или К2 с подсистемой:
# «К13» и «К11» сюда не попадают (за цифрой системы не может идти ещё цифра)
OUTLET = re.compile(r"Выпуск\w*\s*\|?\s*[КK]\s?([12](?:\.\d)?)(?![\d.])(?:\s*-\s*(\d{1,2}))?"
                    r"\s*\|?\s*[Ø∅⌀]\s*(\d{2,3})(?![\d,.])")


def outlet_labels(flat):
    """Подписи выпусков на странице: обозначение, диаметр, подпись как напечатано."""
    out = []
    for m in OUTLET.finditer(flat):
        name = f"К{m.group(1)}" + (f"-{m.group(2)}" if m.group(2) else "")
        out.append({"outlet": name, "diameter": int(m.group(3)), "raw": f"⌀{m.group(3)}",
                    "snippet": " ".join(flat[max(0, m.start() - 40):m.end() + 40].split())})
    return out


def numbering_mismatch(pd_keys, rd_keys):
    """Системы, у которых выпуски в одной стадии без номера, а в другой с номерами: [(система, ПД, РД)].

    «К2» в проекте и «К2-1», «К2-3» в рабочей стадии не сопоставляются (Р-91, п. 3), и сравнивать
    их наименьшим диаметром системы специалист не велел: сопоставляет инспектор (R4-Q-IOS3-074).
    """
    def system(key):
        return key.split("-")[0]

    out = []
    for name in sorted({system(k) for k in list(pd_keys) + list(rd_keys)}):
        pd = sorted(k for k in pd_keys if system(k) == name)
        rd = sorted(k for k in rd_keys if system(k) == name)
        if not pd or not rd or set(pd) & set(rd):
            continue
        if any("-" not in k for k in pd) != any("-" not in k for k in rd):
            out.append((name, pd, rd))
    return out
